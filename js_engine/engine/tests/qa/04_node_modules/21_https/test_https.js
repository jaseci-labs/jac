// HTTPS module — local TLS smoke (no internet)
var https = require("https");
var fs = require("fs");
var path = require("path");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/21_https/test_https.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

assertEq(typeof https.createServer, "function", "createServer");
assertEq(typeof https.request, "function", "request");
assertEq(typeof https.get, "function", "get");
assertEq(typeof https.Agent, "function", "Agent");
assert(https.globalAgent instanceof https.Agent, "globalAgent is https.Agent");
assert(https.globalAgent.keepAlive === true, "globalAgent keepAlive default true");

var certDir = path.join(__dirname, "../../../e2e");
var keyFile = path.join(certDir, "test_key.pem");
var certFile = path.join(certDir, "test_cert.pem");

// Node expects PEM contents; js_engine native TLS reads cert/key from file paths.
var runner = process.env.JAC_JS_RUNNER || "";
var onJacEngine = runner.indexOf("js_engine") !== -1;
var tlsServerOpts = onJacEngine
    ? { key: keyFile, cert: certFile }
    : { key: fs.readFileSync(keyFile), cert: fs.readFileSync(certFile) };

var server = https.createServer(tlsServerOpts, function(req, res) {
    res.writeHead(200, { "Content-Type": "text/plain" });
    res.end("tls-ok");
});

server.on("error", function(e) {
    console.error("FAIL: https server error: " + e.message);
    __reg.bump();
    __jacDone();
});

server.listen(0, "127.0.0.1", function() {
    var port = server.address().port;
    var opts = {
        hostname: "127.0.0.1",
        port: port,
        path: "/",
        method: "GET",
        rejectUnauthorized: false,
        agent: false
    };
    var req = https.request(opts, function(res) {
        assertEq(res.statusCode, 200, "status 200");
        var body = "";
        res.on("data", function(c) { body += c; });
        res.on("end", function() {
            assertEq(body, "tls-ok", "tls body");
            server.close(function() { __jacDone(); });
        });
    });
    req.on("error", function(err) {
        console.error("FAIL: https request error: " + err.message);
        server.close();
        __reg.bump();
        __jacDone();
    });
    req.end();
});

setTimeout(function() {
    console.error("FAIL: test_https timeout");
    server.close();
    __reg.bump();
    __jacDone();
}, 10000);
