// ZLIB-001: gzipSync/deflateSync must actually COMPRESS Buffer/Uint8Array input,
// not emit an empty ~20-byte stream. Two regressions combined here:
//  - the __zlib compress dispatch truncated the 64-bit input pointer via
//    jsv_to_int32 (int(jsv_to_double) needed), and
//  - a TypedArray/Buffer `.length` accessor reached the bridge as a value that
//    failed both the i32 and double type checks (avail_in read as 0), so
//    gzipSync(Buffer) produced empty output. `_bufCopyIn` now does `length | 0`.
// This surfaced as a crash in vite's reportCompressedSize (the gzip size report).
//
// Scope: this pins COMPRESSION (the fix + the vite-critical path). Decompressing
// arbitrary BINARY with embedded NULs is a separate known gap (inflate output
// currently flows through a NUL-truncating str), so roundtrips here use text.
var zlib = require("zlib");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/28_zlib/test_zlib_gzip_buffer.js");
var __jacOrigExit = process.exit.bind(process);
function assert(cond, msg) { __reg.assert(cond, msg); }

// Highly-compressible binary content of a known size — a broken (empty) deflate
// yields exactly 20 bytes for gzip / 8 for zlib regardless of input, so any
// output materially larger than the header proves real compression happened,
// and being SMALLER than the input proves the body was actually deflated.
[64, 753, 4096].forEach(function (sz) {
    var data = Buffer.alloc(sz); // zero-filled → compresses far below `sz`

    var gzB = zlib.gzipSync(data);
    assert(gzB.length > 18, "ZLIB-001: gzipSync(Buffer[" + sz + "]) is not an empty stream (" + gzB.length + ")");
    assert(gzB.length < sz, "ZLIB-001: gzipSync(Buffer[" + sz + "]) actually compressed the body (" + gzB.length + " < " + sz + ")");

    // Uint8Array goes through the same _bufCopyIn / dispatch path.
    var gzU = zlib.gzipSync(new Uint8Array(sz));
    assert(gzU.length > 18 && gzU.length < sz, "ZLIB-001: gzipSync(Uint8Array[" + sz + "]) compressed");

    // deflateSync (zlib wrapper) — same fix path.
    var df = zlib.deflateSync(data);
    assert(df.length > 8 && df.length < sz, "ZLIB-001: deflateSync(Buffer[" + sz + "]) compressed");
});

// Text (ASCII, no NULs) roundtrips fully through gzip AND deflate.
var s = "Hello World! ".repeat(64);
var gzS = zlib.gzipSync(s);
assert(gzS.length > 18 && gzS.length < s.length, "ZLIB-001: gzipSync(string) compressed");
assert(zlib.gunzipSync(gzS).toString() === s, "ZLIB-001: gzip text roundtrip");
assert(zlib.inflateSync(zlib.deflateSync(s)).toString() === s, "ZLIB-001: deflate text roundtrip");

__reg.finalize(__jacOrigExit);
