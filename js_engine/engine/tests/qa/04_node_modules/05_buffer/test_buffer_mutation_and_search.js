// testing_plans/08_buffer_and_encoding/NODE_BUFFER_COMPREHENSIVE_TEST_PLAN.md — ECG-3 (mutation + search + compare)
// Scenario IDs: NBUF-U-*, NBUF-S-*

var Buffer = require("buffer").Buffer;

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/05_buffer/test_buffer_mutation_and_search.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }
function assertOk(cond, msg) { __reg.assert(cond, msg); }

// NBUF-U-001 — slice/subarray share underlying storage with parent (mutate child affects parent)
var u1 = Buffer.from([1, 2, 3, 4, 5]);
var sl = u1.slice(1, 4);
sl[0] = 99;
assertEq(u1[1], 99, "NBUF-U-001: slice mutation visible in parent");
var u1b = Buffer.from([1, 2, 3, 4, 5]);
var su = u1b.subarray(1, 4);
su[0] = 88;
assertEq(u1b[1], 88, "NBUF-U-001: subarray mutation visible in parent");

// NBUF-U-002 copy with offsets
var src = Buffer.from("ABCDE");
var dst = Buffer.alloc(5);
var copied = src.copy(dst, 0, 1, 4);
assertEq(copied, 3, "NBUF-U-002: copy returns byte count");
assertEq(dst.toString("utf8", 0, 3), "BCD", "NBUF-U-002: copy range into target");

// NBUF-U-003 overlapping self-copy
var self = Buffer.from([1, 2, 3, 4, 5]);
self.copy(self, 0, 1, 4);
assertEq(self.join(","), "2,3,4,4,5", "NBUF-U-003: self-copy overlap semantics");

// NBUF-U-004 fill
var f1 = Buffer.alloc(5);
f1.fill(0x41);
assertEq(f1.toString("utf8"), "AAAAA", "NBUF-U-004: fill numeric");
var f2 = Buffer.alloc(6);
f2.fill("ab", 0, 6, "utf8");
assertEq(f2.toString("utf8"), "ababab", "NBUF-U-004: fill string pattern");

// NBUF-S-001 indexOf
var ix = Buffer.from("hello world hello");
assertEq(ix.indexOf("world"), 6, "NBUF-S-001: indexOf string found");
assertEq(ix.indexOf("xyz"), -1, "NBUF-S-001: indexOf not found");
assertEq(ix.indexOf("hello", 1), 12, "NBUF-S-001: indexOf with fromIndex");
assertEq(ix.indexOf(108), 2, "NBUF-S-001: indexOf byte value 108 ('l')");

// NBUF-S-002 lastIndexOf + includes with negative fromIndex
var s2 = Buffer.from("abcabc");
assertEq(s2.lastIndexOf("abc"), 3, "NBUF-S-002: lastIndexOf");
assertOk(s2.includes("bc", -4), "NBUF-S-002: includes with negative byteOffset");
assertEq(s2.indexOf("o", -1), -1, "NBUF-S-002: indexOf not found from negative offset on this buffer");
var s2b = Buffer.from("hello");
assertEq(s2b.indexOf("o", -1), 4, "NBUF-S-002: indexOf finds from negative offset");

// NBUF-S-003 equals + compare
var a = Buffer.from([1, 2, 3]);
var b = Buffer.from([1, 2, 3]);
var c = Buffer.from([1, 2, 4]);
assertOk(a.equals(b), "NBUF-S-003: equals same bytes");
assertEq(a.equals(c), false, "NBUF-S-003: equals false when different");
assertEq(Buffer.compare(a, b), 0, "NBUF-S-003: Buffer.compare equal");
assertEq(Buffer.compare(a, c), -1, "NBUF-S-003: Buffer.compare less");
assertEq(Buffer.compare(c, a), 1, "NBUF-S-003: Buffer.compare greater");
assertEq(a.compare(c), -1, "NBUF-S-003: instance compare less");
var u = new Uint8Array([1, 2, 3]);
assertEq(Buffer.compare(a, u), 0, "NBUF-S-003: Buffer.compare accepts Uint8Array");

// NBUF-S-004 empty needle
var e = Buffer.from("ab");
assertEq(e.indexOf("", 0), 0, "NBUF-S-004: empty needle at 0");
assertEq(e.indexOf("", 1), 1, "NBUF-S-004: empty needle at 1");
assertEq(e.indexOf("", 2), 2, "NBUF-S-004: empty needle at length");

__jacDone();
