// testing_plans/08_buffer_and_encoding/NODE_BUFFER_COMPREHENSIVE_TEST_PLAN.md — ECG-2 (construction + encodings + buf.write)
// Scenario IDs: NBUF-C-*, NBUF-E-*, NBUF-T-*

var Buffer = require("buffer").Buffer;

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/05_buffer/test_buffer_creation_and_encodings.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }
function assertThrows(fn, ErrType, msg) { __reg.assertThrows(fn, ErrType, msg); }
function assertOk(cond, msg) { __reg.assert(cond, msg); }

// NBUF-C-001
var c1 = Buffer.alloc(4);
assertEq(c1.length, 4, "NBUF-C-001: alloc length");
assertEq(c1[0], 0, "NBUF-C-001: zero-filled");

// NBUF-C-002
var c2 = Buffer.alloc(3, 0xff);
assertEq(c2[0], 255, "NBUF-C-002: numeric fill low byte");
assertEq(c2[2], 255, "NBUF-C-002: numeric fill all bytes");

// NBUF-C-003
var c3 = Buffer.alloc(4, "AB", "utf8");
assertEq(c3[0], 65, "NBUF-C-003: string fill repeats pattern byte 0");
assertEq(c3[1], 66, "NBUF-C-003: string fill repeats pattern byte 1");
assertEq(c3[2], 65, "NBUF-C-003: string fill repeats pattern byte 2");

// NBUF-C-004 / NBUF-C-005 — allocUnsafe / Slow alias shape
var u = Buffer.allocUnsafe(8);
assertEq(u.length, 8, "NBUF-C-004: allocUnsafe length");
assertOk(Buffer.isBuffer(u), "NBUF-C-004: allocUnsafe returns Buffer");
assertEq(Buffer.allocUnsafeSlow(2).length, 2, "NBUF-C-005: allocUnsafeSlow length");

// NBUF-C-006 string encodings
var sUtf = Buffer.from("hello", "utf8");
assertEq(sUtf.toString("utf8"), "hello", "NBUF-C-006: utf8 round-trip");
var sHex = Buffer.from("68656c6c6f", "hex");
assertEq(sHex.toString("utf8"), "hello", "NBUF-C-006: hex decode");
var s64 = Buffer.from("aGVsbG8=", "base64");
assertEq(s64.toString("utf8"), "hello", "NBUF-C-006: base64 decode");
var s64u = Buffer.from("aGVsbG8", "base64url");
assertEq(s64u.toString("utf8"), "hello", "NBUF-C-006: base64url decode");

// NBUF-C-007 array clamping (value & 255)
var arr = Buffer.from([256, -1, 300]);
assertEq(arr[0], 0, "NBUF-C-007: 256 maps to 0");
assertEq(arr[1], 255, "NBUF-C-007: -1 maps to 255");
assertEq(arr[2], 44, "NBUF-C-007: 300 maps to 44");

// NBUF-C-008 copy from Buffer
var src = Buffer.from("abc");
var cp = Buffer.from(src);
cp[0] = 120;
assertEq(src.toString(), "abc", "NBUF-C-008: from(Buffer) is independent copy");

// NBUF-C-009 ArrayBuffer + byte range (requires ECMAScript typed array globals)
try {
    if (typeof ArrayBuffer === "undefined" || typeof Uint8Array === "undefined") {
        throw new TypeError("ArrayBuffer/Uint8Array missing");
    }
    var ab = new ArrayBuffer(4);
    var view = new Uint8Array(ab);
    view[0] = 10;
    view[1] = 20;
    view[2] = 30;
    view[3] = 40;
    var fromAb = Buffer.from(ab);
    assertEq(fromAb.length, 4, "NBUF-C-009: from(ArrayBuffer) length");
    assertEq(fromAb[0], 10, "NBUF-C-009: from(ArrayBuffer) first byte");
    var fromSlice = Buffer.from(ab, 1, 2);
    assertEq(fromSlice.length, 2, "NBUF-C-009: from(ArrayBuffer, off, len)");
    assertEq(fromSlice[0], 20, "NBUF-C-009: from(ArrayBuffer) offset");

    var u8 = new Uint8Array([5, 6, 7]);
    var fromU = Buffer.from(u8);
    u8[0] = 1;
    assertEq(fromU[0], 5, "NBUF-C-009: from(Uint8Array) copies bytes");
} catch (e) {
    console.error("FAIL: NBUF-C-009: ArrayBuffer/Uint8Array Buffer.from paths | " + e);
    __reg.bump(); return;
}

// NBUF-C-010 invalid size / encoding
assertThrows(
    function () {
        Buffer.alloc(-1);
    },
    RangeError,
    "NBUF-C-010: alloc negative size throws RangeError"
);
assertThrows(
    function () {
        Buffer.from("x", "utf888");
    },
    TypeError,
    "NBUF-C-010: unknown encoding throws TypeError"
);

// NBUF-E-001 multibyte UTF-8
var euro = Buffer.from("\u20ac", "utf8");
assertEq(euro.length, 3, "NBUF-E-001: euro sign utf8 length");
assertEq(euro.toString("utf8"), "\u20ac", "NBUF-E-001: euro utf8 round-trip");

// NBUF-E-002 hex odd / invalid truncation
assertEq(Buffer.from("a", "hex").length, 0, "NBUF-E-002: lone hex nibble yields empty");
assertEq(Buffer.from("ab", "hex").length, 1, "NBUF-E-002: valid pair decodes one byte");
assertEq(Buffer.from("abg", "hex").length, 1, "NBUF-E-002: stops at invalid hex");

// NBUF-E-003 base64 ignores whitespace
var ws = Buffer.from("aGVs\nbG8=", "base64");
assertEq(ws.toString("utf8"), "hello", "NBUF-E-003: base64 tolerates newline");

// NBUF-E-004 base64url round-trip
assertEq(Buffer.from("hello").toString("base64url"), "aGVsbG8", "NBUF-E-004: toString base64url");

// NBUF-E-005 latin1 / binary
var latin = Buffer.from("\xff\xfe", "latin1");
assertEq(latin.length, 2, "NBUF-E-005: latin1 two bytes");
assertEq(latin[0], 255, "NBUF-E-005: latin1 high byte");
assertEq(Buffer.from("Z", "ascii")[0], 90, "NBUF-E-005: ascii maps ASCII");

// NBUF-E-007 byteLength
assertEq(Buffer.byteLength("hello", "utf8"), 5, "NBUF-E-007: byteLength utf8 ascii");
assertEq(Buffer.byteLength("68656c6c6f", "hex"), 5, "NBUF-E-007: byteLength hex");

// NBUF-E-008 toString range
var r = Buffer.from("hello world");
assertEq(r.toString("utf8", 6, 11), "world", "NBUF-E-008: toString with start/end");

// NBUF-T-001 / T-002
var tw = Buffer.alloc(10);
var n = tw.write("hi", 2, "utf8");
assertEq(n, 2, "NBUF-T-001: write returns byte count");
assertEq(tw.toString("utf8", 2, 4), "hi", "NBUF-T-001: write at offset");
var tw2 = Buffer.alloc(3);
var n2 = tw2.write("hello", 0, 3, "utf8");
assertEq(n2, 3, "NBUF-T-002: write truncates to max length");
assertEq(tw2.toString("utf8"), "hel", "NBUF-T-002: partial write content");

// NBUF-T-003 invalid byteLength argument type
assertThrows(
    function () {
        Buffer.byteLength(null);
    },
    TypeError,
    "NBUF-T-003: byteLength null throws TypeError"
);

__jacDone();
