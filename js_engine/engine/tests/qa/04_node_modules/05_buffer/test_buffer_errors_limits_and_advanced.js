// testing_plans/08_buffer_and_encoding/NODE_BUFFER_COMPREHENSIVE_TEST_PLAN.md — ECG-5 (errors + limits + advanced buffer APIs)
// Scenario IDs: NBUF-X-*, NBUF-A-*

var buf = require("buffer");
var Buffer = buf.Buffer;

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/05_buffer/test_buffer_errors_limits_and_advanced.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }
function assertThrows(fn, ErrType, msg) { __reg.assertThrows(fn, ErrType, msg); }
function assertOk(cond, msg) { __reg.assert(cond, msg); }

// NBUF-X-001
assertThrows(
    function () {
        Buffer.alloc(NaN);
    },
    RangeError,
    "NBUF-X-001: alloc NaN throws RangeError"
);

// NBUF-X-002
var x2 = Buffer.alloc(1);
assertThrows(
    function () {
        x2.readUInt8(5);
    },
    RangeError,
    "NBUF-X-002: readUInt8 out of range throws RangeError"
);

// NBUF-X-003
var x3 = Buffer.alloc(2);
assertThrows(
    function () {
        x3.writeUInt8(1, 5);
    },
    RangeError,
    "NBUF-X-003: writeUInt8 out of range throws RangeError"
);

// NBUF-X-004
assertThrows(
    function () {
        Buffer.compare(Buffer.from("a"), {});
    },
    TypeError,
    "NBUF-X-004: Buffer.compare non-Uint8Array throws TypeError"
);
assertThrows(
    function () {
        Buffer.concat(null);
    },
    TypeError,
    "NBUF-X-004: Buffer.concat non-array throws TypeError"
);

// NBUF-X-006 encoding errors on toString
assertThrows(
    function () {
        Buffer.from("a").toString("utf888");
    },
    TypeError,
    "NBUF-X-006: toString unknown encoding throws TypeError"
);

// NBUF-A-001 atob / btoa
assertEq(buf.atob("aGVsbG8="), "hello", "NBUF-A-001: atob decodes base64 string");
assertEq(buf.btoa("hello"), "aGVsbG8=", "NBUF-A-001: btoa encodes to base64");

// NBUF-A-002 Blob from buffer module
var blob = new buf.Blob(["hi"], { type: "text/plain" });
assertEq(typeof blob.arrayBuffer, "function", "NBUF-A-002: Blob has arrayBuffer");
assertEq(blob.size, 2, "NBUF-A-002: Blob size");

// NBUF-A-003 File
var f = new buf.File(["x"], "n.txt", { type: "text/plain" });
assertEq(f.name, "n.txt", "NBUF-A-003: File name");
assertEq(f.size, 1, "NBUF-A-003: File size");

// NBUF-A-004 transcode
var src = Buffer.from("68656c6c6f", "hex");
var out = buf.transcode(src, "latin1", "utf8");
assertEq(out.toString("utf8"), "hello", "NBUF-A-004: transcode latin1 label to utf8");
assertThrows(
    function () {
        buf.transcode(Buffer.from("a"), "utf888", "utf8");
    },
    Error,
    "NBUF-A-004: transcode invalid encoding throws"
);

// NBUF-A-005 isUtf8 / isAscii
assertOk(buf.isUtf8(Buffer.from("caf\u00e9", "utf8")), "NBUF-A-005: isUtf8 valid utf8 buffer");
assertEq(buf.isUtf8(Buffer.from([0xff, 0xfe])), false, "NBUF-A-005: isUtf8 false for invalid sequence");
assertOk(buf.isAscii(Buffer.from("ABC")), "NBUF-A-005: isAscii ASCII");
assertEq(buf.isAscii(Buffer.from([200])), false, "NBUF-A-005: isAscii false for high byte");

// NBUF-A-006 constants / limits shape
assertOk(buf.kMaxLength > 0, "NBUF-A-006: kMaxLength positive");
assertOk(buf.kStringMaxLength > 0, "NBUF-A-006: kStringMaxLength positive");
assertOk(buf.INSPECT_MAX_BYTES > 0, "NBUF-A-006: INSPECT_MAX_BYTES positive");

__jacDone();
