// BUF-CAT-001 through BUF-CAT-004: Buffer.concat with zero-length elements.
// Regression: the concat copy loop used `break` (not `continue`) on a
// zero-length list element, abandoning every later buffer and returning
// allocUnsafe garbage/zeros for the rest (broke cipher.update()/final()
// round-trips, which concat an empty update chunk with the final block).
var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/05_buffer/test_buffer_concat_zero_length.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

var a = Buffer.from("hello");
var b = Buffer.from(" world");

// BUF-CAT-001: leading empty element
assertEq(Buffer.concat([Buffer.alloc(0), a]).toString("utf8"), "hello",
    "BUF-CAT-001: leading zero-length element does not truncate");

// BUF-CAT-002: empty element between chunks
assertEq(Buffer.concat([a, Buffer.alloc(0), b]).toString("utf8"), "hello world",
    "BUF-CAT-002: interior zero-length element skipped");

// BUF-CAT-003: several empties, exact bytes preserved
var out = Buffer.concat([Buffer.alloc(0), a, Buffer.alloc(0), b, Buffer.alloc(0)]);
assertEq(out.length, 11, "BUF-CAT-003: total length");
assertEq(out.toString("utf8"), "hello world", "BUF-CAT-003: content");

// BUF-CAT-004: explicit totalLength still truncates correctly
assertEq(Buffer.concat([Buffer.alloc(0), a, b], 5).toString("utf8"), "hello",
    "BUF-CAT-004: totalLength truncation with empty first element");

__jacDone();
