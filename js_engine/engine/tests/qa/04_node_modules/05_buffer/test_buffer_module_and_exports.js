// testing_plans/08_buffer_and_encoding/NODE_BUFFER_COMPREHENSIVE_TEST_PLAN.md — ECG-1 (module + exports + globals)
// Scenario IDs: NBUF-M-001, NBUF-M-002, NBUF-M-003, NBUF-M-004, NBUF-G-001, NBUF-G-002, NBUF-G-003

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/05_buffer/test_buffer_module_and_exports.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }
function assertOk(cond, msg) { __reg.assert(cond, msg); }

// NBUF-M-001
var bufMod = require("buffer");
assertEq(typeof bufMod, "object", "NBUF-M-001: require('buffer') typeof object");
assertOk(typeof bufMod.Buffer === "object" || typeof bufMod.Buffer === "function", "NBUF-M-001: Buffer export present");
assertOk(typeof bufMod.Buffer.alloc === "function", "NBUF-M-001: Buffer.alloc is function");
assertOk(typeof bufMod.Buffer.from === "function", "NBUF-M-001: Buffer.from is function");

// NBUF-M-002
var bufModNode = require("node:buffer");
assertOk(bufMod === bufModNode, "NBUF-M-002: require('node:buffer') same cached module as require('buffer')");

var Buffer = bufMod.Buffer;

// NBUF-G-001 — global matches module export after load
assertOk(globalThis.Buffer === Buffer, "NBUF-G-001: globalThis.Buffer identical to module Buffer after require");

// NBUF-G-003 (before G-002 so isBuffer still runs when Uint8Array inheritance is missing)
assertOk(Buffer.isBuffer(Buffer.alloc(0)), "NBUF-G-003: Buffer.isBuffer true for Buffer");
assertEq(Buffer.isBuffer("x"), false, "NBUF-G-003: Buffer.isBuffer false for string");
assertEq(Buffer.isBuffer(null), false, "NBUF-G-003: Buffer.isBuffer false for null");
assertEq(Buffer.isBuffer({}), false, "NBUF-G-003: Buffer.isBuffer false for plain object");

// NBUF-M-004 — export surface (Node.js buffer module)
function assertExport(name, pred) {
    assertOk(pred(bufMod[name]), "NBUF-M-004: export " + name + " present/typed as expected");
}
assertExport("Buffer", function (v) {
    return v && (typeof v.alloc === "function" || typeof v === "function");
});
assertEq(typeof bufMod.SlowBuffer, "function", "NBUF-M-004: SlowBuffer is function (legacy export)");
assertEq(typeof bufMod.INSPECT_MAX_BYTES, "number", "NBUF-M-004: INSPECT_MAX_BYTES is number");
assertEq(typeof bufMod.kMaxLength, "number", "NBUF-M-004: kMaxLength is number");
assertEq(typeof bufMod.kStringMaxLength, "number", "NBUF-M-004: kStringMaxLength is number");
assertEq(typeof bufMod.constants, "object", "NBUF-M-004: constants is object");
assertEq(typeof bufMod.constants.MAX_LENGTH, "number", "NBUF-M-004: constants.MAX_LENGTH is number");
assertEq(typeof bufMod.transcode, "function", "NBUF-M-004: transcode is function");
assertEq(typeof bufMod.isUtf8, "function", "NBUF-M-004: isUtf8 is function");
assertEq(typeof bufMod.isAscii, "function", "NBUF-M-004: isAscii is function");
assertEq(typeof bufMod.atob, "function", "NBUF-M-004: atob is function");
assertEq(typeof bufMod.btoa, "function", "NBUF-M-004: btoa is function");
assertEq(typeof bufMod.Blob, "function", "NBUF-M-004: Blob is function");
assertEq(typeof bufMod.File, "function", "NBUF-M-004: File is function");
assertEq(typeof bufMod.resolveObjectURL, "function", "NBUF-M-004: resolveObjectURL is function");

// NBUF-G-002 — Buffer instances are Uint8Array in Node (after export inventory)
var g2 = Buffer.alloc(1);
assertOk(g2 instanceof Uint8Array, "NBUF-G-002: Buffer.alloc result instanceof Uint8Array");

// NBUF-M-003 — ESM namespace via dynamic import (run_reg.sh does not discover standalone .mjs)
function failM003(msg) {
    console.error("FAIL: NBUF-M-003: " + msg);
    __reg.bump(); return;
}
import("node:buffer")
    .then(function (ns) {
        if (typeof ns.Buffer.alloc !== "function") {
            failM003("namespace Buffer.alloc missing");
        }
        if (ns.Buffer !== Buffer) {
            failM003("dynamic import Buffer !== require buffer Buffer");
        }
        if (typeof ns.kMaxLength !== "number") {
            failM003("namespace kMaxLength missing");
        }
        __jacDone();
    })
    .catch(function (e) {
        console.error("FAIL: NBUF-M-003: dynamic import failed | " + e);
        __reg.bump(); __jacDone();
    });
__jacDone();
