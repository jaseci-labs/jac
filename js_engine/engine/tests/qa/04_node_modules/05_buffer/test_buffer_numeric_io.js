// testing_plans/08_buffer_and_encoding/NODE_BUFFER_COMPREHENSIVE_TEST_PLAN.md — ECG-4 (numeric I/O + JSON)
// Scenario IDs: NBUF-N-*, NBUF-J-*

var Buffer = require("buffer").Buffer;

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/05_buffer/test_buffer_numeric_io.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }
function assertOk(cond, msg) { __reg.assert(cond, msg); }
function near(a, b, tol, msg) {
    var d = a - b;
    if (d < 0) {
        d = -d;
    }
    if (d > tol) {
        console.error("FAIL: " + msg + " | expected ~" + b + " | actual " + a);
        __reg.bump(); return;
    }
}

// NBUF-N-001 unsigned ints
var n = Buffer.alloc(8);
n.writeUInt8(255, 0);
assertEq(n.readUInt8(0), 255, "NBUF-N-001: UInt8");
n.writeUInt16LE(1000, 0);
assertEq(n.readUInt16LE(0), 1000, "NBUF-N-001: UInt16LE");
n.writeUInt16BE(1000, 0);
assertEq(n.readUInt16BE(0), 1000, "NBUF-N-001: UInt16BE");
n.writeUInt32LE(100000, 0);
assertEq(n.readUInt32LE(0), 100000, "NBUF-N-001: UInt32LE");
n.writeUInt32BE(100000, 0);
assertEq(n.readUInt32BE(0), 100000, "NBUF-N-001: UInt32BE");

// NBUF-N-002 signed ints
var n2 = Buffer.alloc(8);
n2.writeInt8(-50, 0);
assertEq(n2.readInt8(0), -50, "NBUF-N-002: Int8");
n2.writeInt16LE(-2, 0);
assertEq(n2.readInt16LE(0), -2, "NBUF-N-002: Int16LE");
n2.writeInt32BE(-1, 0);
assertEq(n2.readInt32BE(0), -1, "NBUF-N-002: Int32BE");
n2.writeInt32LE(-2, 0);
assertEq(n2.readInt32LE(0), -2, "NBUF-N-002: Int32LE");

// NBUF-N-003 float + double (double methods come from Node Buffer / Uint8Array prototype)
var n3 = Buffer.alloc(8);
n3.writeFloatLE(3.14, 0);
near(n3.readFloatLE(0), 3.14, 0.001, "NBUF-N-003: FloatLE round-trip");
if (typeof n3.writeDoubleLE !== "function" || typeof n3.readDoubleLE !== "function") {
    console.error("FAIL: NBUF-N-003: writeDoubleLE/readDoubleLE must exist on Buffer (Node)");
    __reg.bump(); return;
}
n3.writeDoubleLE(3.14159265358979, 0);
near(n3.readDoubleLE(0), 3.14159265358979, 1e-10, "NBUF-N-003: DoubleLE round-trip");

// NBUF-N-004 BigInt
var n4 = Buffer.alloc(16);
if (typeof n4.writeBigUInt64BE !== "function" || typeof n4.readBigUInt64BE !== "function") {
    console.error("FAIL: NBUF-N-004: BigInt buffer read/write methods must exist (Node)");
    __reg.bump(); return;
}
n4.writeBigUInt64BE(18446744073709551615n, 0);
assertEq(n4.readBigUInt64BE(0), 18446744073709551615n, "NBUF-N-004: BigUInt64BE max");
n4.writeBigInt64LE(-1n, 0);
assertEq(n4.readBigInt64LE(0), -1n, "NBUF-N-004: BigInt64LE -1");

// NBUF-J-001 / NBUF-J-002
var j = Buffer.from([65, 66, 67]);
var jo = j.toJSON();
assertEq(jo.type, "Buffer", "NBUF-J-001: toJSON type");
assertEq(jo.data[0], 65, "NBUF-J-001: toJSON data[0]");
assertEq(JSON.stringify(j), '{"type":"Buffer","data":[65,66,67]}', "NBUF-J-002: JSON.stringify Buffer shape");

__jacDone();
