// Plan: testing_plans/06_process_os_stdio/NODE_FS_COMPREHENSIVE_TEST_PLAN.md
// Coverage: ECG-1 (NFS-M-*, NFS-S-*)
var fs = require("fs");
var fsNode = require("node:fs");
var path = require("path");
var os = require("os");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/01_fs/test_fs_nfs_core.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function fail(msg) {
    console.error("FAIL: " + msg);
    __reg.bump(); return;
}

function assert(cond, msg) {
    if (!cond) { fail(msg); }
}

function assertEq(actual, expected, msg) {
    if (actual !== expected) {
        fail(msg + " | expected: " + JSON.stringify(expected) + " | actual: " + JSON.stringify(actual));
    }
}

function expectThrow(fn, check, msg) {
    var threw = false;
    try {
        fn();
    } catch (e) {
        threw = true;
        if (check) { check(e); }
    }
    assert(threw, msg);
}

var tmpDir = path.join(os.tmpdir(), "js_engine_nfs_core_" + process.pid);
fs.mkdirSync(tmpDir, { recursive: true });
process.on("exit", function() {
    try { fs.rmSync(tmpDir, { recursive: true, force: true }); } catch (e) {}
});

var file = path.join(tmpDir, "core.txt");
var appendOnly = path.join(tmpDir, "append_only.txt");

// NFS-M-001 / NFS-M-002
assert(typeof fs === "object" && fs !== null, "NFS-M-001: require('fs') returns object");
assert(typeof fsNode === "object" && fsNode !== null, "NFS-M-002: require('node:fs') returns object");
assert(fs === fsNode, "NFS-M-002: fs and node:fs alias same object");

var requiredFns = [
    "readFileSync", "writeFileSync", "appendFileSync", "existsSync", "unlinkSync",
    "statSync", "readdirSync", "mkdirSync", "rmSync", "renameSync", "copyFileSync",
    "chmodSync", "lstatSync", "accessSync", "createReadStream", "createWriteStream"
];
var i = 0;
while (i < requiredFns.length) {
    var name = requiredFns[i];
    assert(typeof fs[name] === "function", "NFS-M-001: fs." + name + " is function");
    i = i + 1;
}

// NFS-M-004 / NFS-M-006
assert(typeof fs.promises === "object" && fs.promises !== null, "NFS-M-004: fs.promises exists");
assert(typeof fs.constants === "object" && fs.constants !== null, "NFS-M-006: fs.constants exists");
assert(typeof fs.constants.F_OK === "number", "NFS-M-006: fs.constants.F_OK is number");

// NFS-S-001
fs.writeFileSync(file, "hello nfs", "utf8");
assertEq(fs.readFileSync(file, "utf8"), "hello nfs", "NFS-S-001: read/write utf8 round-trip");

// NFS-S-002
var buf = fs.readFileSync(file);
assert(Buffer.isBuffer(buf), "NFS-S-002: readFileSync without encoding returns Buffer");

// NFS-S-003
fs.appendFileSync(file, "\nline2", "utf8");
assertEq(fs.readFileSync(file, "utf8"), "hello nfs\nline2", "NFS-S-003: appendFileSync appends");
fs.appendFileSync(appendOnly, "created by append", "utf8");
assertEq(fs.readFileSync(appendOnly, "utf8"), "created by append", "NFS-S-003: appendFileSync creates missing file");

// NFS-S-004
assert(fs.existsSync(file), "NFS-S-004: existsSync true for existing file");
assert(!fs.existsSync(path.join(tmpDir, "missing.txt")), "NFS-S-004: existsSync false for missing file");

// NFS-S-005
var unlinkTarget = path.join(tmpDir, "unlink.txt");
fs.writeFileSync(unlinkTarget, "x", "utf8");
fs.unlinkSync(unlinkTarget);
assert(!fs.existsSync(unlinkTarget), "NFS-S-005: unlinkSync removes file");
expectThrow(function() {
    fs.unlinkSync(path.join(tmpDir, "nope.txt"));
}, function(e) {
    assertEq(e.code, "ENOENT", "NFS-S-005: unlinkSync missing has ENOENT");
}, "NFS-S-005: unlinkSync missing should throw");

// NFS-S-006
expectThrow(function() {
    fs.readFileSync(path.join(tmpDir, "absent.txt"), "utf8");
}, function(e) {
    assertEq(e.code, "ENOENT", "NFS-S-006: readFileSync missing has ENOENT");
}, "NFS-S-006: readFileSync missing should throw");

// NFS-S-007
expectThrow(function() {
    fs.readFileSync({}, "utf8");
}, function(e) {
    assert(e instanceof TypeError, "NFS-S-007: invalid path type throws TypeError");
}, "NFS-S-007: readFileSync invalid path type should throw");

// NFS-S-008
var utf8ViaObject = fs.readFileSync(file, { encoding: "utf8" });
assertEq(utf8ViaObject, "hello nfs\nline2", "NFS-S-008: readFileSync options.encoding works");
fs.writeFileSync(file, "overwritten via flag", { encoding: "utf8", flag: "w" });
assertEq(fs.readFileSync(file, "utf8"), "overwritten via flag", "NFS-S-008: writeFileSync with options object works");

__jacDone();
