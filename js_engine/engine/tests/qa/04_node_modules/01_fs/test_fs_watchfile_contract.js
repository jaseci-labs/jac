// FSWF-001..004: fs.watchFile / fs.unwatchFile contract
var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/01_fs/test_fs_watchfile_contract.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

var fs = require("fs");
var path = require("path");
var os = require("os");

function assert(cond, msg) { __reg.assert(cond, msg); }

var f = path.join(os.tmpdir(), "jac_watchfile_" + Date.now() + ".txt");
try { fs.unlinkSync(f); } catch (e) {}

var calls = 0;
var listener = function (curr, prev) {
    calls = calls + 1;
    assert(curr && prev, "FSWF-001: curr and prev provided");
    assert(typeof curr.mtimeMs === "number", "FSWF-002: mtimeMs on curr");
};

var sw = fs.watchFile(f, { interval: 100 }, listener);
assert(typeof sw.ref === "function", "FSWF-003: StatWatcher ref");
assert(typeof sw.unref === "function", "FSWF-003: StatWatcher unref");

setTimeout(function () {
    fs.writeFileSync(f, "hello");
    setTimeout(function () {
        assert(calls >= 1, "FSWF-001: listener invoked after write");
        fs.unwatchFile(f, listener);
        var callsBefore = calls;
        fs.writeFileSync(f, "again");
        setTimeout(function () {
            assert(calls === callsBefore, "FSWF-004: unwatchFile removes listener");
            __jacDone();
        }, 300);
    }, 300);
}, 100);
