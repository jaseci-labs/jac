// Vite build FS compatibility regression (realpathSync.native, statSync options, rmSync, mkdirSync, readdir withFileTypes)
"use strict";

var fs = require("node:fs");
var os = require("node:os");
var path = require("node:path");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/01_fs/test_fs_vite_compat.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }
function assertThrows(fn, msg) {
    var ok = false;
    try { fn(); } catch (e) { ok = true; }
    assert(ok, msg);
}

// VITE-FS-001: fs.realpathSync.native
assert(typeof fs.realpathSync.native === "function", "VITE-FS-001: realpathSync.native exists");
assertEq(fs.realpathSync.native("/tmp"), fs.realpathSync("/tmp"), "VITE-FS-001: native matches realpathSync");

// VITE-FS-002: statSync throwIfNoEntry:false
var missing = path.join(os.tmpdir(), "js_engine-vite-missing-" + Date.now());
assertEq(fs.statSync(missing, { throwIfNoEntry: false }), undefined, "VITE-FS-002: throwIfNoEntry false returns undefined");
assertThrows(function () { fs.statSync(missing, { throwIfNoEntry: true }); }, "VITE-FS-002: throwIfNoEntry true throws");
assertThrows(function () { fs.statSync(missing); }, "VITE-FS-002: default throws");

// VITE-FS-003: rmSync force on missing path
fs.rmSync(path.join(os.tmpdir(), "js_engine-vite-rm-missing-" + Date.now()), { force: true });

// VITE-FS-004: rmSync recursive tree removal
var rmDir = path.join(os.tmpdir(), "js_engine-vite-rm-" + Date.now());
fs.mkdirSync(path.join(rmDir, "a", "b"), { recursive: true });
fs.writeFileSync(path.join(rmDir, "a", "b", "f.txt"), "x");
fs.rmSync(rmDir, { recursive: true, force: true });
assertEq(fs.statSync(rmDir, { throwIfNoEntry: false }), undefined, "VITE-FS-004: recursive rm removed tree");

// VITE-FS-005 / VITE-FS-006: mkdirSync deep recursive
var deep = path.join(os.tmpdir(), "js_engine-vite-mk-" + Date.now(), "a", "b", "c");
fs.mkdirSync(deep, { recursive: true });
assert(fs.statSync(deep).isDirectory(), "VITE-FS-005: deep mkdir created path");
fs.mkdirSync(deep, { recursive: true });
var mk2 = path.join(os.tmpdir(), "js_engine-vite-mk2-" + Date.now());
assertEq(fs.mkdirSync(mk2, { recursive: true }), mk2, "VITE-FS-006: recursive mkdir returns path when created");
assertEq(fs.mkdirSync(mk2, { recursive: true }), undefined, "VITE-FS-006b: recursive mkdir returns undefined when exists");

// VITE-FS-007 / VITE-FS-008: readdir withFileTypes
var wfDir = path.join(os.tmpdir(), "js_engine-vite-wft-" + Date.now());
fs.mkdirSync(wfDir);
fs.writeFileSync(path.join(wfDir, "f.txt"), "x");
var dirents = fs.readdirSync(wfDir, { withFileTypes: true });
assertEq(dirents.length, 1, "VITE-FS-007: one dirent");
assertEq(typeof dirents[0].name, "string", "VITE-FS-008: dirent.name is string");
assert(typeof dirents[0].isFile === "function", "VITE-FS-008: dirent.isFile is function");
assert(dirents[0].isFile(), "VITE-FS-008: isFile true for file");
assert(!dirents[0].isDirectory(), "VITE-FS-008: isDirectory false for file");
assert(typeof dirents[0].isSymbolicLink === "function", "VITE-FS-008: isSymbolicLink is function");
var strs = fs.readdirSync(wfDir);
assertEq(typeof strs[0], "string", "VITE-FS-007: plain readdir returns strings");

// cleanup
try { fs.rmSync(wfDir, { recursive: true, force: true }); } catch (e) { /* ignore */ }
try { fs.rmSync(deep.split("/a/b/c")[0], { recursive: true, force: true }); } catch (e) { /* ignore */ }

__jacDone();
