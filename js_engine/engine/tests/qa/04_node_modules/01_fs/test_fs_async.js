// FS-020/FS-021: fs async (callbacks and promises)
var fs   = require("fs");
var path = require("path");
var os   = require("os");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/01_fs/test_fs_async.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

var tmpDir = path.join(os.tmpdir(), "js_engine_fs_async_" + process.pid);
fs.mkdirSync(tmpDir, {recursive: true});
process.on("exit", function() {
    try { fs.rmSync(tmpDir, {recursive: true, force: true}); } catch(e) {}
});

var passed = 0;
var total = 0;
var timeoutId;

function done() {
    passed++;
    if (passed >= total) {
        clearTimeout(timeoutId);
        __jacDone();
    }
}

function addTest() { total++; }

// FS-020: readFile/writeFile (callback)
addTest();
var cbFile = path.join(tmpDir, "cb.txt");
fs.writeFile(cbFile, "callback content", "utf8", function(err) {
    assert(!err, "FS-020: writeFile callback no error");
    fs.readFile(cbFile, "utf8", function(err2, data) {
        assert(!err2, "FS-020: readFile callback no error");
        assertEq(data, "callback content", "FS-020: readFile callback content");
        done();
    });
});

// FS-021: fs.promises
if (fs.promises) {
    addTest();
    var promFile = path.join(tmpDir, "prom.txt");
    fs.promises.writeFile(promFile, "promise content", "utf8")
        .then(function() {
            return fs.promises.readFile(promFile, "utf8");
        })
        .then(function(data) {
            assertEq(data, "promise content", "FS-021: promises.readFile");
            return fs.promises.stat(promFile);
        })
        .then(function(stat) {
            assert(stat.isFile(), "FS-021: promises.stat isFile");
            return fs.promises.unlink(promFile);
        })
        .then(function() {
            assert(!fs.existsSync(promFile), "FS-021: promises.unlink works");
            return fs.promises.mkdir(path.join(tmpDir, "pmkdir"));
        })
        .then(function() {
            assert(fs.existsSync(path.join(tmpDir, "pmkdir")), "FS-021: promises.mkdir");
            return fs.promises.readdir(tmpDir);
        })
        .then(function(entries) {
            assert(Array.isArray(entries), "FS-021: promises.readdir returns array");
            done();
        })
        .catch(function(e) {
            console.error("FAIL: FS-021 promises error: " + e.message);
            __reg.bump(); __jacDone();
        });
}

// FS-022: fs.open + fs.close (callback)
addTest();
var openFile = path.join(tmpDir, "open_test.txt");
fs.writeFileSync(openFile, "open content");
fs.open(openFile, "r", function(err, fd) {
    assert(!err, "FS-022: open callback no error");
    assert(typeof fd === "number" && fd > 2, "FS-022: open returns numeric fd > 2");
    fs.close(fd, function(err2) {
        assert(!err2, "FS-022: close callback no error");
        done();
    });
});

// FS-023: fs.open with explicit mode arg (mode is optional / can be omitted)
addTest();
fs.open(openFile, "r", 0o666, function(err, fd2) {
    assert(!err, "FS-023: open with explicit mode no error");
    assert(typeof fd2 === "number", "FS-023: open with explicit mode returns fd");
    fs.close(fd2, function() { done(); });
});

// FS-024: fs.open on a nonexistent file for reading should return ENOENT (real open(2))
addTest();
fs.open(path.join(tmpDir, "nonexistent_open.txt"), "r", function(err, fd3) {
    assert(err && err.code === "ENOENT", "FS-024: open nonexistent file returns ENOENT");
    assert(fd3 === undefined, "FS-024: fd is undefined on error");
    done();
});

// FS-025: fs.stat callback on existing file
addTest();
var statFile = path.join(tmpDir, "stat_cb.txt");
fs.writeFileSync(statFile, "stat content");
fs.stat(statFile, function(err, st) {
    assert(!err, "FS-025: stat callback no error");
    assert(st && st.isFile(), "FS-025: stat isFile");
    assert(st.size > 0, "FS-025: stat size > 0");
    done();
});

// FS-026: fs.stat callback with options arg (options is optional)
addTest();
fs.stat(statFile, {bigint: false}, function(err, st2) {
    assert(!err, "FS-026: stat with options no error");
    assert(st2 && st2.isFile(), "FS-026: stat with options isFile");
    done();
});

// FS-027: fs.lstat callback on existing file
addTest();
fs.lstat(statFile, function(err, lst) {
    assert(!err, "FS-027: lstat callback no error");
    assert(lst && lst.isFile(), "FS-027: lstat isFile");
    done();
});

// FS-028: fs.lstat callback with options arg (options is optional)
addTest();
fs.lstat(statFile, {bigint: false}, function(err, lst2) {
    assert(!err, "FS-028: lstat with options no error");
    assert(lst2 && lst2.isFile(), "FS-028: lstat with options isFile");
    done();
});

// FS-029: fs.realpath callback on existing file
addTest();
fs.realpath(statFile, function(err, rp) {
    assert(!err, "FS-029: realpath callback no error");
    assert(typeof rp === "string" && rp.length > 0, "FS-029: realpath returns string");
    assert(rp.indexOf("stat_cb.txt") !== -1, "FS-029: realpath contains filename");
    done();
});

// FS-030: fs.realpath callback with options arg (options is optional)
addTest();
fs.realpath(statFile, {encoding: "utf8"}, function(err, rp2) {
    assert(!err, "FS-030: realpath with options no error");
    assert(typeof rp2 === "string", "FS-030: realpath with options returns string");
    done();
});

// Timeout safety
timeoutId = setTimeout(function() {
    console.error("FAIL: FS async test timed out (passed " + passed + "/" + total + ")");
    __reg.bump(); return;
}, 5000);

// If no async tests added, exit immediately
if (total === 0) {
    clearTimeout(timeoutId);
    __jacDone();
}
