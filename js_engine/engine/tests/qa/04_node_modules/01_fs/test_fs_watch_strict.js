// FSW-S-001..010: strict Node v24 fs watcher parity (watch, watchFile, promises.watch)
var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/01_fs/test_fs_watch_strict.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

var fs = require("fs");
var path = require("path");
var os = require("os");

function assert(cond, msg) { __reg.assert(cond, msg); }

function isFSWatcher(w) {
    if (!w || typeof w.close !== "function" || typeof w.on !== "function") { return false; }
    if (typeof fs.FSWatcher === "function") { return w instanceof fs.FSWatcher; }
    return w.constructor && w.constructor.name === "FSWatcher";
}

function isStatWatcher(w) {
    if (!w || typeof w.ref !== "function" || typeof w.unref !== "function") { return false; }
    if (typeof fs.StatWatcher === "function") { return w instanceof fs.StatWatcher; }
    return w.constructor && w.constructor.name === "StatWatcher";
}

var tmpDir = path.join(os.tmpdir(), "jac_fs_watch_strict_" + Date.now());
fs.mkdirSync(tmpDir, { recursive: true });

assert(typeof fs.promises.watch === "function", "FSW-S-006: fs.promises.watch exists");

var w = fs.watch(tmpDir);
assert(isFSWatcher(w), "FSW-S-001: watch returns FSWatcher-shaped instance");

var closeCount = 0;
w.on("close", function () { closeCount = closeCount + 1; });
w.close();
w.close();
assert(closeCount === 0, "FSW-S-002: close event is deferred (not synchronous)");

setTimeout(function () {
    assert(closeCount === 1, "FSW-S-002: exactly one close event after next tick");

    if (typeof AbortController === "function") {
        var ac = new AbortController();
        var wAbort = fs.watch(tmpDir, { signal: ac.signal });
        var abortClosed = false;
        wAbort.on("close", function () { abortClosed = true; });
        ac.abort();
        setTimeout(function () {
            assert(abortClosed, "FSW-S-003: AbortSignal closes watcher");
            runBufferTest();
        }, 150);
    } else {
        runBufferTest();
    }
}, 150);

function runBufferTest() {
    if (!globalThis.Buffer) {
        runIgnoreTest();
        return;
    }
    var bufDir = path.join(tmpDir, "buf");
    fs.mkdirSync(bufDir);
    var gotBuf = false;
    var wb = fs.watch(bufDir, { encoding: "buffer" }, function (ev, fn) {
        if (fn !== undefined && fn !== null && typeof fn.length === "number") {
            gotBuf = true;
        }
    });
    setTimeout(function () {
        fs.writeFileSync(path.join(bufDir, "b.txt"), "x");
        setTimeout(function () {
            assert(gotBuf, "FSW-S-004: buffer encoding yields Buffer-like filename");
            wb.close();
            runIgnoreTest();
        }, 300);
    }, 80);
}

function runIgnoreTest() {
    var ignDir = path.join(tmpDir, "ign");
    fs.mkdirSync(ignDir);
    var seen = 0;
    var wi = fs.watch(ignDir, {
        ignore: function (name) {
            return !!(name && name.indexOf(".tmp") >= 0);
        }
    }, function () { seen = seen + 1; });
    setTimeout(function () {
        fs.writeFileSync(path.join(ignDir, "skip.tmp"), "a");
        fs.writeFileSync(path.join(ignDir, "keep.txt"), "b");
        setTimeout(function () {
            assert(seen >= 1, "FSW-S-005: watch accepts ignore option and still emits events");
            wi.close();
            runPromisesWatch();
        }, 300);
    }, 80);
}

function runPromisesWatch() {
    var promDir = path.join(tmpDir, "prom");
    fs.mkdirSync(promDir);
    var iterable = fs.promises.watch(promDir);
    assert(typeof iterable[Symbol.asyncIterator] === "function",
        "FSW-S-006: promises.watch is async iterable");
    var iter = iterable[Symbol.asyncIterator]();
    var promDone = false;
    setTimeout(function () {
        fs.writeFileSync(path.join(promDir, "p.txt"), "z");
    }, 80);
    iter.next().then(function (res) {
        assert(res && res.done === false, "FSW-S-006: iterator not done");
        assert(res.value && (res.value.eventType === "change" || res.value.eventType === "rename"),
            "FSW-S-006: eventType present");
        return iter.return();
    }).then(function () {
        promDone = true;
        runWatchFileEnoent();
    }).catch(function (e) {
        assert(false, "FSW-S-006: promises.watch failed: " + String(e));
        __jacDone();
    });
    setTimeout(function () {
        if (!promDone) {
            assert(false, "FSW-S-006: promises.watch timed out");
            __jacDone();
        }
    }, 2000);
}

function runWatchFileEnoent() {
    var missing = path.join(tmpDir, "enoent_" + Date.now() + ".txt");
    try { fs.unlinkSync(missing); } catch (e) {}
    var enoentCalls = 0;
    var sawZero = false;
    fs.watchFile(missing, { interval: 80 }, function (curr) {
        enoentCalls = enoentCalls + 1;
        if (curr && (curr.mtimeMs === 0 || (typeof BigInt !== "undefined" && curr.mtimeMs === BigInt(0)))) {
            sawZero = true;
        }
    });
    setTimeout(function () {
        assert(enoentCalls >= 1, "FSW-S-007: ENOENT emits watchFile callback");
        assert(sawZero, "FSW-S-007: zeroed stats on missing file");
        fs.writeFileSync(missing, "back");
        setTimeout(function () {
            assert(enoentCalls >= 2, "FSW-S-007: resume after file appears");
            fs.unwatchFile(missing);
            runWatchFileBigint();
        }, 250);
    }, 200);
}

function runWatchFileBigint() {
    if (typeof BigInt === "undefined") {
        runUnwatchNoop();
        return;
    }
    var bf = path.join(tmpDir, "bigint_" + Date.now() + ".txt");
    fs.writeFileSync(bf, "a");
    var gotBig = false;
    fs.watchFile(bf, { interval: 80, bigint: true }, function (curr) {
        if (curr && typeof curr.size === "bigint") { gotBig = true; }
    });
    setTimeout(function () {
        fs.writeFileSync(bf, "longer");
        setTimeout(function () {
            assert(gotBig, "FSW-S-008: bigint option yields bigint stat fields");
            fs.unwatchFile(bf);
            runUnwatchNoop();
        }, 250);
    }, 200);
}

function runUnwatchNoop() {
    fs.unwatchFile(path.join(tmpDir, "never_watched_" + Date.now() + ".txt"));
    var sw = fs.watchFile(path.join(tmpDir, "noop.txt"), { interval: 200 }, function () {});
    assert(isStatWatcher(sw), "FSW-S-009: watchFile returns StatWatcher-shaped instance");
    assert(typeof sw.stop === "function", "FSW-S-009: StatWatcher has stop()");
    fs.unwatchFile(path.join(tmpDir, "noop.txt"));
    __jacDone();
}
