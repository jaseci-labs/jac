// Plan: testing_plans/06_process_os_stdio/NODE_FS_COMPREHENSIVE_TEST_PLAN.md
// Coverage: ECG-4 (NFS-A-*, NFS-P-*)
var fs = require("fs");
var fspNode = require("node:fs/promises");
var path = require("path");
var os = require("os");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/01_fs/test_fs_nfs_async.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function fail(msg) {
    console.error("FAIL: " + msg);
    __reg.bump(); return;
}

function assert(cond, msg) {
    if (!cond) { fail(msg); }
}

function assertEq(actual, expected, msg) {
    if (actual !== expected) {
        fail(msg + " | expected: " + JSON.stringify(expected) + " | actual: " + JSON.stringify(actual));
    }
}

var tmpDir = path.join(os.tmpdir(), "js_engine_nfs_async_" + process.pid);
fs.mkdirSync(tmpDir, { recursive: true });
process.on("exit", function() {
    try { fs.rmSync(tmpDir, { recursive: true, force: true }); } catch (e) {}
});

assert(typeof fs.promises === "object" && fs.promises !== null, "NFS-P-001: fs.promises exists");
assert(typeof fspNode === "object" && fspNode !== null, "NFS-P-006: node:fs/promises module resolves");
assert(typeof fspNode.readFile === "function", "NFS-P-006: node:fs/promises exposes readFile");

var pending = 2;
var timeoutId = 0;

function done() {
    pending = pending - 1;
    if (pending === 0) {
        clearTimeout(timeoutId);
        __jacDone();
    }
}

var cbFile = path.join(tmpDir, "cb.txt");
var cbSyncFlag = true;

// NFS-A-001 / NFS-A-002 / NFS-A-004
fs.writeFile(cbFile, "callback-data", "utf8", function(err) {
    assert(err === null, "NFS-A-001: writeFile callback err is null on success");
    assert(!cbSyncFlag, "NFS-A-004: writeFile callback executes asynchronously");
    fs.readFile(cbFile, "utf8", function(err2, data) {
        assert(err2 === null, "NFS-A-001: readFile callback err is null on success");
        assertEq(data, "callback-data", "NFS-A-002: callback readFile data matches");
        done();
    });
});
cbSyncFlag = false;

// NFS-A-003
fs.readFile(path.join(tmpDir, "missing-cb.txt"), "utf8", function(err3, data3) {
    assert(!!err3, "NFS-A-003: readFile missing path returns error");
    assertEq(err3.code, "ENOENT", "NFS-A-003: readFile missing path has ENOENT");
    assert(typeof data3 === "undefined", "NFS-A-003: readFile missing path data is undefined");
});

// NFS-P-001 / NFS-P-002 / NFS-P-004 / NFS-P-005 / NFS-P-006
var promiseFile = path.join(tmpDir, "promise.txt");
var pSyncFlag = true;
fs.promises.writeFile(promiseFile, "promise-data", { encoding: "utf8" })
    .then(function() {
        assert(!pSyncFlag, "NFS-P-004: Promise resolution is asynchronous");
        return fs.promises.readFile(promiseFile, { encoding: "utf8" });
    })
    .then(function(text) {
        assertEq(text, "promise-data", "NFS-P-001: promises write/read round-trip");
        return fs.promises.stat(promiseFile);
    })
    .then(function(st) {
        assert(st.isFile(), "NFS-P-002: promises.stat indicates file");
        return fs.promises.access(promiseFile, fs.constants.F_OK);
    })
    .then(function() {
        return fs.promises.readdir(tmpDir, { encoding: "utf8" });
    })
    .then(function(entries) {
        assert(Array.isArray(entries), "NFS-P-002: promises.readdir returns array");
        assert(entries.indexOf("promise.txt") >= 0, "NFS-P-002: promises.readdir includes created file");
        return fs.promises.unlink(promiseFile);
    })
    .then(function() {
        assert(!fs.existsSync(promiseFile), "NFS-P-002: promises.unlink removes file");
        return fspNode.writeFile(path.join(tmpDir, "nodefsp.txt"), "nodefsp", "utf8");
    })
    .then(function() {
        return fspNode.readFile(path.join(tmpDir, "nodefsp.txt"), "utf8");
    })
    .then(function(nodeFspText) {
        assertEq(nodeFspText, "nodefsp", "NFS-P-006: node:fs/promises read/write works");
        return fs.promises.readFile(path.join(tmpDir, "missing-promises.txt"), "utf8");
    })
    .then(function() {
        fail("NFS-P-003: expected readFile on missing path to reject");
    })
    .catch(function(e) {
        assertEq(e.code, "ENOENT", "NFS-P-003: promises missing path reject has ENOENT");
        done();
    });
pSyncFlag = false;

timeoutId = setTimeout(function() {
    fail("NFS-A/NFS-P async tests timed out with pending=" + pending);
}, 8000);
