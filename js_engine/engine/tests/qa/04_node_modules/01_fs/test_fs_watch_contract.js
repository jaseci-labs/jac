// FSW-001..006: fs.watch / FSWatcher contract (Node v24 subset)
var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/01_fs/test_fs_watch_contract.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

var fs = require("fs");
var path = require("path");
var os = require("os");

function assert(cond, msg) { __reg.assert(cond, msg); }

var tmpDir = path.join(os.tmpdir(), "jac_fs_watch_" + Date.now());
fs.mkdirSync(tmpDir, { recursive: true });

var got = [];
var w = fs.watch(tmpDir, function (ev, fn) {
    got.push(String(ev) + ":" + (fn === undefined ? "" : String(fn)));
});

assert(typeof w.close === "function", "FSW-001: close is function");
assert(typeof w.ref === "function", "FSW-001: ref is function");
assert(typeof w.unref === "function", "FSW-001: unref is function");

setTimeout(function () {
    var target = path.join(tmpDir, "probe.txt");
    fs.writeFileSync(target, "a");
    fs.writeFileSync(target, "b");

    setTimeout(function () {
        assert(got.length >= 1, "FSW-002: received at least one watch event");
        var hasChange = false;
        var i = 0;
        while (i < got.length) {
            if (got[i].indexOf("change:") === 0 || got[i].indexOf("rename:") === 0) { hasChange = true; }
            i = i + 1;
        }
        assert(hasChange, "FSW-002: event type is change or rename");

        var closed = false;
        w.on("close", function () { closed = true; });
        w.close();

        setTimeout(function () {
            assert(closed, "FSW-003: close event emitted");
            var w2 = fs.watch(tmpDir, { encoding: "utf8" }, function (ev, fn) {
                if (fn !== undefined) { assert(typeof fn === "string", "FSW-004: utf8 filename is string"); }
            });
            w2.close();
            __jacDone();
        }, 200);
    }, 300);
}, 100);
