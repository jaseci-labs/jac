// Plan: testing_plans/06_process_os_stdio/NODE_FS_COMPREHENSIVE_TEST_PLAN.md
// Coverage: ECG-2 (NFS-D-*, NFS-T-*)
var fs = require("fs");
var path = require("path");
var os = require("os");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/01_fs/test_fs_nfs_dirs_meta.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function fail(msg) {
    console.error("FAIL: " + msg);
    __reg.bump(); return;
}

function assert(cond, msg) {
    if (!cond) { fail(msg); }
}

function assertEq(actual, expected, msg) {
    if (actual !== expected) {
        fail(msg + " | expected: " + JSON.stringify(expected) + " | actual: " + JSON.stringify(actual));
    }
}

function expectThrow(fn, check, msg) {
    var threw = false;
    try {
        fn();
    } catch (e) {
        threw = true;
        if (check) { check(e); }
    }
    assert(threw, msg);
}

var tmpDir = path.join(os.tmpdir(), "js_engine_nfs_dirmeta_" + process.pid);
fs.mkdirSync(tmpDir, { recursive: true });
process.on("exit", function() {
    try { fs.rmSync(tmpDir, { recursive: true, force: true }); } catch (e) {}
});

// NFS-D-001 / NFS-D-002
var oneDir = path.join(tmpDir, "one");
fs.mkdirSync(oneDir);
assert(fs.existsSync(oneDir), "NFS-D-001: mkdirSync creates directory");
assert(fs.statSync(oneDir).isDirectory(), "NFS-D-001: created path is directory");

var deep = path.join(tmpDir, "deep", "a", "b");
var mkResult = fs.mkdirSync(deep, { recursive: true });
assert(fs.existsSync(deep), "NFS-D-002: mkdirSync recursive creates deep tree");
assert(typeof mkResult === "string" || typeof mkResult === "undefined", "NFS-D-002: mkdirSync recursive returns string|undefined");

// NFS-D-003
expectThrow(function() {
    fs.mkdirSync(oneDir);
}, function(e) {
    assertEq(e.code, "EEXIST", "NFS-D-003: mkdirSync existing dir throws EEXIST");
}, "NFS-D-003: mkdirSync existing dir should throw");

// NFS-D-004 / NFS-D-005
fs.writeFileSync(path.join(oneDir, "a.txt"), "a", "utf8");
fs.writeFileSync(path.join(oneDir, "b.txt"), "b", "utf8");
var entries = fs.readdirSync(oneDir);
assert(Array.isArray(entries), "NFS-D-004: readdirSync returns array");
assert(entries.indexOf("a.txt") >= 0 && entries.indexOf("b.txt") >= 0, "NFS-D-004: readdirSync includes created files");
var utf8Entries = fs.readdirSync(oneDir, { encoding: "utf8" });
assert(Array.isArray(utf8Entries), "NFS-D-005: readdirSync with encoding still returns array");
assert(typeof utf8Entries[0] === "string", "NFS-D-005: readdirSync entries are strings with utf8 encoding");

// NFS-D-006
expectThrow(function() {
    fs.readdirSync(path.join(tmpDir, "missing-dir"));
}, function(e) {
    assertEq(e.code, "ENOENT", "NFS-D-006: readdirSync missing dir has ENOENT");
}, "NFS-D-006: readdirSync missing dir should throw");

// NFS-D-007 / NFS-D-008
var emptyDir = path.join(tmpDir, "empty");
fs.mkdirSync(emptyDir);
fs.rmdirSync(emptyDir);
assert(!fs.existsSync(emptyDir), "NFS-D-007: rmdirSync removes empty directory");

var rmTree = path.join(tmpDir, "rm_tree");
fs.mkdirSync(path.join(rmTree, "child"), { recursive: true });
fs.writeFileSync(path.join(rmTree, "child", "f.txt"), "x", "utf8");
fs.rmSync(rmTree, { recursive: true, force: true });
assert(!fs.existsSync(rmTree), "NFS-D-008: rmSync recursive+force removes tree");

// NFS-T-001 / NFS-T-002
var statFile = path.join(tmpDir, "stat.txt");
fs.writeFileSync(statFile, "stat me", "utf8");
var st = fs.statSync(statFile);
assert(typeof st.size === "number" && st.size > 0, "NFS-T-001: statSync size is positive number");
assert(st.isFile(), "NFS-T-001: statSync isFile true");
assert(!st.isDirectory(), "NFS-T-001: statSync isDirectory false for file");
var stDir = fs.statSync(oneDir);
assert(stDir.isDirectory(), "NFS-T-002: statSync isDirectory true for dir");
assert(!stDir.isFile(), "NFS-T-002: statSync isFile false for dir");

// NFS-T-004
expectThrow(function() {
    fs.statSync(path.join(tmpDir, "missing-stat"));
}, function(e) {
    assertEq(e.code, "ENOENT", "NFS-T-004: statSync missing path has ENOENT");
}, "NFS-T-004: statSync missing path should throw");
expectThrow(function() {
    fs.lstatSync(path.join(tmpDir, "missing-lstat"));
}, function(e) {
    assertEq(e.code, "ENOENT", "NFS-T-004: lstatSync missing path has ENOENT");
}, "NFS-T-004: lstatSync missing path should throw");

// NFS-T-005
fs.accessSync(statFile, fs.constants.F_OK);
expectThrow(function() {
    fs.accessSync(path.join(tmpDir, "missing-access"), fs.constants.F_OK);
}, function(e) {
    assertEq(e.code, "ENOENT", "NFS-T-005: accessSync missing path has ENOENT");
}, "NFS-T-005: accessSync missing path should throw");

// NFS-T-006
fs.chmodSync(statFile, 0o644);
assert(fs.existsSync(statFile), "NFS-T-006: chmodSync does not remove file");
expectThrow(function() {
    fs.chmodSync(statFile, "not-a-mode");
}, function(e) {
    assert(e instanceof TypeError, "NFS-T-006: invalid mode type throws TypeError");
}, "NFS-T-006: chmodSync invalid mode type should throw");

// NFS-T-007 (version-gated)
var stBig = fs.statSync(statFile, { bigint: true });
if (typeof stBig.size === "bigint") {
    assert(typeof stBig.size === "bigint", "NFS-T-007: statSync bigint mode returns bigint size");
}

__jacDone();
