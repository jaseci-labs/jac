// FS-LIVE-001..004: work scheduled INSIDE an async fs callback (immediate,
// timer, child stdin write, nested readFile) must run. Regression: fs
// completions were delivered through the loop's unref'd wake handle, so with
// nothing else pending uv_run returned first and the callbacks ran in the
// post-loop flush — everything they scheduled was silently dropped. esbuild
// sends every >1MB transform from its temp-file writeFile callback, so vite's
// render-phase transform never got a reply ("Unexpected early exit").
// FS-BIG-001: writeFileSync(path, Buffer >= 256KB) (mmap-backed store) must not crash.
// FS-UTF8-001..003: strings are written as real UTF-8 (4-byte astral, 0x00 for
// U+0000), never the engine's internal CESU-8 / sentinel bytes.
var fs = require("fs"); var path = require("path"); var os = require("os"); var cp = require("child_process");
var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/01_fs/test_fs_callback_liveness.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }
function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(a, e, msg) { __reg.assertEq(a, e, msg); }

var tmpDir = path.join(os.tmpdir(), "js_engine_fs_live_" + process.pid);
fs.mkdirSync(tmpDir, { recursive: true });
process.on("exit", function () { try { fs.rmSync(tmpDir, { recursive: true, force: true }); } catch (e) {} });

// --- sync parts first ---
var big = Buffer.alloc(1200000, 65); big[777777] = 66;
var pBig = path.join(tmpDir, "big.bin");
fs.writeFileSync(pBig, big);
var back = fs.readFileSync(pBig);
assert(back.length === big.length && back[777777] === 66 && back.equals(big), "FS-BIG-001: 1.2MB Buffer round-trips through writeFileSync/readFileSync");

var text = "const a = \"café … 🚀 \u0000 end\";\n".repeat(3);
var pTxt = path.join(tmpDir, "t.js");
fs.writeFileSync(pTxt, text);
var bytes = fs.readFileSync(pTxt);
assert(bytes.equals(Buffer.from(text, "utf8")), "FS-UTF8-001: writeFileSync(string) bytes == Buffer.from(string)");
assertEq(bytes.indexOf(Buffer.from([0xf0, 0x9f, 0x9a, 0x80])) >= 0, true, "FS-UTF8-002: astral char written as a 4-byte UTF-8 sequence");
assertEq(bytes.indexOf(Buffer.from([0xed, 0xa0])) , -1, "FS-UTF8-002: no CESU-8 surrogate bytes in the file");
var nuls = 0; for (var i = 0; i < bytes.length; i++) if (bytes[i] === 0) nuls++;
assertEq(nuls, 3, "FS-UTF8-003: U+0000 written as a real NUL byte");

// --- async liveness: let the loop go idle, then schedule from inside fs callbacks ---
var pending = 4;
function one(msg) { assert(true, msg); if (--pending === 0) { clearTimeout(guard); __jacDone(); } }
var guard = setTimeout(function () {
    assert(false, "FS-LIVE-000: " + pending + " callback-scheduled task(s) never ran (loop exited early)");
    __jacDone();
}, 6000);
guard.unref();   // the guard itself must not be what keeps the loop alive

setTimeout(function () {
    var p1 = path.join(tmpDir, "w1.txt");
    fs.writeFile(p1, "x".repeat(200000), function (err) {
        assert(!err, "FS-LIVE-001: writeFile callback err=" + err);
        setImmediate(function () { one("FS-LIVE-001: setImmediate from fs callback ran"); });
        setTimeout(function () { one("FS-LIVE-002: setTimeout from fs callback ran"); }, 30);
        var c = cp.spawn("cat");
        c.stdout.on("data", function (d) { if (d.length === 1000) { one("FS-LIVE-003: child stdin write from fs callback answered"); c.kill(); } });
        c.stdin.write(Buffer.alloc(1000, 65));
        fs.readFile(p1, "utf8", function (e2, d) {
            assert(!e2 && d.length === 200000, "FS-LIVE-004: nested readFile len=" + (d && d.length));
            setImmediate(function () { one("FS-LIVE-004: setImmediate from nested fs callback ran"); });
        });
    });
}, 300);
