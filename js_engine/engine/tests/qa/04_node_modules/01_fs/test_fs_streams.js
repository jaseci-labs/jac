// FS-030/FS-031: createReadStream / createWriteStream
var fs   = require("fs");
var path = require("path");
var os   = require("os");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/01_fs/test_fs_streams.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

var tmpDir = path.join(os.tmpdir(), "js_engine_fs_strm_" + process.pid);
fs.mkdirSync(tmpDir, {recursive: true});
process.on("exit", function() {
    try { fs.rmSync(tmpDir, {recursive: true, force: true}); } catch(e) {}
});

var srcFile = path.join(tmpDir, "read_src.txt");
var dstFile = path.join(tmpDir, "write_dst.txt");
fs.writeFileSync(srcFile, "stream test content");

var passed = 0;
var total = 2;

function done() {
    passed++;
    if (passed >= total) __jacDone();
}

// FS-031: createWriteStream
var ws = fs.createWriteStream(dstFile, {encoding: "utf8"});
assert(typeof ws.write === "function", "FS-031: writeStream has write()");
assert(typeof ws.end === "function",   "FS-031: writeStream has end()");
ws.write("line1\n");
ws.write("line2\n");
ws.end(function() {
    var result = fs.readFileSync(dstFile, "utf8");
    assert(result.indexOf("line1") >= 0, "FS-031: writeStream content line1");
    assert(result.indexOf("line2") >= 0, "FS-031: writeStream content line2");
    done();
});

// FS-030: createReadStream
var rs = fs.createReadStream(srcFile, {encoding: "utf8"});
assert(typeof rs.on === "function",    "FS-030: readStream has on()");
var chunks = [];
rs.on("data", function(chunk) {
    chunks.push(chunk);
});
rs.on("end", function() {
    var full = chunks.join("");
    assertEq(full, "stream test content", "FS-030: readStream data event accumulates");
    done();
});
rs.on("error", function(err) {
    console.error("FAIL: FS-030 read stream error: " + err.message);
    __reg.bump(); return;
});

setTimeout(function() {
    console.error("FAIL: FS stream tests timed out (passed " + passed + "/" + total + ")");
    __reg.bump(); return;
}, 5000);
