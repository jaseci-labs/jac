// fs.promises.watch must reject on watch errors
var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase(
  "regression/04_node_modules/01_fs/test_fs_promises_watch_error.js"
);
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

var fs = require("fs");
var path = require("path");

function assert(cond, msg) { __reg.assert(cond, msg); }

var badPath = path.join(__dirname, "___no_such_watch_dir___", "missing");

var watchIterable = fs.promises.watch(badPath);
var watchIter = watchIterable;
if (watchIterable && typeof Symbol !== "undefined" && Symbol.asyncIterator &&
    typeof watchIterable[Symbol.asyncIterator] === "function") {
    watchIter = watchIterable[Symbol.asyncIterator]();
}
watchIter.next().then(
  function () {
    assert(false, "expected rejection for missing watch path");
    __jacDone();
  },
  function (err) {
    assert(err !== null && err !== undefined, "rejection carries error");
    __jacDone();
  }
);

setTimeout(function () {
  assert(false, "promises.watch error test timed out");
  __jacDone();
}, 5000);
