// Plan: testing_plans/06_process_os_stdio/NODE_FS_COMPREHENSIVE_TEST_PLAN.md
// Coverage: ECG-5 (NFS-R-*, NFS-E-*)
var fs = require("fs");
var path = require("path");
var os = require("os");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/01_fs/test_fs_nfs_streams_errors.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function fail(msg) {
    console.error("FAIL: " + msg);
    __reg.bump(); return;
}

function assert(cond, msg) {
    if (!cond) { fail(msg); }
}

function assertEq(actual, expected, msg) {
    if (actual !== expected) {
        fail(msg + " | expected: " + JSON.stringify(expected) + " | actual: " + JSON.stringify(actual));
    }
}

var tmpDir = path.join(os.tmpdir(), "js_engine_nfs_streams_" + process.pid);
fs.mkdirSync(tmpDir, { recursive: true });
process.on("exit", function() {
    try { fs.rmSync(tmpDir, { recursive: true, force: true }); } catch (e) {}
});

// NFS-E-001 / NFS-E-002 sanity on ENOENT shape
try {
    fs.readFileSync(path.join(tmpDir, "missing-enoent.txt"), "utf8");
    fail("NFS-E-001: expected readFileSync missing path to throw");
} catch (e1) {
    assertEq(e1.code, "ENOENT", "NFS-E-001: missing path throws ENOENT");
    assert(typeof e1.path === "string", "NFS-E-002: ENOENT error includes path");
}

// NFS-E-003 invalid flag
try {
    fs.writeFileSync(path.join(tmpDir, "bad-flag.txt"), "x", { flag: "not-a-flag" });
    fail("NFS-E-003: expected invalid flag to throw");
} catch (e2) {
    assert(!!e2, "NFS-E-003: invalid flag throws");
}

// NFS-R-002 / NFS-R-003
var writeDst = path.join(tmpDir, "wstream.txt");
var ws = fs.createWriteStream(writeDst, { encoding: "utf8" });
assert(typeof ws.write === "function", "NFS-R-002: createWriteStream exposes write");
assert(typeof ws.end === "function", "NFS-R-002: createWriteStream exposes end");
assert(typeof ws.on === "function", "NFS-R-002: createWriteStream exposes on");

var pending = 3;
var timeoutId = 0;

function done() {
    pending = pending - 1;
    if (pending === 0) {
        clearTimeout(timeoutId);
        __jacDone();
    }
}

ws.on("error", function(e3) {
    fail("NFS-R-004: unexpected write stream error: " + e3.message);
});
ws.write("line1\n");
ws.write("line2\n");
ws.end("line3\n");
ws.on("finish", function() {
    var text = fs.readFileSync(writeDst, "utf8");
    assert(text.indexOf("line1") >= 0 && text.indexOf("line2") >= 0 && text.indexOf("line3") >= 0,
        "NFS-R-002: createWriteStream writes expected content");
    done();
});

// NFS-R-001
var readSrc = path.join(tmpDir, "read-src.txt");
fs.writeFileSync(readSrc, "read-stream-content", "utf8");
var rs = fs.createReadStream(readSrc, { encoding: "utf8" });
var chunks = [];
rs.on("data", function(chunk) {
    chunks.push(chunk);
});
rs.on("end", function() {
    assertEq(chunks.join(""), "read-stream-content", "NFS-R-001: createReadStream data/end content");
    done();
});
rs.on("error", function(e4) {
    fail("NFS-R-001: unexpected read stream error: " + e4.message);
});

// NFS-R-004 missing-file stream error
var rsMissing = fs.createReadStream(path.join(tmpDir, "missing-read-stream.txt"), { encoding: "utf8" });
rsMissing.on("error", function(e5) {
    assertEq(e5.code, "ENOENT", "NFS-R-004: createReadStream missing file emits ENOENT");
    done();
});

timeoutId = setTimeout(function() {
    fail("NFS-R/NFS-E stream tests timed out with pending=" + pending);
}, 8000);
