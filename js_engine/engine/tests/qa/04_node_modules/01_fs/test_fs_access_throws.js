// Regression: fs.accessSync (and fs.promises.access) must THROW / REJECT with
// ENOENT on a missing path — previously it silently succeeded. Config searches
// that gate on `access` (`try { await access(p) } catch { continue }`, e.g.
// vite/lilconfig probing .postcssrc) then believed absent files existed and
// threw ENOENT from the follow-up readFile as an UNCAUGHT async rejection,
// contributing to `vite build`'s "Unexpected early exit". See VITE_ROADMAP.md.
var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/01_fs/test_fs_access_throws.js");
var __jacOrigExit = process.exit.bind(process);
function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }
function finish() { __reg.finalize(__jacOrigExit); }

var fs = require("fs");
var os = require("os");
var path = require("path");

var missing = path.join(os.tmpdir(), "jac_qa_no_such_file_" + Date.now() + ".xyz");
var present = __filename; // this test file certainly exists

// FS-ACC-001 — accessSync throws ENOENT for a missing path.
var threw = false, code = null;
try { fs.accessSync(missing); } catch (e) { threw = true; code = e && e.code; }
assert(threw, "FS-ACC-001: accessSync(missing) throws");
assertEq(code, "ENOENT", "FS-ACC-001: accessSync(missing) error.code is ENOENT");

// FS-ACC-002 — accessSync succeeds (no throw) for a present path.
var ok = true;
try { fs.accessSync(present); } catch (e) { ok = false; }
assert(ok, "FS-ACC-002: accessSync(present) does not throw");

// FS-ACC-003 — existsSync still returns booleans (must not have started throwing).
assertEq(fs.existsSync(missing), false, "FS-ACC-003: existsSync(missing) === false");
assertEq(fs.existsSync(present), true, "FS-ACC-003: existsSync(present) === true");

// FS-ACC-004 — promises.access rejects for missing, resolves for present, and
// the exact search idiom (catch → continue) sees the rejection.
Promise.resolve()
  .then(function () {
    return fs.promises.access(missing).then(
      function () { assert(false, "FS-ACC-004: promises.access(missing) unexpectedly resolved"); },
      function (e) { assertEq(e && e.code, "ENOENT", "FS-ACC-004: promises.access(missing) rejects ENOENT"); }
    );
  })
  .then(function () {
    return fs.promises.access(present).then(
      function () { assert(true, "FS-ACC-004: promises.access(present) resolves"); },
      function (e) { assert(false, "FS-ACC-004: promises.access(present) unexpectedly rejected: " + e); }
    );
  })
  .then(finish, function (e) { assert(false, "FS-ACC-004: chain threw: " + e); finish(); });
