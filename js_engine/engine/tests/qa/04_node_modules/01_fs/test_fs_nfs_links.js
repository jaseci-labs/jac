// Coverage: ECG-3 (NFS-L-*)
var fs = require("fs");
var path = require("path");
var os = require("os");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/01_fs/test_fs_nfs_links.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function fail(msg) {
    console.error("FAIL: " + msg);
    __reg.bump(); return;
}

function assert(cond, msg) {
    if (!cond) { fail(msg); }
}

function assertEq(actual, expected, msg) {
    if (actual !== expected) {
        fail(msg + " | expected: " + JSON.stringify(expected) + " | actual: " + JSON.stringify(actual));
    }
}

function expectThrow(fn, check, msg) {
    var threw = false;
    try {
        fn();
    } catch (e) {
        threw = true;
        if (check) { check(e); }
    }
    assert(threw, msg);
}

var tmpDir = path.join(os.tmpdir(), "js_engine_nfs_links_" + process.pid);
fs.mkdirSync(tmpDir, { recursive: true });
process.on("exit", function() {
    try { fs.rmSync(tmpDir, { recursive: true, force: true }); } catch (e) {}
});

// NFS-L-001
var src = path.join(tmpDir, "src.txt");
var dst = path.join(tmpDir, "dst.txt");
fs.writeFileSync(src, "rename-content", "utf8");
fs.renameSync(src, dst);
assert(!fs.existsSync(src), "NFS-L-001: renameSync removes source");
assert(fs.existsSync(dst), "NFS-L-001: renameSync creates destination");
assertEq(fs.readFileSync(dst, "utf8"), "rename-content", "NFS-L-001: renameSync preserves content");

// NFS-L-002
var copied = path.join(tmpDir, "copied.txt");
fs.copyFileSync(dst, copied);
assert(fs.existsSync(copied), "NFS-L-002: copyFileSync creates destination");
assertEq(fs.readFileSync(copied, "utf8"), "rename-content", "NFS-L-002: copyFileSync preserves content");
var exclDest = path.join(tmpDir, "copy-excl.txt");
fs.writeFileSync(exclDest, "already here", "utf8");
expectThrow(function() {
    fs.copyFileSync(dst, exclDest, fs.constants.COPYFILE_EXCL);
}, function(e) {
    assert(e.code === "EEXIST" || e.code === "ERR_FS_COPYFILE_EEXIST", "NFS-L-002: copyFileSync COPYFILE_EXCL rejects existing destination");
}, "NFS-L-002: copyFileSync COPYFILE_EXCL should throw");

// NFS-L-003 / NFS-L-004
var target = path.join(tmpDir, "target.txt");
var link = path.join(tmpDir, "link.txt");
fs.writeFileSync(target, "target-data", "utf8");
var symlinkSupported = true;
try {
    fs.symlinkSync(target, link);
} catch (e) {
    symlinkSupported = false;
    // On restricted environments this is allowed to fail due to permissions.
    assert(e.code === "EPERM" || e.code === "EACCES" || e.code === "ENOSYS", "NFS-L-003: symlinkSync only skips on expected platform restrictions");
}
if (symlinkSupported) {
    var linkTarget = fs.readlinkSync(link);
    assertEq(linkTarget, target, "NFS-L-003: readlinkSync returns symlink target");
    var rp = fs.realpathSync(link);
    assert(typeof rp === "string" && rp.length > 0, "NFS-L-004: realpathSync returns non-empty path");
    assertEq(fs.readFileSync(link, "utf8"), "target-data", "NFS-L-004: reading through symlink reaches target");
}

// NFS-L-005
expectThrow(function() {
    fs.readlinkSync(path.join(tmpDir, "missing-link"));
}, function(e) {
    assertEq(e.code, "ENOENT", "NFS-L-005: readlinkSync missing path has ENOENT");
}, "NFS-L-005: readlinkSync missing path should throw");
expectThrow(function() {
    fs.realpathSync(path.join(tmpDir, "missing-realpath"));
}, function(e) {
    assertEq(e.code, "ENOENT", "NFS-L-005: realpathSync missing path has ENOENT");
}, "NFS-L-005: realpathSync missing path should throw");

// NFS-L-006
expectThrow(function() {
    fs.renameSync(1, 2);
}, function(e) {
    assert(e instanceof TypeError, "NFS-L-006: renameSync invalid argument types throw TypeError");
}, "NFS-L-006: renameSync invalid argument types should throw");

__jacDone();
