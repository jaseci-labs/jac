// FS-001 through FS-013: fs sync operations
var fs   = require("fs");
var path = require("path");
var os   = require("os");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/01_fs/test_fs_sync.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

// Use a unique temp directory to avoid cross-test contamination
var tmpDir = path.join(os.tmpdir(), "js_engine_fs_test_" + process.pid);
fs.mkdirSync(tmpDir, {recursive: true});

function cleanup() {
    try { fs.rmSync(tmpDir, {recursive: true, force: true}); } catch(e) {}
}
process.on("exit", cleanup);

var testFile = path.join(tmpDir, "test.txt");
var testFile2 = path.join(tmpDir, "test2.txt");

// FS-002: writeFileSync (test before read)
fs.writeFileSync(testFile, "hello world", "utf8");
assert(fs.existsSync(testFile), "FS-002: file created after writeFileSync");

// FS-001: readFileSync
var content = fs.readFileSync(testFile, "utf8");
assertEq(content, "hello world", "FS-001: readFileSync content matches");
// Buffer mode
var buf = fs.readFileSync(testFile);
assert(Buffer.isBuffer(buf) || (typeof buf === "object" && buf !== null),
    "FS-001: readFileSync without encoding returns Buffer");
// Non-existent file throws
var threw = false;
try { fs.readFileSync(path.join(tmpDir, "nonexistent.txt"), "utf8"); } catch(e) { threw = true; }
assert(threw, "FS-001: readFileSync non-existent throws");

// FS-002: writeFileSync overwrite
fs.writeFileSync(testFile, "overwritten", "utf8");
assertEq(fs.readFileSync(testFile, "utf8"), "overwritten", "FS-002: overwrite");

// FS-003: appendFileSync
fs.writeFileSync(testFile, "line1\n", "utf8");
fs.appendFileSync(testFile, "line2\n", "utf8");
var appended = fs.readFileSync(testFile, "utf8");
assertEq(appended, "line1\nline2\n", "FS-003: appendFileSync appends");
// create if absent
var appendNew = path.join(tmpDir, "append_new.txt");
fs.appendFileSync(appendNew, "first", "utf8");
assert(fs.existsSync(appendNew), "FS-003: appendFileSync creates file");

// FS-004: existsSync
assert(fs.existsSync(testFile),          "FS-004: file exists");
assert(!fs.existsSync(path.join(tmpDir,"missing.txt")), "FS-004: missing = false");
assert(fs.existsSync(tmpDir),            "FS-004: dir exists = true");

// FS-006: statSync
var stat = fs.statSync(testFile);
assert(typeof stat.size === "number",    "FS-006: stat.size is number");
assert(stat.size > 0,                    "FS-006: stat.size > 0");
assert(stat.isFile(),                    "FS-006: isFile()");
assert(!stat.isDirectory(),              "FS-006: !isDirectory() for file");
var dirStat = fs.statSync(tmpDir);
assert(dirStat.isDirectory(),            "FS-006: isDirectory()");
assert(!dirStat.isFile(),               "FS-006: !isFile() for dir");

// FS-008: mkdirSync
var subDir = path.join(tmpDir, "subdir");
fs.mkdirSync(subDir);
assert(fs.existsSync(subDir),           "FS-008: mkdirSync creates dir");
assert(fs.statSync(subDir).isDirectory(),"FS-008: created dir isDirectory");
// recursive
var deepDir = path.join(tmpDir, "a", "b", "c");
fs.mkdirSync(deepDir, {recursive: true});
assert(fs.existsSync(deepDir),          "FS-008: mkdirSync recursive");
// already exists - should throw without recursive
var threwMkdir = false;
try { fs.mkdirSync(subDir); } catch(e) { threwMkdir = true; }
assert(threwMkdir, "FS-008: mkdirSync existing dir throws");

// FS-007: readdirSync
fs.writeFileSync(path.join(subDir, "a.txt"), "a");
fs.writeFileSync(path.join(subDir, "b.txt"), "b");
var entries = fs.readdirSync(subDir);
assert(Array.isArray(entries),           "FS-007: readdirSync returns array");
assert(entries.indexOf("a.txt") >= 0,    "FS-007: a.txt in listing");
assert(entries.indexOf("b.txt") >= 0,    "FS-007: b.txt in listing");
// non-existent dir throws
var threwDir = false;
try { fs.readdirSync(path.join(tmpDir, "nodir")); } catch(e) { threwDir = true; }
assert(threwDir, "FS-007: readdirSync non-existent throws");

// FS-010: renameSync / copyFileSync
var src = path.join(tmpDir, "src.txt");
fs.writeFileSync(src, "rename me");
var dst = path.join(tmpDir, "dst.txt");
fs.renameSync(src, dst);
assert(!fs.existsSync(src),             "FS-010: renameSync removes source");
assert(fs.existsSync(dst),              "FS-010: renameSync creates dest");
assertEq(fs.readFileSync(dst, "utf8"), "rename me", "FS-010: renameSync content preserved");
// copyFileSync
fs.copyFileSync(dst, testFile2);
assert(fs.existsSync(testFile2),        "FS-010: copyFileSync creates dest");
assertEq(fs.readFileSync(testFile2,"utf8"), "rename me", "FS-010: copyFileSync content");

// FS-005: unlinkSync
fs.unlinkSync(testFile2);
assert(!fs.existsSync(testFile2),       "FS-005: unlinkSync removes file");
// non-existent file throws
var threwUnlink = false;
try { fs.unlinkSync(path.join(tmpDir,"nope.txt")); } catch(e) { threwUnlink = true; }
assert(threwUnlink, "FS-005: unlinkSync non-existent throws");

// FS-009: rmdirSync / rmSync
var rmDir = path.join(tmpDir, "rmme");
fs.mkdirSync(rmDir);
fs.rmdirSync(rmDir);
assert(!fs.existsSync(rmDir),          "FS-009: rmdirSync removes empty dir");
// rmSync recursive
var rmRecDir = path.join(tmpDir, "rmrec");
fs.mkdirSync(rmRecDir);
fs.writeFileSync(path.join(rmRecDir, "f.txt"), "x");
fs.rmSync(rmRecDir, {recursive: true});
assert(!fs.existsSync(rmRecDir),       "FS-009: rmSync recursive removes dir+contents");

// FS-011: chmodSync — just verify it doesn't throw
fs.chmodSync(testFile, 0o644);
assert(fs.existsSync(testFile),        "FS-011: chmodSync no crash");

// FS-012: symlinkSync / readlinkSync / realpathSync
var linkTarget = path.join(tmpDir, "linkTarget.txt");
var linkPath   = path.join(tmpDir, "link.txt");
fs.writeFileSync(linkTarget, "target content");
var symlinkThrew = false;
try {
    fs.symlinkSync(linkTarget, linkPath);
} catch(e) {
    symlinkThrew = true;
}
if (!symlinkThrew) {
    assert(fs.existsSync(linkPath),        "FS-012: symlink exists");
    var linkDest = fs.readlinkSync(linkPath);
    assertEq(linkDest, linkTarget,         "FS-012: readlinkSync returns target");
    var real = fs.realpathSync(linkPath);
    assertEq(typeof real, "string",        "FS-012: realpathSync returns string");
}

// FS-013: accessSync / lstatSync
fs.accessSync(testFile, fs.constants.F_OK); // should not throw
var lstat = fs.lstatSync(testFile);
assert(lstat.isFile(),                     "FS-013: lstatSync isFile");

__jacDone();
