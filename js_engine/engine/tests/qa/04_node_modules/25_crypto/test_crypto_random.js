// CRP-020..CRP-028: randomBytes, randomUUID, randomInt, timingSafeEqual
var crypto = require("node:crypto");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase(
    "regression/04_node_modules/25_crypto/test_crypto_random.js"
);
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }
function assert(cond, msg) { __reg.assert(cond, msg); }

var rb = crypto.randomBytes(16);
assert(rb && rb.length === 16, "CRP-020: randomBytes length");

var rb2 = crypto.randomBytes(16);
var same = true;
for (var i = 0; i < 16; i++) {
    if (rb[i] !== rb2[i]) { same = false; break; }
}
assert(!same, "CRP-021: randomBytes not identical");

var uuid = crypto.randomUUID();
assert(typeof uuid === "string" && uuid.length === 36, "CRP-022: randomUUID format");
assert(uuid[14] === "4", "CRP-023: randomUUID version nibble");

var ri = crypto.randomInt(10, 20);
assert(ri >= 10 && ri < 20, "CRP-024: randomInt range");

var a = crypto.randomBytes(4);
var b = crypto.randomBytes(4);
b[0] = a[0];
assert(crypto.timingSafeEqual(a, a), "CRP-025: timingSafeEqual self");
assert(!crypto.timingSafeEqual(a, b), "CRP-026: timingSafeEqual diff");

var threw = false;
try {
    crypto.timingSafeEqual(a, crypto.randomBytes(3));
} catch (e) {
    threw = e instanceof RangeError;
}
assert(threw, "CRP-027: timingSafeEqual length mismatch throws");

__jacDone();
