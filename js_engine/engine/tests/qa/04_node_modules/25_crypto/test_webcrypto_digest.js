// WCR-001..WCR-008: globalThis.crypto + subtle.digest
var crypto = require("node:crypto");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase(
    "regression/04_node_modules/25_crypto/test_webcrypto_digest.js"
);
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }
function assert(cond, msg) { __reg.assert(cond, msg); }

var wc = crypto.webcrypto;
assert(typeof wc !== "undefined", "WCR-001: crypto.webcrypto");
assert(typeof wc.subtle !== "undefined", "WCR-002: subtle");
assert(typeof wc.getRandomValues === "function", "WCR-003: getRandomValues");

var done = false;
var helloBytes = Buffer.from("hello");
wc.subtle
    .digest("SHA-256", helloBytes)
    .then(function (buf) {
        var u8 = new Uint8Array(buf);
        var hex = "";
        for (var i = 0; i < u8.length; i++) {
            var b = u8[i].toString(16);
            hex += b.length === 1 ? "0" + b : b;
        }
        assert(
            hex ===
                "2cf24dba5fb0a30e26e83b2ac5b9e29e1b161e5c1fa7425e73043362938b9824",
            "WCR-004: subtle.digest SHA-256"
        );
        var ta = new Uint8Array(8);
        wc.getRandomValues(ta);
        assert(ta.length === 8, "WCR-005: getRandomValues length");
        var u = wc.randomUUID();
        assert(u.length === 36, "WCR-006: webcrypto randomUUID");
        done = true;
        __jacDone();
    })
    .catch(function (e) {
        assert(false, "WCR-ERR: " + e);
        __jacDone();
    });

setTimeout(function () {
    if (!done) {
        assert(false, "WCR-007: async digest timeout");
        __jacDone();
    }
}, 3000);
