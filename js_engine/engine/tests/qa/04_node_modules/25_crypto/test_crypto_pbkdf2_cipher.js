// CRP-030..CRP-040: pbkdf2, AES-GCM round-trip
var crypto = require("node:crypto");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase(
    "regression/04_node_modules/25_crypto/test_crypto_pbkdf2_cipher.js"
);
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }
function assert(cond, msg) { __reg.assert(cond, msg); }

// RFC 6070 test vector 1 (PBKDF2-HMAC-SHA1)
var derived = crypto.pbkdf2Sync("password", "salt", 1, 20, "sha1");
assert(
    derived.toString("hex") === "0c60c80f961f0e71f3a9b524af6012062fe037a6",
    "CRP-030: pbkdf2Sync sha1 vector"
);

var key = crypto.randomBytes(32);
var iv = crypto.randomBytes(12);
var plain = Buffer.from("js_engine crypto aes-256-gcm", "utf8");
var cipher = crypto.createCipheriv("aes-256-gcm", key, iv);
var enc = Buffer.concat([cipher.update(plain), cipher.final()]);
var tag = cipher.getAuthTag();

var decipher = crypto.createDecipheriv("aes-256-gcm", key, iv);
decipher.setAuthTag(tag);
var dec = Buffer.concat([decipher.update(enc), decipher.final()]);
assert(dec.toString("utf8") === plain.toString("utf8"), "CRP-031: aes-256-gcm round-trip");

assert(crypto.getCiphers().indexOf("aes-256-gcm") >= 0, "CRP-032: getCiphers");

__jacDone();
