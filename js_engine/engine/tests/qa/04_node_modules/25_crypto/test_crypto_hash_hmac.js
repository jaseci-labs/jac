// CRP-001..CRP-012: createHash, hash, createHmac — Node v22 vectors
var crypto = require("node:crypto");
var cryptoBare = require("crypto");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase(
    "regression/04_node_modules/25_crypto/test_crypto_hash_hmac.js"
);
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }
function assert(cond, msg) { __reg.assert(cond, msg); }

assert(typeof crypto.createHash === "function", "CRP-001: createHash");
assert(typeof cryptoBare.createHash === "function", "CRP-002: bare crypto");

var sha256Hello =
    "2cf24dba5fb0a30e26e83b2ac5b9e29e1b161e5c1fa7425e73043362938b9824";
assert(
    crypto.createHash("sha256").update("hello").digest("hex") === sha256Hello,
    "CRP-003: sha256 hello"
);
assert(
    crypto.hash("sha256", "hello", "hex") === sha256Hello,
    "CRP-004: hash oneshot"
);

var sha1Empty = "da39a3ee5e6b4b0d3255bfef95601890afd80709";
assert(
    crypto.createHash("sha1").update("").digest("hex") === sha1Empty,
    "CRP-005: sha1 empty"
);

var hmacSha256 = crypto
    .createHmac("sha256", "key")
    .update("message")
    .digest("hex");
assert(
    hmacSha256 ===
        "6e9ef29b75fffc5b7abae527d58fdadb2fe42e7219011976917343065f58ed4a",
    "CRP-006: hmac-sha256 key+message"
);

var chunked = crypto.createHash("sha256");
chunked.update("hel");
chunked.update("lo");
assert(chunked.digest("hex") === sha256Hello, "CRP-007: chunked update");

assert(
    crypto.getHashes().indexOf("sha256") >= 0,
    "CRP-008: getHashes includes sha256"
);

__jacDone();
