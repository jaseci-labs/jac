var util = require("util");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/09_util/test_util_advanced_gated.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

// NUTIL-V-001 system error helpers
if (typeof util.getSystemErrorName === "function") {
    var n = util.getSystemErrorName(-2);
    assertEq(typeof n, "string", "NUTIL-V-001: getSystemErrorName returns string");
    assert(n.length > 0, "NUTIL-V-001: getSystemErrorName non-empty");
}
if (typeof util.getSystemErrorMap === "function") {
    var m = util.getSystemErrorMap();
    assert(m && typeof m.get === "function", "NUTIL-V-001: getSystemErrorMap is Map-like");
}
if (typeof util.getSystemErrorMessage === "function") {
    var msg = util.getSystemErrorMessage(-2);
    assertEq(typeof msg, "string", "NUTIL-V-001: getSystemErrorMessage returns string");
}

// NUTIL-V-002 toUSVString
if (typeof util.toUSVString === "function") {
    assertEq(util.toUSVString("a\uD800b"), "a\uFFFDb", "NUTIL-V-002: lone surrogate replaced");
}

// NUTIL-V-004 stripVT / styleText
if (typeof util.stripVTControlCharacters === "function") {
    assertEq(util.stripVTControlCharacters("\u001B[31mhi\u001B[0m"), "hi", "NUTIL-V-004: stripVT removes SGR");
}
if (typeof util.styleText === "function") {
    var st = util.styleText("red", "x");
    assertEq(typeof st, "string", "NUTIL-V-004: styleText returns string");
    assert(st.indexOf("x") >= 0, "NUTIL-V-004: styleText contains payload");
}

// NUTIL-V-005 MIME
if (typeof util.MIMEType === "function") {
    var mt = new util.MIMEType("text/html;charset=utf-8");
    assertEq(mt.essence, "text/html", "NUTIL-V-005: MIMEType essence");
}
if (typeof util.MIMEParams === "function") {
    var mp = new util.MIMEParams();
    mp.set("a", "1");
    assertEq(mp.get("a"), "1", "NUTIL-V-005: MIMEParams set/get");
}

// NUTIL-V-003 transferable abort (smoke when globals exist)
if (typeof util.transferableAbortSignal === "function" && typeof AbortController !== "undefined") {
    var ac = new AbortController();
    var sig = util.transferableAbortSignal(ac.signal);
    assert(sig && typeof sig.aborted === "boolean", "NUTIL-V-003: transferableAbortSignal shape");
}
// util.aborted(signal, resource) is Promise-based in Node 20+; omit one-arg smoke here (NUTIL-V-003).

