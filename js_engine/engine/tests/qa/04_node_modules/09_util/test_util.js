// testing_plans/14_utilities_diagnostics/NODE_UTIL_COMPREHENSIVE_TEST_PLAN.md — legacy smoke (UTIL-*)
// UTIL-001 through UTIL-011: util module
var util = require("util");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/09_util/test_util.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

// UTIL-001: inspect
assertEq(typeof util.inspect({}), "string",         "UTIL-001: inspect returns string");
assert(util.inspect({a:1}).indexOf("a") >= 0,        "UTIL-001: inspect object");
assert(util.inspect([1,2,3]).indexOf("1") >= 0,      "UTIL-001: inspect array");
assert(util.inspect({a:{b:{c:1}}}).indexOf("c") >= 0,"UTIL-001: inspect nested");
var deep = util.inspect({a:1}, {depth:0});
assertEq(typeof deep, "string",                      "UTIL-001: inspect with depth option");

// UTIL-002: format
assertEq(util.format("%s world", "hello"), "hello world",  "UTIL-002: %s format");
assertEq(util.format("%d + %d = %d", 1, 2, 3), "1 + 2 = 3","UTIL-002: %d format");
assertEq(util.format("%j", {a:1}), '{"a":1}',              "UTIL-002: %j format");
assertEq(util.format("%d%%", 100),  "100%",                 "UTIL-002: %% literal in mixed format");
assertEq(util.format("a", "b", "c"), "a b c",              "UTIL-002: extra args appended");

// UTIL-003: promisify
function nodeStyleCb(x, cb) {
    if (x < 0) return cb(new Error("negative"));
    cb(null, x * 2);
}
var promisified = util.promisify(nodeStyleCb);
assert(typeof promisified === "function",              "UTIL-003: promisify returns function");
assert(typeof promisified(5).then === "function",      "UTIL-003: promisified returns Promise");

var pDone = false;
promisified(5).then(function(val) {
    assertEq(val, 10, "UTIL-003: promisified resolves with value");
    pDone = true;
});
promisified(-1).catch(function(e) {
    assert(e instanceof Error, "UTIL-003: promisified rejects on error");
});

// UTIL-004: callbackify
async function asyncFn(x) { return x * 3; }
if (typeof util.callbackify === "function") {
    var callbackified = util.callbackify(asyncFn);
    assert(typeof callbackified === "function", "UTIL-004: callbackify returns function");
    callbackified(4, function(err, result) {
        assert(!err, "UTIL-004: callbackified no error");
        assertEq(result, 12, "UTIL-004: callbackified result");
    });
}

// UTIL-005: inherits
function Parent() {}
Parent.prototype.greet = function() { return "hello"; };
function Child() { Parent.call(this); }
util.inherits(Child, Parent);
var child = new Child();
assertEq(child.greet(), "hello",             "UTIL-005: inherits proto method");
assert(child instanceof Parent,              "UTIL-005: inherits instanceof");
assert(Child.super_ === Parent,              "UTIL-005: inherits super_");

// UTIL-006: deprecate / debuglog
if (typeof util.deprecate === "function") {
    var deprecated = util.deprecate(function() { return 42; }, "deprecated fn");
    assertEq(typeof deprecated, "function",  "UTIL-006: deprecate returns function");
    assertEq(deprecated(), 42,               "UTIL-006: deprecated fn still works");
}
if (typeof util.debuglog === "function") {
    var dbg = util.debuglog("test");
    assertEq(typeof dbg, "function",         "UTIL-006: debuglog returns function");
}

// UTIL-007: parseArgs — may be absent
if (typeof util.parseArgs === "function") {
    var parsed = util.parseArgs({
        args: ["--foo", "bar", "--baz", "42"],
        options: {
            foo: {type: "string"},
            baz: {type: "string"}
        }
    });
    assert(typeof parsed.values === "object", "UTIL-007: parseArgs returns .values");
}

// UTIL-008: isDeepStrictEqual
if (typeof util.isDeepStrictEqual === "function") {
    assert(util.isDeepStrictEqual({a:1},{a:1}),      "UTIL-008: deep equal objects");
    assert(util.isDeepStrictEqual([1,2,3],[1,2,3]),  "UTIL-008: deep equal arrays");
    assert(!util.isDeepStrictEqual({a:1},{a:2}),     "UTIL-008: deep not equal");
    assert(util.isDeepStrictEqual(NaN, NaN),         "UTIL-008: NaN deep equal NaN");
    assert(!util.isDeepStrictEqual(+0, -0),          "UTIL-008: +0 not deep equal -0");
}

// UTIL-009: types.*
if (util.types) {
    var types = util.types;
    assert(types.isDate(new Date()),            "UTIL-009: isDate(Date)");
    assert(!types.isDate({}),                   "UTIL-009: isDate({})=false");
    assert(types.isMap(new Map()),              "UTIL-009: isMap(Map)");
    assert(types.isSet(new Set()),              "UTIL-009: isSet(Set)");
    assert(types.isPromise(Promise.resolve()),  "UTIL-009: isPromise(Promise)");
    assert(types.isNativeError(new Error()),    "UTIL-009: isNativeError(Error)");
    assert(!types.isNativeError({}),            "UTIL-009: isNativeError({})=false");
}

// UTIL-010: TextEncoder / TextDecoder
if (typeof util.TextEncoder !== "undefined") {
    var enc = new util.TextEncoder();
    var encoded = enc.encode("hello");
    assert(encoded instanceof Uint8Array || typeof encoded === "object", "UTIL-010: TextEncoder encodes");
    var dec = new util.TextDecoder("utf-8");
    var decoded = dec.decode(encoded);
    assertEq(decoded, "hello", "UTIL-010: TextDecoder decodes");
} else if (typeof TextEncoder !== "undefined") {
    var enc2 = new TextEncoder();
    var enc2d = enc2.encode("world");
    var dec2 = new TextDecoder();
    assertEq(dec2.decode(enc2d), "world", "UTIL-010: global TextEncoder/Decoder");
}

// UTIL-011: Legacy predicates
if (typeof util.isNull === "function") {
    assert(util.isNull(null),                   "UTIL-011: isNull(null)");
    assert(!util.isNull(0),                     "UTIL-011: isNull(0)=false");
    assert(util.isUndefined(undefined),         "UTIL-011: isUndefined");
    assert(util.isArray([]),                    "UTIL-011: isArray");
    assert(util.isPrimitive(42),                "UTIL-011: isPrimitive(number)");
    assert(!util.isPrimitive({}),               "UTIL-011: isPrimitive(obj)=false");
}

// Wait for async operations
setTimeout(function() {
    assert(pDone, "UTIL-003: promisified eventually resolved");
    __jacDone();
}, 500);
