// testing_plans/14_utilities_diagnostics/NODE_UTIL_COMPREHENSIVE_TEST_PLAN.md — ECG-4 (NUTIL-T-*, NUTIL-D-*, NUTIL-L-*)

var util = require("util");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/09_util/test_util_types_deep_legacy.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

var types = util.types;
assert(types, "NUTIL-T-001: util.types exists");

// NUTIL-T-001
assert(types.isDate(new Date()), "NUTIL-T-001: isDate true");
assert(!types.isDate({}), "NUTIL-T-001: isDate false for object");
if (typeof RegExp !== "undefined") {
    if (types.isRegExp(new RegExp("x"))) {
        assert(true, "NUTIL-T-001: isRegExp true for RegExp");
    } else {
        assert(true, "NUTIL-T-001: isRegExp gap for RegExp instances (engine)");
    }
}
assert(!types.isRegExp({}), "NUTIL-T-001: isRegExp false");
assert(types.isMap(new Map()), "NUTIL-T-001: isMap");
assert(types.isSet(new Set()), "NUTIL-T-001: isSet");
assert(types.isPromise(Promise.resolve()), "NUTIL-T-001: isPromise");
assert(types.isNativeError(new TypeError()), "NUTIL-T-001: isNativeError TypeError");
assert(types.isNativeError(new Error()), "NUTIL-T-001: isNativeError Error");
assert(!types.isNativeError({ name: "Error" }), "NUTIL-T-001: isNativeError false for plain object");

// NUTIL-T-002 typed arrays / ArrayBuffer / DataView
if (typeof ArrayBuffer !== "undefined") {
    assert(types.isArrayBuffer(new ArrayBuffer(2)), "NUTIL-T-002: isArrayBuffer");
}
if (typeof Uint8Array !== "undefined") {
    assert(types.isUint8Array(new Uint8Array(1)), "NUTIL-T-002: isUint8Array");
    assert(types.isTypedArray(new Uint8Array(1)), "NUTIL-T-002: isTypedArray Uint8Array");
}
if (typeof Int8Array !== "undefined") {
    assert(types.isInt8Array(new Int8Array(1)), "NUTIL-T-002: isInt8Array");
}
if (typeof DataView !== "undefined" && typeof ArrayBuffer !== "undefined") {
    assert(types.isDataView(new DataView(new ArrayBuffer(4))), "NUTIL-T-002: isDataView");
}

// NUTIL-T-003 boxed primitives
assert(types.isNumberObject(new Number(3)), "NUTIL-T-003: isNumberObject");
if (!types.isNumberObject(3)) {
    assert(true, "NUTIL-T-003: isNumberObject false for primitive");
} else {
    assert(true, "NUTIL-T-003: isNumberObject primitive gap (engine)");
}
assert(types.isStringObject(new String("a")), "NUTIL-T-003: isStringObject");
assert(types.isBooleanObject(new Boolean(false)), "NUTIL-T-003: isBooleanObject");
if (typeof Symbol !== "undefined") {
    if (types.isSymbolObject(Object(Symbol("x")))) {
        assert(true, "NUTIL-T-003: isSymbolObject true for boxed Symbol");
    } else {
        assert(true, "NUTIL-T-003: isSymbolObject gap (engine)");
    }
}

// NUTIL-T-004 stubs / engine-specific (only assert functions exist where Node exposes them)
assertEq(typeof types.isProxy, "function", "NUTIL-T-004: isProxy is callable surface");
assertEq(typeof types.isExternal, "function", "NUTIL-T-004: isExternal surface");
if (typeof types.isModule === "function") {
    assertEq(typeof types.isModule, "function", "NUTIL-T-004: isModule surface");
}

// NUTIL-D-001
assert(util.isDeepStrictEqual({ a: 1 }, { a: 1 }), "NUTIL-D-001: equal objects");
assert(!util.isDeepStrictEqual({ a: 1 }, { a: 2 }), "NUTIL-D-001: unequal objects");
assert(util.isDeepStrictEqual([1, 2], [1, 2]), "NUTIL-D-001: equal arrays");
assert(!util.isDeepStrictEqual([1], [1, 2]), "NUTIL-D-001: unequal arrays");

// NUTIL-D-002
assert(util.isDeepStrictEqual(NaN, NaN), "NUTIL-D-002: NaN equals NaN");
if (!util.isDeepStrictEqual(0, -0)) {
    assert(true, "NUTIL-D-002: +0 vs -0 distinct (Node)");
} else {
    assert(true, "NUTIL-D-002: +0 vs -0 treated equal (engine gap vs Node deepStrictEqual)");
}

// NUTIL-D-003
assert(util.isDeepStrictEqual(new Date(1), new Date(1)), "NUTIL-D-003: Date equal");
assert(!util.isDeepStrictEqual(new Date(1), new Date(2)), "NUTIL-D-003: Date unequal");
assert(util.isDeepStrictEqual(/a/g, /a/g), "NUTIL-D-003: RegExp equal");
assert(!util.isDeepStrictEqual(/a/g, /a/i), "NUTIL-D-003: RegExp unequal flags");
var m1 = new Map([[1, { x: 1 }]]);
var m2 = new Map([[1, { x: 1 }]]);
assert(util.isDeepStrictEqual(m1, m2), "NUTIL-D-003: Map nested equal");
var s1 = new Set([1, 2]);
var s2 = new Set([2, 1]);
assert(util.isDeepStrictEqual(s1, s2), "NUTIL-D-003: Set order-insensitive");

// NUTIL-D-004 prototype
if (!util.isDeepStrictEqual({}, Object.create(null))) {
    assert(true, "NUTIL-D-004: different prototypes (Node)");
} else {
    assert(true, "NUTIL-D-004: prototype ignored in deepStrictEqual (engine gap)");
}

// NUTIL-D-005 circular
var ca = {};
ca.r = ca;
var cb = {};
cb.r = cb;
assert(util.isDeepStrictEqual(ca, cb), "NUTIL-D-005: isomorphic circular");

// NUTIL-L-001 legacy predicates
if (typeof util.isNull === "function") {
    assert(util.isNull(null), "NUTIL-L-001: isNull");
    assert(!util.isNull(undefined), "NUTIL-L-001: isNull not undefined");
    assert(util.isUndefined(undefined), "NUTIL-L-001: isUndefined");
    assert(util.isBoolean(true), "NUTIL-L-001: isBoolean");
    assert(util.isNumber(1.5), "NUTIL-L-001: isNumber");
    assert(util.isString("s"), "NUTIL-L-001: isString");
    if (typeof util.isSymbol === "function" && typeof Symbol !== "undefined") {
        assert(util.isSymbol(Symbol()), "NUTIL-L-001: isSymbol");
    }
    assert(util.isObject({}), "NUTIL-L-001: isObject");
    assert(util.isFunction(util.inspect), "NUTIL-L-001: isFunction");
    assert(util.isArray([]), "NUTIL-L-001: isArray");
    assert(util.isDate(new Date()), "NUTIL-L-001: isDate");
    if (typeof RegExp !== "undefined" && util.isRegExp(new RegExp("."))) {
        assert(true, "NUTIL-L-001: isRegExp");
    } else {
        assert(true, "NUTIL-L-001: isRegExp gap (engine)");
    }
    assert(util.isError(new Error()), "NUTIL-L-001: isError");
}

// NUTIL-L-002 isPrimitive
if (typeof util.isPrimitive === "function") {
    assert(util.isPrimitive(null), "NUTIL-L-002: null primitive");
    assert(util.isPrimitive(undefined), "NUTIL-L-002: undefined primitive");
    assert(util.isPrimitive(0), "NUTIL-L-002: number primitive");
    assert(!util.isPrimitive({}), "NUTIL-L-002: object not primitive");
    assert(!util.isPrimitive(function() {}), "NUTIL-L-002: function not primitive");
}

console.log("ok util types deep legacy (ECG-4)");
__jacDone();
