// testing_plans/14_utilities_diagnostics/NODE_UTIL_COMPREHENSIVE_TEST_PLAN.md — ECG-1 (NUTIL-M-*)

var util = require("util");
var nodeUtil = require("node:util");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/09_util/test_util_module_surface.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

// NUTIL-M-001
assertEq(typeof util, "object", "NUTIL-M-001: require('util') exports object");
assertEq(typeof util.inspect, "function", "NUTIL-M-001: util.inspect is function");
assertEq(typeof util.format, "function", "NUTIL-M-001: util.format is function");
assertEq(typeof util.promisify, "function", "NUTIL-M-001: util.promisify is function");
assert(util.types && typeof util.types.isDate === "function", "NUTIL-M-001: util.types present");
if (typeof util.parseArgs === "function") {
    assertEq(typeof util.parseArgs, "function", "NUTIL-M-001: util.parseArgs is function when present");
}

// NUTIL-M-002
assert(util === nodeUtil, "NUTIL-M-002: require('util') same identity as require('node:util')");

// NUTIL-M-004 TextEncoder / TextDecoder (global or util export; optional on minimal runtimes)
var hasEnc =
    typeof util.TextEncoder !== "undefined" ||
    (typeof globalThis !== "undefined" && typeof globalThis.TextEncoder !== "undefined");
if (hasEnc) {
    if (typeof util.TextEncoder !== "undefined") {
        assertEq(typeof util.TextEncoder, "function", "NUTIL-M-004: util.TextEncoder is constructor");
    }
    if (typeof util.TextDecoder !== "undefined") {
        assertEq(typeof util.TextDecoder, "function", "NUTIL-M-004: util.TextDecoder is constructor");
    }
} else {
    assert(true, "NUTIL-M-004: TextEncoder/TextDecoder absent (documented runtime gap)");
}

// NUTIL-M-005 — document parity targets (advanced APIs); presence is informational, not required
var advanced = [
    "formatWithOptions",
    "getSystemErrorName",
    "getSystemErrorMap",
    "toUSVString",
    "stripVTControlCharacters",
    "styleText",
    "MIMEType",
    "MIMEParams",
    "transferableAbortController",
    "aborted"
];
var present = 0;
for (var j = 0; j < advanced.length; j++) {
    var name = advanced[j];
    if (typeof util[name] === "function") {
        present++;
    }
}
assert(typeof present === "number", "NUTIL-M-005: advanced util API surface inventoried (present=" + present + ")");

console.log("ok util module surface (ECG-1)");
__jacDone();
