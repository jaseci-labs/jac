// --- NUTIL-G-001 disabled debuglog ---
var prevDbg = process.env.NODE_DEBUG;
delete process.env.NODE_DEBUG;
var log1 = util.debuglog("zzabsenttokenzz");
assertEq(typeof log1, "function", "NUTIL-G-001: debuglog returns function");
var stderrWrites = 0;
if (process.stderr && process.stderr.write) {
    var origWrite = process.stderr.write;
    process.stderr.write = function() {
        stderrWrites++;
        return origWrite.apply(process.stderr, arguments);
    };
    log1("should not appear");
    process.stderr.write = origWrite;
}
assertEq(stderrWrites, 0, "NUTIL-G-001: disabled debuglog does not write stderr");

// --- NUTIL-G-002 / G-003: Node reads NODE_DEBUG on first debuglog in the process; use a fresh child so output is capturable (stderr.write patching misses Node's internal write path).
if (prevDbg === undefined) {
    delete process.env.NODE_DEBUG;
} else {
    process.env.NODE_DEBUG = prevDbg;
}
var cp = null;
try {
    cp = require("child_process");
} catch (e1) {
    cp = null;
}
if (cp && typeof cp.spawnSync === "function") {
    var runner = process.execPath;
    var snippet =
        "var u=require('util');" +
        "u.debuglog('foobarutiltest')('hello %s', 'world');";
    var r = cp.spawnSync(runner, ["-e", snippet], {
        encoding: "utf8",
        env: Object.assign({}, process.env, { NODE_DEBUG: "FOOBARUTILTEST" })
    });
    var combined = (r.stderr || "") + (r.stdout || "");
    assert(combined.indexOf("FOOBARUTILTEST") >= 0, "NUTIL-G-002: debuglog line includes section");
    assert(combined.indexOf("hello world") >= 0, "NUTIL-G-002: debuglog formats message");
    assert(/\d+/.test(combined), "NUTIL-G-002: debuglog includes pid digit");
} else {
    assert(true, "NUTIL-G-002: skipped (no child_process.spawnSync)");
}

// --- NUTIL-R-001 / R-002 / R-004 ---
var warnCount = 0;
var prevEmit = process.emitWarning;
process.emitWarning = function() {
    warnCount++;
    if (prevEmit) {
        return prevEmit.apply(process, arguments);
    }
};
var prevNoDep = process.noDeprecation;
process.noDeprecation = false;
var inner = function() {
    return 7;
};
var dep = util.deprecate(inner, "use something else", "DEP_TEST_UTIL");
assertEq(dep(), 7, "NUTIL-R-001: deprecate forwards return");
dep();
dep();
assertEq(warnCount, 1, "NUTIL-R-002: deprecate warns once");
warnCount = 0;
process.noDeprecation = true;
var dep2 = util.deprecate(function() {
    return 8;
}, "silent", "DEP_SILENT");
assertEq(dep2(), 8, "NUTIL-R-003: noDeprecation skips warn path");
dep2();
assertEq(warnCount, 0, "NUTIL-R-003: second call still no warn");
process.noDeprecation = prevNoDep;
process.emitWarning = prevEmit;

// --- NUTIL-H-001 / H-002 / H-003 / H-004 ---
function ParentH() {}
ParentH.prototype.greet = function() {
    return "hi";
};
function ChildH() {
    ParentH.call(this);
}
ChildH.prototype.extra = 1;
util.inherits(ChildH, ParentH);
var ch = new ChildH();
assertEq(ch.greet(), "hi", "NUTIL-H-001: inherits method");
assert(ch instanceof ParentH, "NUTIL-H-001: instanceof");
assertEq(ChildH.super_, ParentH, "NUTIL-H-002: super_");
var h3 = false;
try {
    util.inherits(null, ParentH);
} catch (e) {
    h3 = e instanceof TypeError;
}
assert(h3, "NUTIL-H-003: inherits null ctor throws TypeError");
var h3b = false;
