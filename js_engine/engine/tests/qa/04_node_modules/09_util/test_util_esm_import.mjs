import * as ns from "node:util";
import { inspect, format, promisify } from "node:util";

function assert(cond, msg) {
    if (!cond) {
        console.error("FAIL: " + msg);
        process.exit(1);
    }
}
function assertEq(a, e, msg) {
    if (a !== e) {
        console.error(
            "FAIL: " +
                msg +
                " | expected: " +
                JSON.stringify(e) +
                " | actual: " +
                JSON.stringify(a)
        );
        process.exit(1);
    }
}

assertEq(typeof ns.inspect, "function", "NUTIL-M-003: namespace inspect");
assertEq(typeof ns.format, "function", "NUTIL-M-003: namespace format");
assertEq(typeof inspect, "function", "NUTIL-M-003: named import inspect");
assertEq(typeof format, "function", "NUTIL-M-003: named import format");
assertEq(typeof promisify, "function", "NUTIL-M-003: named import promisify");
assertEq(format("%s", "esm"), "esm", "NUTIL-M-003: format works from ESM");

console.log("ok util ESM imports (NUTIL-M-003)");
