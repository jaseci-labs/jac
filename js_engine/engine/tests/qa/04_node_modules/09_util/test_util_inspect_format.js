// testing_plans/14_utilities_diagnostics/NODE_UTIL_COMPREHENSIVE_TEST_PLAN.md — ECG-2 (NUTIL-I-*, NUTIL-F-*)

var util = require("util");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/09_util/test_util_inspect_format.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

// --- NUTIL-I-001 primitives ---
assertEq(util.inspect(null), "null", "NUTIL-I-001: inspect null");
assertEq(util.inspect(undefined), "undefined", "NUTIL-I-001: inspect undefined");
assertEq(util.inspect(true), "true", "NUTIL-I-001: inspect true");
assertEq(util.inspect(false), "false", "NUTIL-I-001: inspect false");
assertEq(util.inspect(0), "0", "NUTIL-I-001: inspect 0");
// -0 formatting may differ by Node/util.inspect implementation
assertEq(typeof util.inspect(-0), "string", "NUTIL-I-001: inspect -0 is string");
assertEq(util.inspect(NaN), "NaN", "NUTIL-I-001: inspect NaN");
assertEq(util.inspect(Infinity), "Infinity", "NUTIL-I-001: inspect Infinity");
assert(util.inspect("hi").indexOf("hi") >= 0, "NUTIL-I-001: inspect string contains payload");
if (typeof BigInt !== "undefined") {
    assertEq(util.inspect(BigInt(7)), "7n", "NUTIL-I-001: inspect bigint");
}
if (typeof Symbol !== "undefined") {
    var s = Symbol("t");
    assert(util.inspect(s).indexOf("Symbol") >= 0, "NUTIL-I-001: inspect symbol");
}

// --- NUTIL-I-002 objects / arrays ---
var insObj = util.inspect({ z: 1, a: 2 });
assert(insObj.indexOf("z") >= 0 && insObj.indexOf("a") >= 0, "NUTIL-I-002: inspect object keys");
assert(util.inspect([9, 8]).indexOf("9") >= 0, "NUTIL-I-002: inspect array elements");

// --- NUTIL-I-003 depth ---
assertEq(util.inspect({}, { depth: 0 }), "{}", "NUTIL-I-003: empty object depth 0");
var depth0 = util.inspect({ a: { b: 1 } }, { depth: 0 });
assert(depth0 === "[Object]" || depth0.indexOf("a") >= 0, "NUTIL-I-003: depth 0 truncates or shallow-expands");
assertEq(typeof util.inspect({ a: 1 }, { depth: null }), "string", "NUTIL-I-003: depth null yields string");

// --- NUTIL-I-004 circular ---
var circ = {};
circ.self = circ;
var circOut = util.inspect(circ);
assert(circOut.indexOf("Circular") >= 0 || circOut.indexOf("circular") >= 0, "NUTIL-I-004: circular marker");

// --- NUTIL-I-005 Date, RegExp, Error, Map, Set, Promise ---
assert(util.inspect(new Date(0)).indexOf("1970") >= 0 || util.inspect(new Date(0)).indexOf("UTC") >= 0, "NUTIL-I-005: inspect Date");
assert(util.inspect(/a/g).indexOf("/") >= 0, "NUTIL-I-005: inspect RegExp");
assert(util.inspect(new Error("e")).indexOf("e") >= 0, "NUTIL-I-005: inspect Error message");
assert(util.inspect(new Map([[1, 2]])).indexOf("Map") >= 0, "NUTIL-I-005: inspect Map");
assert(util.inspect(new Set([3])).indexOf("Set") >= 0, "NUTIL-I-005: inspect Set");
assert(util.inspect(Promise.resolve()).indexOf("Promise") >= 0, "NUTIL-I-005: inspect Promise");

// --- NUTIL-I-006 showHidden / colors (no throw; output is implementation-defined) ---
assertEq(typeof util.inspect({ a: 1 }, { showHidden: true, colors: true }), "string", "NUTIL-I-006: inspect with showHidden+colors");

// --- NUTIL-I-007 function ---
assert(util.inspect(function named() {}).indexOf("Function") >= 0, "NUTIL-I-007: inspect named function");
assert(util.inspect(function() {}).indexOf("Function") >= 0, "NUTIL-I-007: inspect anonymous function");

// --- NUTIL-I-008 null options ---
assertEq(typeof util.inspect([1], null), "string", "NUTIL-I-008: inspect with null options");

// --- NUTIL-F-001 format specifiers ---
assertEq(util.format("%s", "a"), "a", "NUTIL-F-001: %s");
assertEq(util.format("%d", 3), "3", "NUTIL-F-001: %d integer");
assertEq(util.format("%i", "010"), "10", "NUTIL-F-001: %i parseInt");
assertEq(util.format("%f", "2.5"), "2.5", "NUTIL-F-001: %f");
assertEq(util.format("%j", { k: 1 }), '{"k":1}', "NUTIL-F-001: %j");
assert(util.format("%o", { b: 2 }).indexOf("b") >= 0, "NUTIL-F-001: %o");
assert(util.format("%O", { c: 3 }).indexOf("c") >= 0, "NUTIL-F-001: %O");
assertEq(util.format("%d%%", 100), "100%", "NUTIL-F-001: %% literal after specifier");

// --- NUTIL-F-002 missing args leave placeholders ---
assertEq(util.format("%s %s", "only"), "only %s", "NUTIL-F-002: trailing %s preserved");

// --- NUTIL-F-003 extra args (Node: String coerced, not inspect-quoted)
assertEq(util.format("a", "b", "c"), "a b c", "NUTIL-F-003: extra string args space-separated without quotes");
assertEq(util.format("x=%s", 1, "extra"), "x=1 extra", "NUTIL-F-003: extra after consumed specifiers");
assertEq(util.format("hello", "world"), "hello world", "NUTIL-F-003: no format string joins like Node");

// --- NUTIL-F-004 non-string first argument ---
var f4 = util.format(42, "z");
assert(f4.indexOf("42") >= 0 && f4.indexOf("z") >= 0, "NUTIL-F-004: non-string first arg uses inspect-join");

// --- NUTIL-F-005 %j circular: Node stringifies as '[Circular]'; some engines throw instead ---
var cyc = {};
cyc.x = cyc;
var f5 = "";
var threw5 = false;
try {
    f5 = util.format("%j", cyc);
} catch (e) {
    threw5 = e instanceof TypeError || e instanceof Error;
}
assert(
    threw5 || f5.indexOf("Circular") >= 0,
    "NUTIL-F-005: %j circular throws or yields Circular marker"
);

// --- NUTIL-F-006 format does not mutate ---
var o = { m: 1 };
util.format("%j", o);
assertEq(o.m, 1, "NUTIL-F-006: format %j does not mutate input");

// --- NUTIL-F-007 formatWithOptions when available ---
if (typeof util.formatWithOptions === "function") {
    var fw = util.formatWithOptions({ colors: false }, "%s", "ok");
    assertEq(fw, "ok", "NUTIL-F-007: formatWithOptions basic");
} else {
    assertEq(typeof util.formatWithOptions, "undefined", "NUTIL-F-007: formatWithOptions absent (skipped)");
}

console.log("ok util inspect and format (ECG-2)");
__jacDone();
