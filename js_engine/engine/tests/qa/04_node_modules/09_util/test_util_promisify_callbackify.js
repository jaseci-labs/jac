// testing_plans/14_utilities_diagnostics/NODE_UTIL_COMPREHENSIVE_TEST_PLAN.md — ECG-3 (NUTIL-P-*, NUTIL-C-*)

var util = require("util");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/09_util/test_util_promisify_callbackify.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

var tasks = [];

// --- NUTIL-P-001 / P-002 ---
function nodeCb(x, cb) {
    if (x < 0) {
        cb(new Error("neg"));
        return;
    }
    cb(null, x * 2);
}
var prom = util.promisify(nodeCb);
tasks.push(
    prom(4).then(function(v) {
        assertEq(v, 8, "NUTIL-P-001: promisify resolves value");
    })
);
tasks.push(
    prom(-1).catch(function(err) {
        assert(err instanceof Error, "NUTIL-P-002: promisify rejects Error");
        assertEq(err.message, "neg", "NUTIL-P-002: rejection message");
    })
);

// --- NUTIL-P-003 ---
var p3 = false;
try {
    util.promisify(null);
} catch (e) {
    p3 = e instanceof TypeError;
}
assert(p3, "NUTIL-P-003: promisify non-function throws TypeError");

// --- NUTIL-P-004 this binding ---
var ctx = { mul: 10 };
function withCtx(cb) {
    cb(null, this.mul);
}
tasks.push(
    util.promisify(withCtx.bind(ctx))().then(function(v) {
        assertEq(v, 10, "NUTIL-P-004: promisify callback this (bound for engines without call-site this)");
    })
);

// --- NUTIL-P-005 custom symbol ---
var customSym = typeof Symbol !== "undefined" && Symbol.for ? Symbol.for("nodejs.util.promisify.custom") : null;
if (customSym) {
    function origFn() {}
    origFn[customSym] = function() {
        return Promise.resolve(99);
    };
    tasks.push(
        util.promisify(origFn)().then(function(v) {
            assertEq(v, 99, "NUTIL-P-005: promisify.custom used");
        })
    );
    var bad = function() {};
    bad[customSym] = "notfn";
    var badThrew = false;
    try {
        util.promisify(bad);
    } catch (e2) {
        badThrew = e2 instanceof TypeError;
    }
    assert(badThrew, "NUTIL-P-005: invalid promisify.custom throws TypeError");
}

// --- NUTIL-P-006 multi success args ---
function multiCb(cb) {
    cb(null, 1, 2);
}
tasks.push(
    util.promisify(multiCb)().then(function(v) {
        assertEq(v, 1, "NUTIL-P-006: promisify first success argument only");
    })
);

// --- NUTIL-C-* callbackify ---
if (typeof util.callbackify === "function") {
    function retOk(x) {
        return Promise.resolve(x * 3);
    }
    function retBad() {
        return Promise.reject(new Error("cbfail"));
    }
    tasks.push(
        new Promise(function(resolve) {
            util.callbackify(retOk)(5, function(err, val) {
                assert(err == null, "NUTIL-C-001: callbackify no err");
                assertEq(val, 15, "NUTIL-C-001: callbackify value");
                resolve();
            });
        })
    );
    tasks.push(
        new Promise(function(resolve) {
            util.callbackify(retBad)(function(err, val) {
                assert(err instanceof Error, "NUTIL-C-002: callbackify err");
                assertEq(val, undefined, "NUTIL-C-002: no success value");
                resolve();
            });
        })
    );
    var c4 = false;
    try {
        util.callbackify({});
    } catch (e) {
        c4 = e instanceof TypeError;
    }
    assert(c4, "NUTIL-C-004: callbackify non-function throws TypeError");
    var c5 = false;
    try {
        util.callbackify(retOk)(5, null);
    } catch (e) {
        c5 = e instanceof TypeError;
    }
    assert(c5, "NUTIL-C-005: callbackify non-function callback throws TypeError");
    var o = {
        x: 7,
        m: function() {
            return Promise.resolve(this.x);
        }
    };
    tasks.push(
        new Promise(function(resolve) {
            util.callbackify(o.m).call(o, function(err, val) {
                assert(!err, "NUTIL-C-006: no error");
                assertEq(val, 7, "NUTIL-C-006: this preserved");
                resolve();
            });
        })
    );
    function retNullReject() {
        return Promise.reject(null);
    }
    tasks.push(
        new Promise(function(resolve) {
            util.callbackify(retNullReject)(function(err, val) {
                assertEq(val, undefined, "NUTIL-C-003: no success value on falsy rejection");
                // Node wraps with ERR_FALSY_VALUE_REJECTION; minimal engines may pass (null, undefined).
                if (err != null && err.code) {
                    assertEq(err.code, "ERR_FALSY_VALUE_REJECTION", "NUTIL-C-003: error code when wrapped");
                }
                resolve();
            });
        })
    );
}

Promise.all(tasks).then(
    function() {
        console.log("ok util promisify callbackify (ECG-3)");
        __jacDone();
    },
    function(err) {
        console.error("FAIL: NUTIL-ECG-3: async error " + err);
        __reg.bump(); return;
    }
);
__jacDone();
