// E2E parity: 204, query string, ClientRequest events, node: prefix, Agent options
var http = require("http");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/19_http/test_http_misc_parity.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

var httpNode = require("node:http");
assertEq(typeof httpNode.createServer, "function", "node:http createServer");
assertEq(httpNode.STATUS_CODES[200], "OK", "node:http STATUS_CODES");

var agent = new http.Agent({ keepAlive: true, maxSockets: 10 });
assertEq(agent.keepAlive, true, "Agent keepAlive");
assertEq(agent.maxSockets, 10, "Agent maxSockets");
assert(typeof agent.createConnection === "function", "Agent.createConnection");

var phase = 0;

var server204 = http.createServer(function(req, res) {
    res.writeHead(204);
    res.end();
});

server204.listen(0, "127.0.0.1", function() {
    var port = server204.address().port;
    http.get("http://127.0.0.1:" + port + "/empty", function(res) {
        assertEq(res.statusCode, 204, "204 status");
        var d = "";
        res.on("data", function(ch) { d += ch; });
        res.on("end", function() {
            assertEq(d, "", "204 empty body");
            server204.close(function() { phase = 1; startQuery(); });
        });
    });
});

function startQuery() {
    var serverQ = http.createServer(function(req, res) {
        res.writeHead(200);
        res.end(req.url);
    });
    serverQ.listen(0, "127.0.0.1", function() {
        var port = serverQ.address().port;
        http.get("http://127.0.0.1:" + port + "/search?q=hello&page=1", function(res) {
            var d = "";
            res.on("data", function(ch) { d += ch; });
            res.on("end", function() {
                assertEq(d, "/search?q=hello&page=1", "req.url query string");
                serverQ.close(function() { phase = 2; start404(); });
            });
        });
    });
}

function start404() {
    var server404 = http.createServer(function(req, res) {
        res.writeHead(404, "Custom Not Found", { "X-Reason": "testing" });
        res.end("nf");
    });
    server404.listen(0, "127.0.0.1", function() {
        var port = server404.address().port;
        http.get("http://127.0.0.1:" + port + "/x", function(res) {
            assertEq(res.statusCode, 404, "404 status");
            assertEq(res.statusMessage, "Custom Not Found", "404 statusMessage");
            assert(res.headers["x-reason"] === "testing", "custom header");
            res.on("data", function() {});
            res.on("end", function() {
                server404.close(function() { phase = 3; startEvents(); });
            });
        });
    });
}

function startEvents() {
    var serverEv = http.createServer(function(req, res) {
        res.writeHead(200);
        res.end("ok");
    });
    serverEv.listen(0, "127.0.0.1", function() {
        var port = serverEv.address().port;
        var socketEmitted = false;
        var finishEmitted = false;
        var req = http.request({
            hostname: "127.0.0.1",
            port: port,
            path: "/events",
            method: "GET",
            agent: false
        }, function(res) {
            res.on("data", function() {});
            res.on("end", function() {
                assert(socketEmitted, "socket event");
                assert(finishEmitted, "finish event");
                serverEv.close(function() { __jacDone(); });
            });
        });
        req.on("socket", function() { socketEmitted = true; });
        req.on("finish", function() { finishEmitted = true; });
        req.end();
    });
}

setTimeout(function() {
    console.error("FAIL: test_http_misc_parity timeout phase=" + phase);
    __reg.bump();
    __jacDone();
}, 15000);
