// REQC-002: GET with query string in URL
// Verifies the full request-target (path + query) is preserved.
// ─────────────────────────────────────────────────────────────────────────────
function test_get_query_string(next) {
    var server = http.createServer(function(req, res) {
        assertEq(req.method, "GET",                    "REQC-002: method=GET");
        assertEq(req.url,    "/search?q=hello&limit=10","REQC-002: url with query");
        // Headers object (plain object on js_engine, object on Node.js)
        assert(req.headers["host"] !== undefined, "REQC-002: host header present");
        res.writeHead(200, { "Content-Length": "2" });
        res.end("ok");
    });

    server.listen(0, "127.0.0.1", function() {
        var port = server.address().port;
        http.get(
            "http://127.0.0.1:" + port + "/search?q=hello&limit=10",
            function(res) {
                assertEq(res.statusCode, 200, "REQC-002: response 200");
                res.on("data", function() {});
                res.on("end", function() {
                    server.close(function() { next(); });
                });
            }
        ).on("error", function(e) {
            assert(false, "REQC-002: error: " + e.message);
            server.close(function() { next(); });
        });
    });
}

