// Helper: read request body, compatible with both js_engine (req.body) and
// Node.js (streaming IncomingMessage).
function readBody(req, cb) {
    if (typeof req.body !== "undefined") {
        // js_engine: body is already a string on the request object
        cb(req.body);
    } else {
        // Node.js: collect data chunks
        var body = "";
        req.on("data", function(chunk) { body = body + chunk; });
        req.on("end", function() { cb(body); });
    }
}

// ─────────────────────────────────────────────────────────────────────────────
// REQC-001: POST with JSON body
// Verifies the request parser correctly delivers method, URL, and body.
// ─────────────────────────────────────────────────────────────────────────────
function test_post_with_body(next) {
    var payload = "{\"hello\":\"world\",\"num\":42}";
    var server = http.createServer(function(req, res) {
        readBody(req, function(body) {
            assertEq(req.method,     "POST",    "REQC-001: method=POST");
            assertEq(req.url,        "/api/data","REQC-001: url=/api/data");
            assertEq(body, payload,             "REQC-001: body payload intact");
            res.writeHead(200, { "Content-Type": "application/json",
                                 "Content-Length": "2" });
            res.end("ok");
        });
    });

    server.listen(0, "127.0.0.1", function() {
        var port = server.address().port;
        var opts = {
            hostname: "127.0.0.1",
            port: port,
            path: "/api/data",
            method: "POST",
            headers: {
                "Content-Type": "application/json",
                "Content-Length": String(payload.length)
            }
        };
        var req = http.request(opts, function(res) {
            assertEq(res.statusCode, 200, "REQC-001: response 200");
            res.on("data", function() {});
            res.on("end", function() {
                server.close(function() { next(); });
            });
        });
        req.on("error", function(e) {
            assert(false, "REQC-001: request error: " + e.message);
            server.close(function() { next(); });
        });
        req.write(payload);
        req.end();
    });
}

