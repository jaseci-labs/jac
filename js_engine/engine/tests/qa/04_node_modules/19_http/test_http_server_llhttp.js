// ─────────────────────────────────────────────────────────────────────────────
// REQC-004: POST with a 1 KB body — integrity check
// Verifies large(-ish) request bodies are not truncated.
// ─────────────────────────────────────────────────────────────────────────────
function test_large_body(next) {
    // Build 1024-byte payload: "A" × 1024
    var payload = "";
    var i = 0;
    while (i < 1024) { payload = payload + "A"; i = i + 1; }

    var server = http.createServer(function(req, res) {
        readBody(req, function(body) {
            assertEq(req.method, "POST", "REQC-004: method=POST");
            assertEq(body.length, 1024,  "REQC-004: body length 1024");
            assertEq(body.charAt(0),   "A", "REQC-004: body[0]=A");
            assertEq(body.charAt(1023),"A", "REQC-004: body[1023]=A");
            res.writeHead(200, { "Content-Length": "2" });
            res.end("ok");
        });
    });

    server.listen(0, "127.0.0.1", function() {
        var port = server.address().port;
        var opts = {
            hostname: "127.0.0.1",
            port: port,
            path: "/upload",
            method: "POST",
            headers: {
                "Content-Type":   "text/plain",
                "Content-Length": String(payload.length)
            }
        };
        var req = http.request(opts, function(res) {
            assertEq(res.statusCode, 200, "REQC-004: response 200");
            res.on("data", function() {});
            res.on("end", function() {
                server.close(function() { next(); });
            });
        });
        req.on("error", function(e) {
            assert(false, "REQC-004: large body error: " + e.message);
            server.close(function() { next(); });
        });
        req.write(payload);
        req.end();
    });
}

// ─────────────────────────────────────────────────────────────────────────────
// REQC-005: WebSocket Upgrade request — server sees upgrade header
// Sends an HTTP Upgrade request (without completing the WS handshake) and
// verifies the server can read the Upgrade header from the request.
// ─────────────────────────────────────────────────────────────────────────────
function test_upgrade_header_visible(next) {
    var server = http.createServer(function(req, res) {
        // Server reads the Upgrade header and echoes it back
        var upgradeHdr = req.headers["upgrade"] || "(none)";
        var connHdr    = req.headers["connection"] || "(none)";
        assert(upgradeHdr.toLowerCase().indexOf("websocket") !== -1,
               "REQC-005: upgrade header contains 'websocket'");
        assert(connHdr.toLowerCase().indexOf("upgrade") !== -1,
               "REQC-005: connection header contains 'upgrade'");
        res.writeHead(200, {
            "Content-Type": "text/plain",
            "X-Saw-Upgrade": upgradeHdr,
            "Content-Length": "2"
        });
        res.end("ok");
    });

    server.listen(0, "127.0.0.1", function() {
        var port = server.address().port;
        var opts = {
            hostname: "127.0.0.1",
            port: port,
            path: "/ws-echo",
            method: "GET",
            headers: {
                "Upgrade":               "websocket",
                "Connection":            "Upgrade",
                "Sec-WebSocket-Key":     "dGhlIHNhbXBsZSBub25jZQ==",
                "Sec-WebSocket-Version": "13"
            }
        };
        var req = http.request(opts, function(res) {
            // We sent headers that trigger the WS path, but the server
            // (configured without a ws handler) responds 200 instead of 101.
            assert(res.statusCode === 200 || res.statusCode === 101,
                   "REQC-005: status 200 or 101 (got " + res.statusCode + ")");
            var body = "";
            res.on("data", function(c) { body = body + c; });
            res.on("end", function() {
                server.close(function() { next(); });
            });
        });
        req.on("error", function(e) {
            // Allow ECONNRESET (server may close after 101)
            server.close(function() { next(); });
        });
        req.end();
    });
}

