// ─────────────────────────────────────────────────────────────────────────────
// LLHTTP-001: headers with unusual but valid characters in values
// Verifies the parser handles header values containing commas, quotes, etc.
// ─────────────────────────────────────────────────────────────────────────────
function test_unusual_header_chars(next) {
    var server = http.createServer(function(req, res) {
        res.writeHead(200, {
            "X-Custom": "value, with, commas",
            "X-Quoted": "\"quoted value\"",
            "Content-Length": "2"
        });
        res.end("ok");
    });
    server.listen(0, "127.0.0.1", function() {
        var port = server.address().port;
        http.get("http://127.0.0.1:" + port + "/", function(res) {
            assertEq(res.statusCode, 200, "LLHTTP-001: unusual chars status 200");
            assert(typeof res.headers["x-custom"] === "string",
                   "LLHTTP-001: comma-header present");
            assert(res.headers["x-custom"].indexOf("commas") !== -1,
                   "LLHTTP-001: comma-header value preserved");
            var body = "";
            res.on("data", function(c) { body += c; });
            res.on("end", function() {
                assertEq(body, "ok", "LLHTTP-001: body correct");
                server.close(function() { next(); });
            });
        }).on("error", function(e) {
            assert(false, "LLHTTP-001: unusual chars error: " + e.message);
            server.close(function() { next(); });
        });
    });
}

// ─────────────────────────────────────────────────────────────────────────────
// LLHTTP-002: chunked transfer encoding — multiple writes from server
// Verifies the response parser correctly reassembles a chunked body.
// ─────────────────────────────────────────────────────────────────────────────
function test_chunked_body(next) {
    var server = http.createServer(function(req, res) {
        res.writeHead(200, { "Transfer-Encoding": "chunked" });
        res.write("hello");
        res.write(" ");
        res.write("world");
        res.end();
    });
    server.listen(0, "127.0.0.1", function() {
        var port = server.address().port;
        http.get("http://127.0.0.1:" + port + "/", function(res) {
            assertEq(res.statusCode, 200, "LLHTTP-002: chunked status 200");
            var body = "";
            res.on("data", function(c) { body += c; });
            res.on("end", function() {
                assertEq(body, "hello world", "LLHTTP-002: chunked body assembled");
                server.close(function() { next(); });
            });
        }).on("error", function(e) {
            assert(false, "LLHTTP-002: chunked error: " + e.message);
            server.close(function() { next(); });
        });
    });
}

