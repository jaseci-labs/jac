// ─────────────────────────────────────────────────────────────────────────────
// LLHTTP-005: very large header value (8 KB — well under _HV_BUF_SIZE = 16 KB)
// Verifies hdr_buf overflow guard does not drop valid large headers.
// ─────────────────────────────────────────────────────────────────────────────
function test_large_header(next) {
    var big = new Array(8193).join("x");  // 8192 × "x"
    var server = http.createServer(function(req, res) {
        res.writeHead(200, { "X-Big": big, "Content-Length": "2" });
        res.end("ok");
    });
    server.listen(0, "127.0.0.1", function() {
        var port = server.address().port;
        http.get("http://127.0.0.1:" + port + "/", function(res) {
            assertEq(res.statusCode, 200, "LLHTTP-005: large header status 200");
            assert(typeof res.headers["x-big"] === "string",
                   "LLHTTP-005: large header present");
            assert(res.headers["x-big"].length > 100,
                   "LLHTTP-005: large header non-trivially long");
            var body = "";
            res.on("data", function(c) { body += c; });
            res.on("end", function() {
                assertEq(body, "ok", "LLHTTP-005: body after large header");
                server.close(function() { next(); });
            });
        }).on("error", function(e) {
            assert(false, "LLHTTP-005: large header error: " + e.message);
            server.close(function() { next(); });
        });
    });
}

// ─────────────────────────────────────────────────────────────────────────────
// LLHTTP-006: many headers (stress hdr_buf accumulation, ~40 header lines)
// Exercises the hdr_buf overflow guard added in Phase B.
// ─────────────────────────────────────────────────────────────────────────────
function test_many_headers(next) {
    var server = http.createServer(function(req, res) {
        var hdrs = { "Content-Length": "2" };
        var i = 0;
        while (i < 20) {
            hdrs["X-Header-" + i] = "value-" + i;
            i = i + 1;
        }
        res.writeHead(200, hdrs);
        res.end("ok");
    });
    server.listen(0, "127.0.0.1", function() {
        var port = server.address().port;
        http.get("http://127.0.0.1:" + port + "/", function(res) {
            assertEq(res.statusCode, 200, "LLHTTP-006: many headers status 200");
            assert(typeof res.headers["x-header-0"] === "string",
                   "LLHTTP-006: first extra header present");
            assert(typeof res.headers["x-header-19"] === "string",
                   "LLHTTP-006: last extra header present");
            var body = "";
            res.on("data", function(c) { body += c; });
            res.on("end", function() {
                assertEq(body, "ok", "LLHTTP-006: body after many headers");
                server.close(function() { next(); });
            });
        }).on("error", function(e) {
            assert(false, "LLHTTP-006: many headers error: " + e.message);
            server.close(function() { next(); });
        });
    });
}

// ─────────────────────────────────────────────────────────────────────────────
// LLHTTP-007: multiple values for the same header field (Set-Cookie)
// ─────────────────────────────────────────────────────────────────────────────
function test_multi_set_cookie(next) {
    var server = http.createServer(function(req, res) {
        res.setHeader("Set-Cookie", ["a=1; Path=/", "b=2; Path=/"]);
        res.writeHead(200);
        res.end("cookies");
    });
    server.listen(0, "127.0.0.1", function() {
        var port = server.address().port;
        http.get("http://127.0.0.1:" + port + "/", function(res) {
            assertEq(res.statusCode, 200, "LLHTTP-007: multi-cookie status 200");
            var sc = res.headers["set-cookie"];
            // Node.js exposes repeated Set-Cookie as an array; other engines
            // may join with ", " — both representations are valid here.
            assert(Array.isArray(sc) ? sc.length >= 1 : typeof sc === "string",
                   "LLHTTP-007: Set-Cookie header present");
            var body = "";
            res.on("data", function(c) { body += c; });
            res.on("end", function() {
                assertEq(body, "cookies", "LLHTTP-007: body after multi-cookie");
                server.close(function() { next(); });
            });
        }).on("error", function(e) {
            assert(false, "LLHTTP-007: multi-cookie error: " + e.message);
            server.close(function() { next(); });
        });
    });
}

