// HTTP-001 through HTTP-005: http module
var http = require("http");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/19_http/test_http.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

// HTTP-004: STATUS_CODES
assertEq(typeof http.STATUS_CODES, "object",               "HTTP-004: STATUS_CODES is object");
assertEq(http.STATUS_CODES[200],   "OK",                   "HTTP-004: 200 = OK");
assertEq(http.STATUS_CODES[404],   "Not Found",            "HTTP-004: 404 = Not Found");
assertEq(http.STATUS_CODES[500],   "Internal Server Error","HTTP-004: 500 = Internal Server Error");
assertEq(http.STATUS_CODES[301],   "Moved Permanently",    "HTTP-004: 301 = Moved Permanently");

// HTTP-001: createServer — function exists, returns server object
assertEq(typeof http.createServer, "function",             "HTTP-001: createServer exists");
var server = http.createServer(function(req, res) {
    // HTTP-002: Request parsing
    assert(typeof req.method === "string",                 "HTTP-002: req.method is string");
    assert(typeof req.url    === "string",                 "HTTP-002: req.url is string");
    assert(typeof req.headers === "object",               "HTTP-002: req.headers is object");
    // HTTP-003: Response
    res.writeHead(200, {"Content-Type": "text/plain"});
    res.end("hello");
});
assert(typeof server.listen === "function",               "HTTP-001: server.listen");
assert(typeof server.close  === "function",               "HTTP-001: server.close");

// HTTP-005: request/get — function exists
assertEq(typeof http.request, "function",                 "HTTP-005: http.request exists");
assertEq(typeof http.get, "function",                     "HTTP-005: http.get exists");

// Listen on random port, do a simple GET request, then close
server.listen(0, "127.0.0.1", function() {
    var port = server.address().port;
    var requestReceived = false;
    var responseDone = false;

    var req = http.get("http://127.0.0.1:" + port + "/test", function(res) {
        assertEq(res.statusCode, 200,                      "HTTP-003: status 200");
        assertEq(typeof res.headers, "object",             "HTTP-003: res.headers is object");
        var body = "";
        res.on("data", function(chunk) { body += chunk; });
        res.on("end", function() {
            assertEq(body, "hello",                        "HTTP-003: response body");
            responseDone = true;
            server.close(function() { __jacDone(); });
        });
    });
    req.on("error", function(e) {
        console.error("FAIL: HTTP request error: " + e.message);
        server.close();
        __reg.bump(); return;
    });
});

setTimeout(function() {
    console.error("FAIL: HTTP test timed out");
    server.close();
    __reg.bump(); return;
}, 5000);
