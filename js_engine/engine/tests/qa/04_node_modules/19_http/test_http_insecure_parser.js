// insecureHTTPParser allows missing Host on HTTP/1.1 (js_engine); Node returns 400
var http = require("http");
var net = require("net");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/19_http/test_http_insecure_parser.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }

var onJacEngine = __jacHarness.isJacEngineRunner();

var gotRequest = false;
var server = http.createServer({ insecureHTTPParser: true }, function(req, res) {
    gotRequest = true;
    res.end("ok");
});

server.listen(0, "127.0.0.1", function() {
    var port = server.address().port;
    var raw = "GET /nohost HTTP/1.1\r\n\r\n";
    var sock = net.connect(port, "127.0.0.1", function() {
        sock.write(raw);
    });
    var resp = "";
    var done = false;
    sock.on("data", function(d) {
        resp += d;
        if (done) {
            return;
        }
        if (onJacEngine && gotRequest && resp.indexOf("ok") !== -1) {
            done = true;
            sock.destroy();
            server.close(function() { __jacDone(); });
            return;
        }
        if (!onJacEngine && resp.indexOf("400") !== -1) {
            done = true;
            assert(!gotRequest, "Node rejects missing Host (400, handler not run)");
            sock.destroy();
            server.close(function() { __jacDone(); });
        }
    });
    sock.on("error", function(e) {
        console.error("sock err: " + e.message);
        server.close();
        __reg.bump();
        __jacDone();
    });
});

setTimeout(function() {
    console.error("FAIL: insecure parser timeout");
    server.close();
    __reg.bump();
    __jacDone();
}, 5000);
