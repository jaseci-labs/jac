// keepAliveTimeout on server + getDefaultHighWaterMark exports (http on js_engine, stream on Node)
var http = require("http");
var stream = require("stream");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/19_http/test_http_keepalive_hwm.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

var onJacEngine = __jacHarness.isJacEngineRunner();
var hwm = onJacEngine ? http : stream;

assertEq(typeof hwm.getDefaultHighWaterMark, "function", "getDefaultHighWaterMark");
assertEq(typeof hwm.setDefaultHighWaterMark, "function", "setDefaultHighWaterMark");

var defaultBufHwm = hwm.getDefaultHighWaterMark(false);
var defaultObjHwm = hwm.getDefaultHighWaterMark(true);
assert(defaultBufHwm > 0, "default buffer HWM positive");
assertEq(defaultObjHwm, 16, "objectMode HWM");
if (onJacEngine) {
    assertEq(defaultBufHwm, 16384, "default HWM");
}

if (onJacEngine) {
    hwm.setDefaultHighWaterMark(8192, false);
    assertEq(hwm.getDefaultHighWaterMark(false), 8192, "setDefaultHighWaterMark");
    hwm.setDefaultHighWaterMark(16384, false);
} else {
    hwm.setDefaultHighWaterMark(false, 8192);
    assertEq(hwm.getDefaultHighWaterMark(false), 8192, "setDefaultHighWaterMark");
    hwm.setDefaultHighWaterMark(false, defaultBufHwm);
}

var hits = 0;
var server = http.createServer({ keepAliveTimeout: 250 }, function(req, res) {
    hits = hits + 1;
    res.writeHead(200);
    res.end("pong-" + hits);
});

server.listen(0, "127.0.0.1", function() {
    var port = server.address().port;
    var agent = new http.Agent({ keepAlive: true });

    http.get({ hostname: "127.0.0.1", port: port, path: "/", agent: agent }, function(res) {
        var body = "";
        res.on("data", function(c) { body += c; });
        res.on("end", function() {
            assertEq(body, "pong-1", "first response");
            setTimeout(function() {
                http.get({ hostname: "127.0.0.1", port: port, path: "/", agent: agent },
                    function(res2) {
                        var body2 = "";
                        res2.on("data", function(c) { body2 += c; });
                        res2.on("end", function() {
                            assertEq(body2, "pong-2", "second response after idle");
                            assertEq(hits, 2, "two requests handled");
                            agent.destroy();
                            server.close(function() { __jacDone(); });
                        });
                    }).on("error", function(e) {
                        console.error("second get: " + e.message);
                        __reg.bump();
                        __jacDone();
                    });
            }, 400);
        });
    }).on("error", function(e) {
        console.error("first get: " + e.message);
        __reg.bump();
        __jacDone();
    });
});

setTimeout(function() {
    console.error("FAIL: test_http_keepalive_hwm timeout");
    server.close();
    __reg.bump();
    __jacDone();
}, 10000);
