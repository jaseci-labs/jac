// HTTP core API parity — validateHeader*, OutgoingMessage, headersDistinct, setMaxIdleHTTPParsers
var http = require("http");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/19_http/test_http_core_api.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

assertEq(typeof http.OutgoingMessage, "function", "exports OutgoingMessage");
assertEq(typeof http.validateHeaderName, "function", "validateHeaderName");
assertEq(typeof http.validateHeaderValue, "function", "validateHeaderValue");
assertEq(typeof http.setMaxIdleHTTPParsers, "function", "setMaxIdleHTTPParsers");
assertEq(typeof http.setGlobalProxyFromEnv, "function", "setGlobalProxyFromEnv");

http.setMaxIdleHTTPParsers(500);

var threwName = false;
try {
    http.validateHeaderName("bad header");
} catch (e) {
    threwName = e && e.code === "ERR_INVALID_HTTP_TOKEN";
}
assert(threwName, "invalid header name throws ERR_INVALID_HTTP_TOKEN");

var threwVal = false;
try {
    http.validateHeaderValue("X-Test", "line\nbreak");
} catch (e2) {
    threwVal = e2 && e2.code === "ERR_INVALID_CHAR";
}
assert(threwVal, "invalid header value throws ERR_INVALID_CHAR");

var server = http.createServer(function(req, res) {
    assertEq(typeof req.headersDistinct, "object", "headersDistinct object");
    assert(Array.isArray(req.headersDistinct["host"]), "headersDistinct host array");
    res.writeHead(200);
    res.end("ok");
});

server.listen(0, "127.0.0.1", function() {
    var port = server.address().port;
    var req = http.request({
        hostname: "127.0.0.1",
        port: port,
        path: "/",
        method: "GET",
        headers: { "X-Test": "a", "X-Other": "b" }
    }, function(res) {
        var body = "";
        res.on("data", function(c) { body += c; });
        res.on("end", function() {
            assertEq(body, "ok", "body ok");
            var restore = http.setGlobalProxyFromEnv({ HTTP_PROXY: "", NO_PROXY: "*" });
            assertEq(typeof restore, "function", "setGlobalProxyFromEnv returns restore");
            restore();
            server.close(function() { __jacDone(); });
        });
    });
    req.end();
});

setTimeout(function() {
    console.error("FAIL: test_http_core_api timeout");
    server.close();
    __reg.bump();
    __jacDone();
}, 8000);
