// connectionsCheckingInterval — periodic closeIdleConnections on idle keep-alive sockets
var http = require("http");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/19_http/test_http_connections_checking.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

var hits = 0;
var server = http.createServer({
    keepAliveTimeout: 60000,
    connectionsCheckingInterval: 100
}, function(req, res) {
    hits = hits + 1;
    res.writeHead(200, { Connection: "keep-alive" });
    res.end("hit-" + hits);
});

server.listen(0, "127.0.0.1", function() {
    var port = server.address().port;
    var agent = new http.Agent({ keepAlive: true, maxSockets: 1 });

    http.get({ hostname: "127.0.0.1", port: port, path: "/", agent: agent }, function(res) {
        var body = "";
        res.on("data", function(c) { body += c; });
        res.on("end", function() {
            assertEq(body, "hit-1", "first response");
            setTimeout(function() {
                http.get({ hostname: "127.0.0.1", port: port, path: "/", agent: agent },
                    function(res2) {
                        var body2 = "";
                        res2.on("data", function(c) { body2 += c; });
                        res2.on("end", function() {
                            assertEq(body2, "hit-2", "second request after idle sweep");
                            assertEq(hits, 2, "two distinct requests");
                            agent.destroy();
                            server.close(function() { __jacDone(); });
                        });
                    }).on("error", function(e) {
                        console.error("second get: " + e.message);
                        __reg.bump();
                        __jacDone();
                    });
            }, 350);
        });
    }).on("error", function(e) {
        console.error("first get: " + e.message);
        __reg.bump();
        __jacDone();
    });
});

setTimeout(function() {
    console.error("FAIL: test_http_connections_checking timeout");
    server.close();
    __reg.bump();
    __jacDone();
}, 10000);
