// optimizeEmptyRequests — readableEnded before handler (js_engine); Node leaves false
var http = require("http");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/19_http/test_http_optimize_empty.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }

var onJacEngine = __jacHarness.isJacEngineRunner();
var readableEndedAtHandler = false;

var server = http.createServer({ optimizeEmptyRequests: true }, function(req, res) {
    readableEndedAtHandler = req.readableEnded === true;
    res.writeHead(200);
    res.end("ok");
});

server.listen(0, "127.0.0.1", function() {
    var port = server.address().port;
    var req = http.request({
        hostname: "127.0.0.1",
        port: port,
        path: "/",
        method: "POST",
        headers: { "Content-Length": "0" },
        agent: false
    }, function(res) {
        res.on("data", function() {});
        res.on("end", function() {
            if (onJacEngine) {
                assert(readableEndedAtHandler, "readableEnded true in handler");
            } else {
                assert(!readableEndedAtHandler, "Node readableEnded false in handler");
            }
            server.close(function() { __jacDone(); });
        });
    });
    req.on("error", function(e) {
        console.error("client: " + e.message);
        server.close();
        __reg.bump();
        __jacDone();
    });
    req.end();
});

setTimeout(function() {
    console.error("FAIL: test_http_optimize_empty timeout");
    server.close();
    __reg.bump();
    __jacDone();
}, 8000);
