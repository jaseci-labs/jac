// Deprecated HTTP APIs — compatibility shims (Node v24 stability 0)
var http = require("http");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/19_http/test_http_legacy_compat.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }

var server = http.createServer(function(req, res) {
    assert(req.connection === req.socket, "message.connection alias");
    assert(res.connection === res.socket, "response.connection alias");
    res.writeHead(200);
    res.end("legacy");
});

server.listen(0, "127.0.0.1", function() {
    var port = server.address().port;
    var req = http.request({
        hostname: "127.0.0.1",
        port: port,
        path: "/",
        method: "GET"
    }, function(res) {
        var body = "";
        res.on("data", function(c) { body += c; });
        res.on("end", function() {
            assert(req.socket !== null, "request.socket set after connect");
            assert(req.connection === req.socket, "request.connection alias");
            server.close(function() { __jacDone(); });
        });
    });
    req.on("socket", function(sock) {
        assert(sock !== null, "socket event delivers socket");
    });
    req.end();
});

setTimeout(function() {
    server.close();
    __reg.bump();
    __jacDone();
}, 8000);
