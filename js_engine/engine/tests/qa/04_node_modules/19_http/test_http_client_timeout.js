// ClientRequest.setTimeout — mirrors e2e test_node_http.js group 8
var http = require("http");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/19_http/test_http_client_timeout.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }

var server = http.createServer(function(req, res) {
    setTimeout(function() {
        res.writeHead(200);
        res.end("late");
    }, 500);
});

server.listen(0, "127.0.0.1", function() {
    var port = server.address().port;
    var timeoutFired = false;

    var req = http.request({
        hostname: "127.0.0.1",
        port: port,
        path: "/slow",
        method: "GET",
        agent: false
    }, function(res) {
        res.on("data", function() {});
        res.on("end", function() {});
    });

    req.setTimeout(100, function() {
        timeoutFired = true;
        req.destroy();
    });
    req.on("error", function() {
        // Node emits ECONNRESET after destroy(); js_engine may not.
    });
    req.end();

    setTimeout(function() {
        assert(timeoutFired, "request timeout event fired");
        server.close(function() { __jacDone(); });
    }, 400);
});

setTimeout(function() {
    console.error("FAIL: test_http_client_timeout timeout");
    server.close();
    __reg.bump();
    __jacDone();
}, 8000);
