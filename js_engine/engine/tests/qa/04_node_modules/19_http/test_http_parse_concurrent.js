// HTTP-PARSE-001: concurrent requests do not corrupt header parsing (no global leak)
var http = require("http");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase(
  "regression/04_node_modules/19_http/test_http_parse_concurrent.js"
);
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

var pending = 2;
function doneOne() {
    pending = pending - 1;
    if (pending === 0) { __jacDone(); }
}

var server = http.createServer(function (req, res) {
    var tag = req.headers["x-tag"] || "";
    res.writeHead(200, { "Content-Type": "text/plain" });
    res.end(tag);
});

server.listen(0, "127.0.0.1", function () {
    var port = server.address().port;
    http.get({ host: "127.0.0.1", port: port, path: "/", headers: { "X-Tag": "A" } }, function (res) {
        var body = "";
        res.on("data", function (c) { body += c; });
        res.on("end", function () {
            assertEq(body, "A", "HTTP-PARSE-001: first body");
            doneOne();
        });
    }).on("error", function (e) {
        console.error(e.message);
        __reg.bump();
        doneOne();
    });

    http.get({ host: "127.0.0.1", port: port, path: "/", headers: { "X-Tag": "B" } }, function (res) {
        var body = "";
        res.on("data", function (c) { body += c; });
        res.on("end", function () {
            assertEq(body, "B", "HTTP-PARSE-001: second body");
            doneOne();
        });
    }).on("error", function (e) {
        console.error(e.message);
        __reg.bump();
        doneOne();
    });
});

setTimeout(function () {
    server.close();
    console.error("FAIL: test_http_parse_concurrent timeout");
    __reg.bump();
    __jacDone();
}, 8000);
