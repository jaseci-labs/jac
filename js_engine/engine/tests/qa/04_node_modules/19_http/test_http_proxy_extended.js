// NO_PROXY bypass + HTTPS CONNECT via HTTP proxy (setGlobalProxyFromEnv)
var http = require("http");
var https = require("https");
var net = require("net");
var fs = require("fs");
var path = require("path");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/19_http/test_http_proxy_extended.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

var CRLF = "\r\n";

function createConnectProxy(cb) {
    var connectCount = 0;
    var server = net.createServer(function(clientSocket) {
        var buf = "";
        function onData(chunk) {
            buf = buf + chunk;
            var idx = buf.indexOf(CRLF + CRLF);
            if (idx === -1) { return; }
            clientSocket.removeListener("data", onData);
            connectCount = connectCount + 1;
            var firstLine = buf.split(CRLF)[0];
            var target = firstLine.split(" ")[1];
            var parts = target.split(":");
            var thost = parts[0];
            var tport = Number(parts[1]);
            var early = buf.substring(idx + 4);
            var upstream = net.connect({ host: thost, port: tport }, function() {
                clientSocket.write("HTTP/1.1 200 Connection Established" + CRLF + CRLF);
                if (early.length > 0) { upstream.write(early); }
                clientSocket.on("data", function(c) { upstream.write(c); });
                upstream.on("data", function(c) { clientSocket.write(c); });
                clientSocket.on("end", function() { upstream.end(); });
                upstream.on("end", function() { clientSocket.end(); });
                clientSocket.on("error", function() { upstream.destroy(); });
                upstream.on("error", function() { clientSocket.destroy(); });
            });
            upstream.on("error", function() { clientSocket.destroy(); });
        }
        clientSocket.on("data", onData);
    });
    server.listen(0, "127.0.0.1", cb);
    server.getConnectCount = function () { return connectCount; };
    return server;
}

var phase = 0;

function startNoProxy() {
    var backend = http.createServer(function(req, res) {
        res.end("direct");
    });
    var proxy = http.createServer(function(req, res) {
        res.end("proxied");
    });

    backend.listen(0, "127.0.0.1", function() {
        var bport = backend.address().port;
        proxy.listen(0, "127.0.0.1", function() {
            var pport = proxy.address().port;
            var restore = http.setGlobalProxyFromEnv({
                HTTP_PROXY: "http://127.0.0.1:" + pport,
                NO_PROXY: "127.0.0.1"
            });

            http.get("http://127.0.0.1:" + bport + "/", function(res) {
                var body = "";
                res.on("data", function(c) { body += c; });
                res.on("end", function() {
                    assertEq(body, "direct", "NO_PROXY bypasses proxy");
                    restore();
                    proxy.close(function() {
                        backend.close(function() {
                            phase = 1;
                            startHttpsConnect();
                        });
                    });
                });
            }).on("error", function(err) {
                console.error("NO_PROXY: " + err.message);
                restore();
                proxy.close();
                backend.close();
                __reg.bump();
                __jacDone();
            });
        });
    });
}

function startHttpsConnect() {
    var certDir = path.join(__dirname, "../../../e2e");
    var keyFile = path.join(certDir, "test_key.pem");
    var certFile = path.join(certDir, "test_cert.pem");
    var runner = process.env.JAC_JS_RUNNER || "";
    var onJacEngine = runner.indexOf("js_engine") !== -1;
    var tlsOpts = onJacEngine
        ? { key: keyFile, cert: certFile }
        : { key: fs.readFileSync(keyFile), cert: fs.readFileSync(certFile) };

    var backend = https.createServer(tlsOpts, function(req, res) {
        res.writeHead(200);
        res.end("tls-via-proxy");
    });

    backend.listen(0, "127.0.0.1", function() {
        var bport = backend.address().port;
        var connectProxy = createConnectProxy(function() {
            var pport = connectProxy.address().port;
            var restore = http.setGlobalProxyFromEnv({
                HTTPS_PROXY: "http://127.0.0.1:" + pport,
                NO_PROXY: ""
            });

            // Node v24: agent:false bypasses HTTPS_PROXY CONNECT; use default agent.
            var req = https.request({
                host: "127.0.0.1",
                hostname: "127.0.0.1",
                port: bport,
                servername: "localhost",
                path: "/",
                method: "GET",
                rejectUnauthorized: false
            }, function(res) {
                var body = "";
                res.on("data", function(c) { body += c; });
                res.on("end", function() {
                    assertEq(res.statusCode, 200, "HTTPS via CONNECT status");
                    assertEq(body, "tls-via-proxy", "HTTPS via CONNECT body");
                    assert(connectProxy.getConnectCount() >= 1,
                        "HTTPS CONNECT: proxy received CONNECT");
                    restore();
                    connectProxy.close(function() {
                        backend.close(function() { __jacDone(); });
                    });
                });
            });
            req.on("error", function(err) {
                console.error("HTTPS CONNECT: " + err.message);
                restore();
                connectProxy.close();
                backend.close();
                __reg.bump();
                __jacDone();
            });
            req.end();
        });
    });
}

