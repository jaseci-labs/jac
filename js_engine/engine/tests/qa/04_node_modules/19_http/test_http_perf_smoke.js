// Non-functional smoke: sequential keep-alive GETs (default 100, <30s)
var http = require("http");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/19_http/test_http_perf_smoke.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }

var TARGET = 100;
if (process.env.JAC_HTTP_PERF_TARGET) {
    TARGET = Number(process.env.JAC_HTTP_PERF_TARGET) || TARGET;
}
var MAX_MS = 30000;
var t0 = Date.now();
var finished = false;

var server = http.createServer(function(req, res) {
    res.writeHead(200);
    res.end("pong");
});

server.listen(0, "127.0.0.1", function() {
    var port = server.address().port;
    var agent = new http.Agent({ keepAlive: true, maxSockets: 4 });
    var done = 0;
    var errors = 0;

    function next(i) {
        if (i >= TARGET) {
            finished = true;
            var elapsed = Date.now() - t0;
            assert(done === TARGET, "completed " + TARGET + " requests");
            assert(errors === 0, "no request errors");
            assert(elapsed < MAX_MS, "under " + MAX_MS + "ms (" + elapsed + "ms)");
            agent.destroy();
            server.close(function() { __jacDone(); });
            return;
        }
        var req = http.request({
            hostname: "127.0.0.1",
            port: port,
            path: "/",
            agent: agent
        }, function(res) {
            res.on("data", function() {});
            res.on("end", function() {
                done = done + 1;
                next(i + 1);
            });
        });
        req.on("error", function() {
            errors = errors + 1;
            next(i + 1);
        });
        req.end();
    }
    next(0);
});

setTimeout(function() {
    if (finished) { return; }
    console.error("FAIL: perf smoke timeout");
    server.close();
    __reg.bump();
    __jacDone();
}, MAX_MS + 5000);
