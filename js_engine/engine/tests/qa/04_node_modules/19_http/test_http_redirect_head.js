// Client redirects (maxRedirects on js_engine) + HEAD no body + Expect 100-continue
var http = require("http");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/19_http/test_http_redirect_head.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

var onJacEngine = __jacHarness.isJacEngineRunner();
var phase = 0;

// Redirect chain: /start -> /final
var chain = http.createServer(function(req, res) {
    if (req.url === "/start") {
        res.writeHead(302, { Location: "/final" });
        res.end("redirecting");
        return;
    }
    if (req.url === "/final") {
        res.writeHead(200);
        res.end("done");
        return;
    }
    res.writeHead(404);
    res.end("missing");
});

function onRedirectResponse(res) {
    var body = "";
    res.on("data", function(c) { body += c; });
    res.on("end", function() {
        assertEq(res.statusCode, 200, "final status after redirect");
        assertEq(body, "done", "final body");
        chain.close(function() { phase = 1; startHead(); });
    });
}

function followRedirects(opts, maxRedirects, onRes, onErr) {
    var left = maxRedirects;
    function go(path) {
        var reqOpts = {
            hostname: opts.hostname,
            port: opts.port,
            path: path,
            method: opts.method || "GET",
            agent: opts.agent
        };
        var req = http.request(reqOpts, function(res) {
            if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location && left > 0) {
                left = left - 1;
                res.resume();
                go(res.headers.location);
                return;
            }
            onRes(res);
        });
        req.on("error", onErr);
        req.end();
    }
    go(opts.path);
}

chain.listen(0, "127.0.0.1", function() {
    var port = chain.address().port;
    var baseOpts = {
        hostname: "127.0.0.1",
        port: port,
        path: "/start",
        method: "GET",
        agent: false
    };

    if (onJacEngine) {
        var req = http.request(Object.assign({ maxRedirects: 3 }, baseOpts), onRedirectResponse);
        req.on("error", function(e) {
            console.error("redirect: " + e.message);
            chain.close();
            __reg.bump();
            __jacDone();
        });
        req.end();
        return;
    }

    followRedirects(baseOpts, 3, onRedirectResponse, function(e) {
        console.error("redirect: " + e.message);
        chain.close();
        __reg.bump();
        __jacDone();
    });
});

function startHead() {
    var headServer = http.createServer(function(req, res) {
        assertEq(req.method, "HEAD", "HEAD method");
        res.writeHead(200, { "Content-Length": "99" });
        res.end("should-not-see");
    });

    headServer.listen(0, "127.0.0.1", function() {
        var port = headServer.address().port;
        var req = http.request({
            hostname: "127.0.0.1",
            port: port,
            path: "/",
            method: "HEAD",
            agent: false
        }, function(res) {
            assertEq(res.statusCode, 200, "HEAD status");
            var body = "";
            res.on("data", function(c) { body += c; });
            res.on("end", function() {
                assertEq(body, "", "HEAD has no body");
                headServer.close(function() { phase = 2; startContinue(); });
            });
        });
        req.end();
    });
}

function startContinue() {
    var contServer = http.createServer(function(req, res) {
        var body = "";
        req.on("data", function(c) { body += c; });
        req.on("end", function() {
            assertEq(body, "payload", "POST body");
            res.writeHead(200);
            res.end("continued");
        });
    });

    contServer.listen(0, "127.0.0.1", function() {
        var port = contServer.address().port;
        var req = http.request({
            hostname: "127.0.0.1",
            port: port,
            path: "/",
            method: "POST",
            headers: { "Expect": "100-continue" },
            agent: false
        }, function(res) {
            var body = "";
            res.on("data", function(c) { body += c; });
            res.on("end", function() {
                assertEq(body, "continued", "100-continue flow");
                contServer.close(function() { __jacDone(); });
            });
        });
        req.end("payload");
    });
}

setTimeout(function() {
    console.error("FAIL: redirect/head timeout phase=" + phase);
    __reg.bump();
    __jacDone();
}, 12000);
