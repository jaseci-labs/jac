// Server advanced: upgrade, chunked request bodies, uniqueHeaders, checkHeader* aliases
var http = require("http");
var net = require("net");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/19_http/test_http_server_advanced.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

var onJacEngine = __jacHarness.isJacEngineRunner();
var phase = 0;

if (onJacEngine) {
    assertEq(typeof http.checkHeaderName, "function", "checkHeaderName export");
    assertEq(typeof http.checkHeaderValue, "function", "checkHeaderValue export");
    http.checkHeaderName("X-Ok");
    http.checkHeaderValue("X-Ok", "value");
    startUniqueHeaders();
} else {
    startChunked();
}

function startUniqueHeaders() {
    var uniqueServer = http.createServer({ uniqueHeaders: ["x-test"] }, function(req, res) {
        var dupThrown = false;
        try {
            res.setHeader("X-Test", "a");
            res.setHeader("X-Test", "b");
        } catch (e) {
            dupThrown = e && e.code === "ERR_HTTP_HEADERS_SENT";
        }
        assert(dupThrown, "uniqueHeaders duplicate throws");
        res.writeHead(200);
        res.end("ok");
    });

    uniqueServer.listen(0, "127.0.0.1", function() {
        var uport = uniqueServer.address().port;
        http.get("http://127.0.0.1:" + uport + "/", function(res) {
            res.on("data", function() {});
            res.on("end", function() {
                uniqueServer.close(function() { phase = 1; startChunked(); });
            });
        }).on("error", function(e) {
            console.error("unique get: " + e.message);
            __reg.bump();
            __jacDone();
        });
    });
}

function startChunked() {
    var chunkedServer = http.createServer(function(req, res) {
        var body = "";
        req.on("data", function(c) { body += c; });
        req.on("end", function() {
            assertEq(body, "hello", "chunked body");
            res.end("chunk-ok");
        });
    });

    chunkedServer.listen(0, "127.0.0.1", function() {
        var cport = chunkedServer.address().port;
        var raw = "POST / HTTP/1.1" + "\r\n" +
            "Host: 127.0.0.1\r\n" +
            "Transfer-Encoding: chunked\r\n" +
            "\r\n" +
            "5\r\n" +
            "hello\r\n" +
            "0\r\n" +
            "\r\n";
        var sock = net.connect(cport, "127.0.0.1", function() {
            sock.write(raw);
        });
        var resp = "";
        sock.on("data", function(d) {
            resp += d;
            if (resp.indexOf("chunk-ok") !== -1) {
                sock.destroy();
                chunkedServer.close(function() { phase = 2; startUpgrade(); });
            }
        });
        sock.on("error", function(e) {
            console.error("chunked: " + e.message);
            chunkedServer.close();
            __reg.bump();
            __jacDone();
        });
    });
}

function startUpgrade() {
    var upgradeHit = false;
    var upgradeServer = http.createServer();
    upgradeServer.on("upgrade", function(req, socket, head) {
        upgradeHit = true;
        assertEq(req.method, "GET", "upgrade method");
        assert(req.headers["upgrade"] !== undefined, "upgrade header");
        socket.end();
    });

    upgradeServer.listen(0, "127.0.0.1", function() {
        var wport = upgradeServer.address().port;
        var req = "GET / HTTP/1.1\r\n" +
            "Host: 127.0.0.1\r\n" +
            "Connection: Upgrade\r\n" +
            "Upgrade: websocket\r\n" +
            "\r\n";
        var wsock = net.connect(wport, "127.0.0.1", function() {
            wsock.write(req);
        });
        wsock.on("end", function() {
            assert(upgradeHit, "upgrade event fired");
            upgradeServer.close(function() { __jacDone(); });
        });
        wsock.on("error", function(e) {
            console.error("upgrade: " + e.message);
            upgradeServer.close();
            __reg.bump();
            __jacDone();
        });
    });
}

setTimeout(function() {
    console.error("FAIL: test_http_server_advanced timeout phase=" + phase);
    __reg.bump();
    __jacDone();
}, 12000);
