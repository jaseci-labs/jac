// HTTP forward proxy — setGlobalProxyFromEnv sends absolute-URI request line to proxy
var http = require("http");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/19_http/test_http_proxy.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

var backendPort = 0;
var backend = http.createServer(function(req, res) {
    res.end("direct");
});

backend.listen(0, "127.0.0.1", function() {
    backendPort = backend.address().port;

    var proxy = http.createServer(function(req, res) {
        assert(req.url.indexOf("http://127.0.0.1:" + backendPort + "/") === 0,
            "absolute URI to origin");
        res.writeHead(200, { "Content-Type": "text/plain" });
        res.end("proxied-ok");
    });

    proxy.listen(0, "127.0.0.1", function() {
        var pport = proxy.address().port;
        var restore = http.setGlobalProxyFromEnv({
            HTTP_PROXY: "http://127.0.0.1:" + pport,
            NO_PROXY: ""
        });

        http.get("http://127.0.0.1:" + backendPort + "/", function(res) {
            var body = "";
            res.on("data", function(c) { body += c; });
            res.on("end", function() {
                assertEq(res.statusCode, 200, "status via proxy");
                assertEq(body, "proxied-ok", "body via proxy");
                restore();
                proxy.close(function() {
                    backend.close(function() { __jacDone(); });
                });
            });
        }).on("error", function(err) {
            console.error("FAIL client: " + err.message);
            restore();
            proxy.close();
            backend.close();
            __reg.bump();
            __jacDone();
        });
    });
});

setTimeout(function() {
    console.error("FAIL: test_http_proxy timeout");
    backend.close();
    __reg.bump();
    __jacDone();
}, 8000);
