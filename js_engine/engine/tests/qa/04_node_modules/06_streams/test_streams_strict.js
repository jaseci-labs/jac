// STRM-S-001..020: strict Node v24 node:stream parity
var stream = require("stream");
var nodeStream = require("node:stream");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/06_streams/test_streams_strict.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

var onJacEngine = __jacHarness.isJacEngineRunner();

assert(typeof stream.Readable === "function", "STRM-S-001: Readable");
assert(typeof stream.Writable === "function", "STRM-S-001: Writable");
assert(typeof stream.Duplex === "function", "STRM-S-001: Duplex");
assert(typeof stream.Transform === "function", "STRM-S-001: Transform");
assert(typeof stream.PassThrough === "function", "STRM-S-001: PassThrough");
assert(typeof stream.pipeline === "function", "STRM-S-002: pipeline");
assert(typeof stream.finished === "function", "STRM-S-002: finished");
assert(typeof stream.duplexPair === "function", "STRM-S-002: duplexPair");
assert(typeof stream.compose === "function", "STRM-S-002: compose");
assert(typeof stream.addAbortSignal === "function", "STRM-S-002: addAbortSignal");
assert(typeof stream.isReadable === "function", "STRM-S-002: isReadable");
assert(typeof stream.isWritable === "function", "STRM-S-002: isWritable");
assert(typeof stream.isErrored === "function", "STRM-S-002: isErrored");
var expectedByteHwm = onJacEngine ? 16384 : (process.platform === "win32" ? 16384 : 65536);
assertEq(stream.getDefaultHighWaterMark(false), expectedByteHwm, "STRM-S-003: default byte HWM");
assertEq(stream.getDefaultHighWaterMark(true), 16, "STRM-S-003: default object HWM");
assert(typeof stream.Readable.from === "function", "STRM-S-004: Readable.from");
assert(typeof stream.promises === "object", "STRM-S-005: stream.promises");
assert(typeof stream.promises.pipeline === "function", "STRM-S-005: promises.pipeline");
assert(typeof stream.promises.finished === "function", "STRM-S-005: promises.finished");

var sp = require("stream/promises");
assert(sp === stream.promises, "STRM-S-006: stream/promises alias");
assert(nodeStream.Readable === stream.Readable, "STRM-S-007: node:stream identity");

// Backpressure
var blocked = false;
var drainFired = false;
var slow = new stream.Writable({
    highWaterMark: 8,
    write: function (chunk, enc, cb) {
        blocked = true;
        setTimeout(function () {
            blocked = false;
            cb();
        }, 20);
    }
});
slow.on("drain", function () { drainFired = true; });
var ok = slow.write("1234567890");
assert(ok === false, "STRM-S-008: write returns false under backpressure");

// Pipe + finish
var pipeOut = [];
var pr = new stream.Readable({ read: function () {} });
var pw = new stream.Writable({
    write: function (c, e, cb) { pipeOut.push(String(c)); cb(); }
});
var finishCount = 0;
pw.on("finish", function () { finishCount = finishCount + 1; });
pr.pipe(pw);
pr.push("a");
pr.push("b");
pr.push(null);

// Duplex / Transform
var pt = new stream.PassThrough();
var tfOut = [];
pt.on("data", function (c) { tfOut.push(String(c)); });
pt.write("x");
pt.end("y");

// duplexPair
var pair = stream.duplexPair();
assert(pair && pair.length === 2, "STRM-S-009: duplexPair length");

// destroy idempotent
var d = new stream.Readable({ read: function () {} });
var closeN = 0;
d.on("close", function () { closeN = closeN + 1; });
d.destroy();
d.destroy();
assert(closeN === 0, "STRM-S-010: close deferred after destroy");

setTimeout(function () {
    assert(closeN === 1, "STRM-S-010: single close after destroy");
    assert(drainFired, "STRM-S-008: drain after backpressure clears");
    assert(pipeOut.join("") === "ab", "STRM-S-011: pipe transfers data");
    assert(finishCount === 1, "STRM-S-011: pipe finish once");
    assert(tfOut.indexOf("x") >= 0, "STRM-S-012: PassThrough data");

    stream.promises.finished(pw).then(function () {
        runPipelineTest();
    }).catch(function (e) {
        assert(false, "STRM-S-013: finished promise failed: " + String(e));
        __jacDone();
    });
}, 120);

function runPipelineTest() {
    var src = stream.Readable.from(["p", "q"]);
    var dst = new stream.Writable({
        write: function (c, e, cb) { cb(); }
    });
    stream.promises.pipeline(src, dst).then(function () {
        assert(true, "STRM-S-013: promises.pipeline resolves");
        __jacDone();
    }).catch(function (e) {
        assert(false, "STRM-S-013: promises.pipeline failed: " + String(e));
        __jacDone();
    });
}
