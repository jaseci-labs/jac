#!/usr/bin/env bash
# RRES: createRequire().resolve()/require() must ALWAYS use CJS resolution (the
# "require" exports condition) — even inside a module evaluated under import().
# Regression: the ambient require_is_esm flag leaked into the resolver, picking
# the "import" condition (broke Vite's rollup package.json lookup).
# Own node_modules symlink (isolated dir — no clash with 22_packages).
set -uo pipefail
here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck disable=SC1091
source "$here/../../_harness/regression_case_sh.sh"
: "${JAC_JS_RUNNER:=bin/js_engine}"

suite="regression/04_node_modules/24_require_resolve/test_require_resolve_conditions.sh"

if [[ -e "$here/node_modules" && ! -L "$here/node_modules" ]]; then
    regression_record_fail "RRES-000: $here/node_modules exists and is not a symlink; refusing to shadow it"
    regression_finish_test_case "$suite"
fi
ln -sfn "$here/_fixtures_node_modules" "$here/node_modules"
cleanup() { [[ -L "$here/node_modules" ]] && rm -f "$here/node_modules"; }
trap cleanup EXIT

check() {
    local label=$1 file=$2 okmark=$3
    local exit_code=0 out
    out=$("$JAC_JS_RUNNER" "$here/$file" 2>&1) || exit_code=$?
    if [[ $exit_code -ne 0 ]]; then
        regression_record_fail "$label crashed (exit $exit_code): $out"
    elif [[ "$out" == *"FAIL:"* ]]; then
        regression_record_fail "$label: $out"
    elif [[ "$out" != *"$okmark"* ]]; then
        regression_record_fail "$label did not complete: $out"
    fi
}

check "RRES-entry"      rres_entry.fixture.mjs      "RRES-ENTRY OK"
check "RRES-via-import" rres_via_import.fixture.mjs "RRES-INNER OK"

regression_finish_test_case "$suite"
