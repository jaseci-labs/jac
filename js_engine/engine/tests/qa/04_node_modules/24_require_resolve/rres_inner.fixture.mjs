import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const p = require.resolve('dualpkg');
if (!p.endsWith('/cjs/index.js')) console.log("FAIL: inner resolve picked " + p + " (must be the require-condition cjs entry)");
const m = require('dualpkg');
if (m.kind !== 'cjs') console.log("FAIL: inner require() loaded kind=" + m.kind + " (must be cjs)");
console.log("RRES-INNER OK");
