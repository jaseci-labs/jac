// TMR-001 through TMR-005: timers module
var timers = require("timers");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/08_timers/test_timers_module.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

// TMR-001: require("timers") exports same functions
assert(typeof timers.setTimeout === "function",    "TMR-001: timers.setTimeout");
assert(typeof timers.setInterval === "function",   "TMR-001: timers.setInterval");
assert(typeof timers.setImmediate === "function",  "TMR-001: timers.setImmediate");
assert(typeof timers.clearTimeout === "function",  "TMR-001: timers.clearTimeout");
assert(typeof timers.clearInterval === "function", "TMR-001: timers.clearInterval");
assert(typeof timers.clearImmediate === "function","TMR-001: timers.clearImmediate");

// Verify they behave the same as globals
var t1 = timers.setTimeout(function(){}, 9999);
assert(t1 !== null && t1 !== undefined, "TMR-001: timers.setTimeout returns handle");
timers.clearTimeout(t1);

var passed = 0;
var total = 0;

function done() {
    passed++;
    if (passed >= total) __jacDone();
}

// TMR-002: timers/promises.setTimeout
var timersPromises;
try { timersPromises = require("timers/promises"); } catch(e) {}
if (timersPromises && typeof timersPromises.setTimeout === "function") {
    total++;
    var p = timersPromises.setTimeout(50, "result");
    assert(typeof p.then === "function", "TMR-002: timers/promises.setTimeout returns Promise");
    p.then(function(val) {
        assertEq(val, "result", "TMR-002: timers/promises.setTimeout resolves with value");
        done();
    });
}

// TMR-003: timers/promises.setImmediate
if (timersPromises && typeof timersPromises.setImmediate === "function") {
    total++;
    timersPromises.setImmediate("immResult").then(function(val) {
        assertEq(val, "immResult", "TMR-003: timers/promises.setImmediate resolves");
        done();
    });
}

// TMR-004: scheduler.wait/yield — may be absent
var scheduler;
try { scheduler = require("timers/promises").scheduler; } catch(e) {}
if (scheduler) {
    if (typeof scheduler.wait === "function") {
        total++;
        scheduler.wait(10).then(function() { done(); });
    }
}

// TMR-005: Timer ordering — setTimeout(0) vs setImmediate vs nextTick
total++;
var order5 = [];
process.nextTick(function() { order5.push("nextTick"); });
Promise.resolve().then(function() { order5.push("microtask"); });
timers.setImmediate(function() { order5.push("setImmediate"); });
timers.setTimeout(function() {
    order5.push("setTimeout");
    // nextTick and microtask fire before I/O callbacks (setImmediate/setTimeout)
    assert(order5.indexOf("nextTick") < order5.indexOf("setTimeout"),
        "TMR-005: nextTick before setTimeout");
    assert(order5.indexOf("microtask") < order5.indexOf("setTimeout"),
        "TMR-005: microtask before setTimeout");
    done();
}, 0);

// Timeout safety
setTimeout(function() {
    if (passed < total) {
        console.error("FAIL: TMR timers/promises test timed out (" + passed + "/" + total + ")");
        __reg.bump(); return;
    }
}, 3000);

if (total === 0) __jacDone();
