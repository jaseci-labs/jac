// Plan: testing_plans/06_process_os_stdio/NODE_OS_COMPREHENSIVE_TEST_PLAN.md — NOS-U
var os = require("os");
var Buffer = require("buffer").Buffer;

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/03_os/test_os_nos_userinfo.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

var plat = process.platform;

// NOS-U-001
var ui = os.userInfo();
assert(typeof ui === "object" && ui !== null, "NOS-U-001: userInfo() returns object");
assertEq(typeof ui.username, "string", "NOS-U-001: username is string");
assertEq(typeof ui.uid, "number", "NOS-U-001: uid is number");
assertEq(typeof ui.gid, "number", "NOS-U-001: gid is number");
assertEq(typeof ui.homedir, "string", "NOS-U-001: homedir is string");
if (plat === "win32") {
    assert(ui.shell === null || typeof ui.shell === "string", "NOS-U-001: shell null or string on Windows");
} else {
    assertEq(typeof ui.shell, "string", "NOS-U-001: shell is string on POSIX");
}

// NOS-U-002
if (plat === "win32") {
    assertEq(ui.uid, -1, "NOS-U-002: uid is -1 on Windows");
    assertEq(ui.gid, -1, "NOS-U-002: gid is -1 on Windows");
} else {
    assert(ui.uid >= 0, "NOS-U-002: uid >= 0 on POSIX");
    assert(ui.gid >= 0, "NOS-U-002: gid >= 0 on POSIX");
}

// NOS-U-003
var uiUtf8 = os.userInfo({ encoding: "utf8" });
assertEq(ui.username, uiUtf8.username, "NOS-U-003: utf8 encoding matches default username");
assertEq(ui.homedir, uiUtf8.homedir, "NOS-U-003: utf8 encoding matches default homedir");

// NOS-U-004
var uiBuf = os.userInfo({ encoding: "buffer" });
assert(Buffer.isBuffer(uiBuf.username), "NOS-U-004: username is Buffer with encoding buffer");
assert(Buffer.isBuffer(uiBuf.homedir), "NOS-U-004: homedir is Buffer with encoding buffer");
if (plat !== "win32") {
    assert(Buffer.isBuffer(uiBuf.shell), "NOS-U-004: shell is Buffer with encoding buffer on POSIX");
}

// NOS-U-005 — unknown encoding string: Node falls back to default string result (does not throw)
var defUi = os.userInfo();
var bogusEnc = os.userInfo({ encoding: "not_a_real_encoding_xyz" });
assertEq(typeof bogusEnc.username, "string", "NOS-U-005: unknown encoding yields string username");
assertEq(defUi.username, bogusEnc.username, "NOS-U-005: unknown encoding matches default username");

// NOS-U-006 — both homedirs are strings; OS may differ precedence vs env-based homedir()
assert(typeof os.homedir() === "string", "NOS-U-006: homedir() is string");
assert(typeof ui.homedir === "string", "NOS-U-006: userInfo().homedir is string");

__jacDone();
