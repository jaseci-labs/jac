// Plan: testing_plans/06_process_os_stdio/NODE_OS_COMPREHENSIVE_TEST_PLAN.md — NOS-N
var os = require("os");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/03_os/test_os_nos_network.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

var ni = os.networkInterfaces();
assert(typeof ni === "object" && ni !== null, "NOS-N-001: networkInterfaces returns object");

var keys = Object.keys(ni);
assert(keys.length > 0, "NOS-N-001: at least one interface");

// NOS-N-002 / NOS-N-006 — each value is array; Node assigns addresses (not all-empty on typical hosts)
var allEmpty = true;
var ki = 0;
while (ki < keys.length) {
    var ifname = keys[ki];
    var addrs = ni[ifname];
    assert(Array.isArray(addrs), "NOS-N-002: " + ifname + " maps to array");
    if (addrs.length > 0) {
        allEmpty = false;
    }
    ki = ki + 1;
}
assert(!allEmpty, "NOS-N-006: networkInterfaces has at least one address entry (not all empty stubs)");

// NOS-N-003 / NOS-N-004 — inspect first non-empty interface
var pick = null;
var pickName = "";
var pj = 0;
while (pj < keys.length) {
    var nm = keys[pj];
    if (ni[nm].length > 0) {
        pickName = nm;
        pick = ni[nm][0];
        break;
    }
    pj = pj + 1;
}
assert(pick !== null, "NOS-N-003: found address record");
assertEq(typeof pick.address, "string", "NOS-N-003: address is string");
assertEq(typeof pick.netmask, "string", "NOS-N-003: netmask is string");
assertEq(typeof pick.mac, "string", "NOS-N-003: mac is string");
assertEq(typeof pick.internal, "boolean", "NOS-N-003: internal is boolean");
assert(pick.family === "IPv4" || pick.family === "IPv6", "NOS-N-004: family is IPv4 or IPv6 string");
if (pick.cidr !== null) {
    assertEq(typeof pick.cidr, "string", "NOS-N-003: cidr is string or null");
}
if (pick.family === "IPv6" && typeof pick.scopeid !== "undefined") {
    assertEq(typeof pick.scopeid, "number", "NOS-N-003: scopeid is number for IPv6");
}

// NOS-N-005 — loopback
var loNames = ["lo", "lo0"];
var li = 0;
while (li < loNames.length) {
    var lon = loNames[li];
    if (ni[lon] && ni[lon].length > 0) {
        var lk = 0;
        while (lk < ni[lon].length) {
            var rec = ni[lon][lk];
            if (rec.address === "127.0.0.1" || rec.address === "::1") {
                assertEq(rec.internal, true, "NOS-N-005: loopback address internal true");
            }
            lk = lk + 1;
        }
    }
    li = li + 1;
}

__jacDone();
