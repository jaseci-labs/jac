// Plan: testing_plans/06_process_os_stdio/NODE_OS_COMPREHENSIVE_TEST_PLAN.md — NOS-M, NOS-I, NOS-P, NOS-R, NOS-C
var os = require("os");
var osNode = require("node:os");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/03_os/test_os_nos_core.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

var requiredExports = [
    "platform", "arch", "type", "release", "hostname", "homedir", "tmpdir", "endianness",
    "cpus", "totalmem", "freemem", "uptime", "loadavg", "networkInterfaces", "userInfo",
    "constants", "EOL", "devNull"
];

// NOS-M-001
assert(typeof os === "object" && os !== null, "NOS-M-001: require('os') returns object");
var k = 0;
while (k < requiredExports.length) {
    var name = requiredExports[k];
    assert(typeof os[name] !== "undefined", "NOS-M-001: os." + name + " is defined");
    k = k + 1;
}

// NOS-M-002
assertEq(typeof osNode, "object", "NOS-M-002: require('node:os') returns object");
k = 0;
while (k < requiredExports.length) {
    var n = requiredExports[k];
    assertEq(typeof os[n], typeof osNode[n], "NOS-M-002: os and node:os export same type for " + n);
    k = k + 1;
}

// NOS-M-004 — optional Node APIs: if present, must be proper callables (no broken placeholders)
var optionalNames = ["availableParallelism", "machine", "version", "getPriority", "setPriority"];
var oi = 0;
while (oi < optionalNames.length) {
    var on = optionalNames[oi];
    if (typeof os[on] !== "undefined") {
        assertEq(typeof os[on], "function", "NOS-M-004: os." + on + " must be function when defined");
    }
    oi = oi + 1;
}

// NOS-I-001 / NOS-I-002
assertEq(os.platform(), process.platform, "NOS-I-001: os.platform aligns with process.platform");
assertEq(os.arch(), process.arch, "NOS-I-002: os.arch aligns with process.arch");
assert(typeof os.platform() === "string" && os.platform().length > 0, "NOS-I-001: platform non-empty string");
assert(typeof os.arch() === "string" && os.arch().length > 0, "NOS-I-002: arch non-empty string");

// NOS-I-003
var plat = process.platform;
var typ = os.type();
assert(typeof typ === "string" && typ.length > 0, "NOS-I-003: type() is non-empty string");
if (plat === "linux") {
    assertEq(typ, "Linux", "NOS-I-003: os.type() === 'Linux' on linux");
} else if (plat === "darwin") {
    assertEq(typ, "Darwin", "NOS-I-003: os.type() === 'Darwin' on darwin");
} else if (plat === "win32") {
    assertEq(typ, "Windows_NT", "NOS-I-003: os.type() === 'Windows_NT' on win32");
} else if (plat === "freebsd") {
    assertEq(typ, "FreeBSD", "NOS-I-003: os.type() === 'FreeBSD' on freebsd");
} else if (plat === "openbsd") {
    assertEq(typ, "OpenBSD", "NOS-I-003: os.type() === 'OpenBSD' on openbsd");
} else {
    assert(typ.length > 0, "NOS-I-003: os.type() non-empty on other platforms");
}

// NOS-I-004
var rel = os.release();
assert(typeof rel === "string" && rel.length > 0, "NOS-I-004: release() non-empty string");

// NOS-I-005 / NOS-I-006 (Node 16+ / 13+)
if (typeof os.machine === "function") {
    var mach = os.machine();
    assert(typeof mach === "string" && mach.length > 0, "NOS-I-005: machine() non-empty string");
}
if (typeof os.version === "function") {
    var ver = os.version();
    assert(typeof ver === "string" && ver.length > 0, "NOS-I-006: version() non-empty string");
}

// NOS-I-007
var p1 = os.platform();
var p2 = os.platform();
assertEq(p1, p2, "NOS-I-007: repeated platform() is stable");

// NOS-P-001
assert(typeof os.hostname() === "string" && os.hostname().length > 0, "NOS-P-001: hostname non-empty");

// NOS-P-002
assert(typeof os.homedir() === "string" && os.homedir().length > 0, "NOS-P-002: homedir non-empty string");

// NOS-P-003 — tmpdir env precedence (POSIX: TMPDIR then TMP then TEMP)
var savedTmpdir = process.env.TMPDIR;
var savedTmp = process.env.TMP;
var savedTemp = process.env.TEMP;
if (plat === "linux" || plat === "darwin" || plat === "freebsd" || plat === "openbsd") {
    delete process.env.TMPDIR;
    delete process.env.TMP;
    delete process.env.TEMP;
    process.env.TMPDIR = "/tmp/nos_os_tmpdir_precedence_test";
    assertEq(os.tmpdir(), "/tmp/nos_os_tmpdir_precedence_test", "NOS-P-003: tmpdir honors TMPDIR on POSIX");
    delete process.env.TMPDIR;
    process.env.TEMP = "/tmp/nos_os_temp_only";
    process.env.TMP = "/tmp/nos_os_tmp_only";
    assertEq(os.tmpdir(), "/tmp/nos_os_tmp_only", "NOS-P-003: tmpdir prefers TMP over TEMP on POSIX");
    delete process.env.TMP;
    process.env.TEMP = "/tmp/nos_os_temp_only2";
    assertEq(os.tmpdir(), "/tmp/nos_os_temp_only2", "NOS-P-003: tmpdir uses TEMP when TMP unset on POSIX");
} else if (plat === "win32") {
    delete process.env.TEMP;
    delete process.env.TMP;
    process.env.TEMP = "C:\\nos_os_temp_test";
    process.env.TMP = "C:\\nos_os_tmp_test";
    assertEq(os.tmpdir(), "C:\\nos_os_temp_test", "NOS-P-003: tmpdir prefers TEMP over TMP on Windows");
}
if (savedTmpdir !== undefined) { process.env.TMPDIR = savedTmpdir; } else { delete process.env.TMPDIR; }
if (savedTmp !== undefined) { process.env.TMP = savedTmp; } else { delete process.env.TMP; }
if (savedTemp !== undefined) { process.env.TEMP = savedTemp; } else { delete process.env.TEMP; }

// NOS-P-004 / NOS-P-005
if (plat === "win32") {
    assertEq(os.EOL, "\r\n", "NOS-P-004: EOL is CRLF on Windows");
    assertEq(os.devNull, "\\\\.\\nul", "NOS-P-005: devNull on Windows");
} else {
    assertEq(os.EOL, "\n", "NOS-P-004: EOL is LF on POSIX");
    assertEq(os.devNull, "/dev/null", "NOS-P-005: devNull is /dev/null on POSIX");
}

// NOS-P-006 — homedir when HOME unset (POSIX); skip on Windows (different rules)
if (plat === "linux" || plat === "darwin" || plat === "freebsd" || plat === "openbsd") {
    var savedHome = process.env.HOME;
    delete process.env.HOME;
    var hdFallback = os.homedir();
    if (savedHome !== undefined) { process.env.HOME = savedHome; } else { delete process.env.HOME; }
    assert(typeof hdFallback === "string" && hdFallback.length > 0, "NOS-P-006: homedir() non-empty when HOME unset");
}

// NOS-R-001 / NOS-R-002
var tm = os.totalmem();
var fm = os.freemem();
assertEq(typeof tm, "number", "NOS-R-001: totalmem is number");
assert(tm > 0, "NOS-R-001: totalmem > 0");
assertEq(typeof fm, "number", "NOS-R-002: freemem is number");
assert(fm >= 0, "NOS-R-002: freemem >= 0");
assert(fm <= tm, "NOS-R-002: freemem <= totalmem");

// NOS-R-003
var up1 = os.uptime();
var up2 = os.uptime();
assert(typeof up1 === "number", "NOS-R-003: uptime is number");
assert(up1 > 0, "NOS-R-003: uptime > 0");
assert(up2 >= up1, "NOS-R-003: uptime monotonic");

// NOS-R-004
if (typeof os.availableParallelism === "function") {
    var ap = os.availableParallelism();
    assert(typeof ap === "number" && ap > 0, "NOS-R-004: availableParallelism() > 0");
    assertEq(ap, ap | 0, "NOS-R-004: availableParallelism() is integral");
}

// NOS-C-001 / NOS-C-002
var cpus = os.cpus();
assert(Array.isArray(cpus), "NOS-C-001: cpus() is array");
if (cpus.length > 0) {
    var c0 = cpus[0];
    assertEq(typeof c0.model, "string", "NOS-C-001: cpu.model is string");
    assertEq(typeof c0.speed, "number", "NOS-C-001: cpu.speed is number");
    assert(typeof c0.times === "object" && c0.times !== null, "NOS-C-002: cpu.times is object");
    assertEq(typeof c0.times.user, "number", "NOS-C-002: times.user is number");
    assertEq(typeof c0.times.nice, "number", "NOS-C-002: times.nice is number");
    assertEq(typeof c0.times.sys, "number", "NOS-C-002: times.sys is number");
    assertEq(typeof c0.times.idle, "number", "NOS-C-002: times.idle is number");
    assertEq(typeof c0.times.irq, "number", "NOS-C-002: times.irq is number");
}

// NOS-C-004
var la = os.loadavg();
assert(Array.isArray(la) && la.length === 3, "NOS-C-004: loadavg length 3");
assert(typeof la[0] === "number" && typeof la[1] === "number" && typeof la[2] === "number", "NOS-C-004: loadavg elements are numbers");
if (plat === "win32") {
    assertEq(la[0], 0, "NOS-C-004: loadavg[0] is 0 on Windows");
    assertEq(la[1], 0, "NOS-C-004: loadavg[1] is 0 on Windows");
    assertEq(la[2], 0, "NOS-C-004: loadavg[2] is 0 on Windows");
} else {
    assert(la[0] >= 0 && la[1] >= 0 && la[2] >= 0, "NOS-C-004: loadavg non-negative on Unix");
}

// NOS-C-005 / NOS-C-006
var end = os.endianness();
assert(end === "LE" || end === "BE", "NOS-C-005: endianness is LE or BE");
if (plat === "linux" || plat === "darwin" || plat === "win32") {
    var ar = os.arch();
    if (ar === "x64" || ar === "ia32" || ar === "arm64" || ar === "arm") {
        assertEq(end, "LE", "NOS-C-006: endianness LE for common little-endian arch " + ar);
    }
}

__jacDone();
