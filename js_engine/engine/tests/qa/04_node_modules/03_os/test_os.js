// OS-001..OS-007 + NOS-* — see testing_plans/06_process_os_stdio/NODE_OS_COMPREHENSIVE_TEST_PLAN.md
var os = require("os");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/03_os/test_os.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

// OS-001 (NOS-I-001..NOS-I-004): platform / arch / type / release
assertEq(typeof os.platform(), "string",  "OS-001 (NOS-I-001): platform() returns string");
assert(os.platform().length > 0,          "OS-001 (NOS-I-001): platform non-empty");
assertEq(typeof os.arch(),    "string",   "OS-001 (NOS-I-002): arch() returns string");
assert(os.arch().length > 0,             "OS-001 (NOS-I-002): arch non-empty");
assertEq(typeof os.type(),    "string",   "OS-001 (NOS-I-003): type() returns string");
assertEq(typeof os.release(), "string",   "OS-001 (NOS-I-004): release() returns string");

// OS-002 (NOS-P-001..NOS-P-003): hostname / homedir / tmpdir
assertEq(typeof os.hostname(), "string",  "OS-002 (NOS-P-001): hostname() returns string");
assert(os.hostname().length > 0,          "OS-002 (NOS-P-001): hostname non-empty");
assertEq(typeof os.homedir(), "string",   "OS-002 (NOS-P-002): homedir() returns string");
assert(os.homedir().length > 0,           "OS-002 (NOS-P-002): homedir non-empty");
assertEq(typeof os.tmpdir(),  "string",   "OS-002 (NOS-P-003): tmpdir() returns string");
assert(os.tmpdir().length > 0,            "OS-002 (NOS-P-003): tmpdir non-empty");

// OS-003 (NOS-C-001, NOS-C-002): cpus — array with model/speed/times
var cpus = os.cpus();
assert(Array.isArray(cpus),              "OS-003 (NOS-C-001): cpus() returns array");
if (cpus.length > 0) {
    var cpu = cpus[0];
    assertEq(typeof cpu.model,  "string", "OS-003 (NOS-C-001): cpu.model is string");
    assertEq(typeof cpu.speed,  "number", "OS-003 (NOS-C-001): cpu.speed is number");
    assert(typeof cpu.times === "object" && cpu.times !== null, "OS-003 (NOS-C-002): cpu.times is object");
    assertEq(typeof cpu.times.user,  "number", "OS-003 (NOS-C-002): times.user is number");
    assertEq(typeof cpu.times.nice,  "number", "OS-003 (NOS-C-002): times.nice is number");
    assertEq(typeof cpu.times.sys,   "number", "OS-003 (NOS-C-002): times.sys is number");
    assertEq(typeof cpu.times.idle,  "number", "OS-003 (NOS-C-002): times.idle is number");
    assertEq(typeof cpu.times.irq,   "number", "OS-003 (NOS-C-002): times.irq is number");
}

// OS-004 (NOS-R-001..NOS-R-003): totalmem / freemem / uptime
assertEq(typeof os.totalmem(), "number", "OS-004 (NOS-R-001): totalmem returns number");
assert(os.totalmem() > 0,               "OS-004 (NOS-R-001): totalmem > 0");
assertEq(typeof os.freemem(),  "number", "OS-004 (NOS-R-002): freemem returns number");
assert(os.freemem() >= 0,               "OS-004 (NOS-R-002): freemem >= 0");
assertEq(typeof os.uptime(),   "number", "OS-004 (NOS-R-003): uptime returns number");
assert(os.uptime() > 0,                 "OS-004 (NOS-R-003): uptime > 0");

// OS-005 (NOS-C-004): loadavg
var loadavg = os.loadavg();
assert(Array.isArray(loadavg),          "OS-005 (NOS-C-004): loadavg returns array");
assertEq(loadavg.length, 3,             "OS-005 (NOS-C-004): loadavg has 3 elements");
assert(typeof loadavg[0] === "number",  "OS-005 (NOS-C-004): loadavg[0] is number");

// OS-006 (NOS-N-001, NOS-U-001): networkInterfaces / userInfo
var ni = os.networkInterfaces();
assert(typeof ni === "object" && ni !== null, "OS-006 (NOS-N-001): networkInterfaces returns object");
if (typeof os.userInfo === "function") {
    var ui = os.userInfo();
    assert(typeof ui === "object" && ui !== null, "OS-006 (NOS-U-001): userInfo returns object");
}

// OS-007 (NOS-P-004, NOS-P-005, NOS-C-005, NOS-K-001, NOS-K-002): constants / EOL / endianness / devNull
assert(typeof os.EOL === "string",       "OS-007 (NOS-P-004): EOL is string");
assert(os.EOL === "\n" || os.EOL === "\r\n", "OS-007 (NOS-P-004): EOL is LF or CRLF");
if (typeof os.endianness === "function") {
    var end = os.endianness();
    assert(end === "BE" || end === "LE",  "OS-007 (NOS-C-005): endianness BE or LE");
}
if (typeof os.devNull !== "undefined") {
    assertEq(typeof os.devNull, "string", "OS-007 (NOS-P-005): devNull is string");
}
if (os.constants) {
    assert(typeof os.constants === "object", "OS-007 (NOS-K-001): constants is object");
}

__jacDone();
