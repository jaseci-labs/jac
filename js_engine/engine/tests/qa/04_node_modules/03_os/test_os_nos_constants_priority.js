// Plan: testing_plans/06_process_os_stdio/NODE_OS_COMPREHENSIVE_TEST_PLAN.md — NOS-K, NOS-S
var os = require("os");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/03_os/test_os_nos_constants_priority.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

var plat = process.platform;

// NOS-K-001
assert(typeof os.constants === "object" && os.constants !== null, "NOS-K-001: constants is object");
assert(typeof os.constants.signals === "object" && os.constants.signals !== null, "NOS-K-001: constants.signals exists");
assert(typeof os.constants.errno === "object" && os.constants.errno !== null, "NOS-K-001: constants.errno exists");

// NOS-K-002
assertEq(os.constants.signals.SIGINT, 2, "NOS-K-002: SIGINT === 2");
assertEq(os.constants.signals.SIGTERM, 15, "NOS-K-002: SIGTERM === 15");
assertEq(os.constants.signals.SIGKILL, 9, "NOS-K-002: SIGKILL === 9");

// NOS-K-003 — POSIX errno spot checks (Linux/darwin/freebsd)
if (plat !== "win32") {
    assertEq(os.constants.errno.ENOENT, 2, "NOS-K-003: ENOENT === 2 on POSIX");
    assertEq(os.constants.errno.EACCES, 13, "NOS-K-003: EACCES === 13 on POSIX");
    assertEq(os.constants.errno.EINVAL, 22, "NOS-K-003: EINVAL === 22 on POSIX");
}

// NOS-K-004 / NOS-K-005
if (typeof os.getPriority === "function") {
    assert(typeof os.constants.priority === "object" && os.constants.priority !== null, "NOS-K-004: constants.priority when getPriority exists");
}
if (plat === "linux" || plat === "darwin" || plat === "freebsd" || plat === "openbsd") {
    if (typeof os.constants.dlopen !== "undefined") {
        assert(typeof os.constants.dlopen === "object", "NOS-K-005: dlopen constants object on POSIX when present");
    }
}

// NOS-S-001
if (typeof os.getPriority === "function") {
    var pr = os.getPriority();
    assertEq(typeof pr, "number", "NOS-S-001: getPriority returns number");
}

// NOS-S-003 — invalid priority throws
if (typeof os.setPriority === "function") {
    var threw = false;
    try {
        os.setPriority(0, 9999);
    } catch (e) {
        threw = true;
        assert(e instanceof Error, "NOS-S-003: setPriority invalid arg throws Error");
    }
    assert(threw, "NOS-S-003: setPriority rejects out-of-range priority");
}

// NOS-S-002 / NOS-S-004 — best-effort: set to normal and read back (no hard assert on exact nice)
if (typeof os.setPriority === "function" && typeof os.getPriority === "function" && plat !== "win32") {
    try {
        os.setPriority(0, os.constants.priority.PRIORITY_NORMAL);
        var pr2 = os.getPriority(0);
        assertEq(typeof pr2, "number", "NOS-S-002: getPriority after setPriority still number");
    } catch (e) {
        // NOS-S-004: permission or platform restriction — must still be a proper Error path
        assert(e instanceof Error, "NOS-S-004: setPriority failure is Error");
    }
}

__jacDone();
