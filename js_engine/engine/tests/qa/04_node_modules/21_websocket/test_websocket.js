// WS-001 through WS-005: WebSocket (global or require)
var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/21_websocket/test_websocket.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

// WebSocket may be a global or need to be loaded differently
var WS = typeof WebSocket !== "undefined" ? WebSocket : null;

// Try to load from ws package or from js_engine's WebSocket global
if (!WS) {
    try { WS = require("ws"); } catch(e) {}
}

if (!WS) {
    console.log("WebSocket not available — skipping");
    __jacDone();
}

// WS-004: Constants
assertEq(WS.CONNECTING, 0, "WS-004: CONNECTING = 0");
assertEq(WS.OPEN,       1, "WS-004: OPEN = 1");
assertEq(WS.CLOSING,    2, "WS-004: CLOSING = 2");
assertEq(WS.CLOSED,     3, "WS-004: CLOSED = 3");

// WS-001: new WebSocket — verify constructor exists
assertEq(typeof WS, "function",              "WS-001: WebSocket is a function");

// WS-005: WebSocketServer — check if available in js_engine
if (typeof Server !== "undefined" && typeof Server.websocket === "function") {
    assert(true, "WS-005: Server.websocket available in js_engine");
}

// For actual connection tests, we'd need a live server.
// Just verify the constructor doesn't crash with invalid URL and that readyState is set
var wsClosed = null;
try {
    // This will fail to connect (no server) — we just check the object shape
    wsClosed = new WS("ws://127.0.0.1:1");
    assertEq(typeof wsClosed.readyState, "number",   "WS-001: readyState is number");
    assert(typeof wsClosed.send === "function",       "WS-003: WebSocket.send exists");
    assert(typeof wsClosed.close === "function",      "WS-003: WebSocket.close exists");
    assert(typeof wsClosed.addEventListener === "function" || typeof wsClosed.on === "function",
        "WS-002: event registration method exists");
    // Try to close immediately
    if (typeof wsClosed.close === "function") {
        try { wsClosed.close(); } catch(e) {}
    }
} catch(e) {
    // Some engines throw synchronously if URL is invalid — that's also OK
}

__jacDone();
