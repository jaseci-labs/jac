// FETCH-001 through FETCH-006: Fetch API (globals available without require)
var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/20_fetch/test_fetch.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

// FETCH-003: Headers constructor
assert(typeof Headers !== "undefined",                      "FETCH-003: Headers exists");
if (typeof Headers !== "undefined") {
    var h = new Headers();
    assert(typeof h.get === "function",                     "FETCH-003: Headers.get");
    assert(typeof h.set === "function",                     "FETCH-003: Headers.set");
    assert(typeof h.has === "function",                     "FETCH-003: Headers.has");
    assert(typeof h.delete === "function",                  "FETCH-003: Headers.delete");
    h.set("Content-Type", "application/json");
    assertEq(h.get("Content-Type"), "application/json",    "FETCH-003: Headers get/set");
    assert(h.has("Content-Type"),                          "FETCH-003: Headers.has true");
    assert(!h.has("X-Missing"),                            "FETCH-003: Headers.has false");
    h.delete("Content-Type");
    assert(!h.has("Content-Type"),                         "FETCH-003: Headers.delete");
    // Init from object
    var h2 = new Headers({"X-Custom": "value"});
    assertEq(h2.get("X-Custom"), "value",                  "FETCH-003: Headers from object");
}

// FETCH-004: Request constructor
assert(typeof Request !== "undefined",                      "FETCH-004: Request exists");
if (typeof Request !== "undefined") {
    var req = new Request("https://example.com/api", {method: "POST"});
    assertEq(req.method, "POST",                           "FETCH-004: Request.method");
    assertEq(typeof req.url, "string",                     "FETCH-004: Request.url");
    assertEq(typeof req.headers, "object",                 "FETCH-004: Request.headers");
}

// FETCH-005: AbortController / AbortSignal
assert(typeof AbortController !== "undefined",              "FETCH-005: AbortController exists");
if (typeof AbortController !== "undefined") {
    var ac = new AbortController();
    assert(typeof ac.abort === "function",                  "FETCH-005: abort() method");
    assert(typeof ac.signal === "object" && ac.signal !== null, "FETCH-005: signal property");
    var sig = ac.signal;
    assertEq(sig.aborted, false,                           "FETCH-005: signal.aborted initially false");
    ac.abort();
    assertEq(sig.aborted, true,                            "FETCH-005: signal.aborted true after abort()");
}

// FETCH-001/FETCH-002/FETCH-006: fetch — function must exist; actual network test needs live server
assert(typeof fetch !== "undefined",                        "FETCH-001: fetch exists");
assertEq(typeof fetch, "function",                         "FETCH-001: fetch is function");

// If Response exists, test it
if (typeof Response !== "undefined") {
    var r = new Response("body text", {status: 200, headers: {"Content-Type": "text/plain"}});
    assertEq(r.status, 200,                                "FETCH-002: Response.status");
    assertEq(r.ok, true,                                   "FETCH-002: Response.ok (200)");
    var r404 = new Response("not found", {status: 404});
    assertEq(r404.ok, false,                               "FETCH-002: Response.ok false (404)");
    assert(typeof r.text === "function",                   "FETCH-002: Response.text()");
    assert(typeof r.json === "function",                   "FETCH-002: Response.json()");
}

__jacDone();
