// TTY-001 through TTY-002: tty module
var tty = require("tty");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/16_tty/test_tty.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

// TTY-001: isatty
assertEq(typeof tty.isatty, "function",          "TTY-001: tty.isatty is function");
// stdin (fd=0), stdout (fd=1), stderr (fd=2) — return boolean
var is0 = tty.isatty(0);
var is1 = tty.isatty(1);
var is2 = tty.isatty(2);
assert(typeof is0 === "boolean",                 "TTY-001: isatty(0) returns boolean");
assert(typeof is1 === "boolean",                 "TTY-001: isatty(1) returns boolean");
assert(typeof is2 === "boolean",                 "TTY-001: isatty(2) returns boolean");
// invalid fd — should return false (not throw)
var isInvalid = tty.isatty(9999);
assert(typeof isInvalid === "boolean",           "TTY-001: isatty(invalid fd) returns boolean");
assertEq(isInvalid, false,                       "TTY-001: isatty(invalid) = false");

// TTY-002: ReadStream / WriteStream constructors exist
assert(typeof tty.ReadStream  === "function" || typeof tty.ReadStream  === "undefined",
    "TTY-002: ReadStream is function or absent");
assert(typeof tty.WriteStream === "function" || typeof tty.WriteStream === "undefined",
    "TTY-002: WriteStream is function or absent");

// TTY-003: clearLine / cursorTo stubs (Vite build reporter)
if (typeof tty.WriteStream === "function") {
    assert(typeof tty.WriteStream.prototype.clearLine === "function", "TTY-003: clearLine exists");
    assert(typeof tty.WriteStream.prototype.cursorTo === "function", "TTY-003: cursorTo exists");
}
if (typeof process.stdout.clearLine === "function") {
    try {
        process.stdout.clearLine(0);
        process.stdout.cursorTo(0);
    } catch (e) {
        assert(false, "TTY-003: stdout clearLine/cursorTo must not throw: " + e);
    }
}

__jacDone();
