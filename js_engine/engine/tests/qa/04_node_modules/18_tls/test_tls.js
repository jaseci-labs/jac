// TLS-001 through TLS-004: tls module (constructors and constants; no actual TLS connections)
var tls;
var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/18_tls/test_tls.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

try {
    tls = require("tls");
} catch(e) {
    console.log("tls module not available — skipping");
    __jacDone();
}

function assert(cond, msg) {
    if (!cond) { console.error("FAIL: " + msg); __reg.bump(); return; }
}
function assertEq(a, e, msg) {
    if (a !== e) { console.error("FAIL: " + msg + " | expected: " + JSON.stringify(e) + " | actual: " + JSON.stringify(a)); __reg.bump(); return; }
}

// TLS-001: connect — function exists
assertEq(typeof tls.connect, "function",               "TLS-001: tls.connect is function");

// TLS-002: createSecureContext — function exists and returns an object
if (typeof tls.createSecureContext === "function") {
    var ctx = tls.createSecureContext({});
    assert(typeof ctx === "object",                    "TLS-002: createSecureContext returns object");
}

// TLS-003: TLSSocket constructor exists
if (typeof tls.TLSSocket !== "undefined") {
    assertEq(typeof tls.TLSSocket, "function",         "TLS-003: TLSSocket is constructor");
}

// TLS-004: Constants — MIN/MAX_VERSION
if (tls.DEFAULT_MIN_VERSION !== undefined) {
    assertEq(typeof tls.DEFAULT_MIN_VERSION, "string", "TLS-004: DEFAULT_MIN_VERSION is string");
}
if (tls.DEFAULT_MAX_VERSION !== undefined) {
    assertEq(typeof tls.DEFAULT_MAX_VERSION, "string", "TLS-004: DEFAULT_MAX_VERSION is string");
}
// createServer exists
assertEq(typeof tls.createServer, "function",          "TLS-004: tls.createServer exists");

__jacDone();
