// NET-001 through NET-004: net module
var net = require("net");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/17_net/test_net.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

// NET-001: isIP / isIPv4 / isIPv6
assertEq(typeof net.isIP,    "function", "NET-001: net.isIP exists");
assertEq(typeof net.isIPv4,  "function", "NET-001: net.isIPv4 exists");
assertEq(typeof net.isIPv6,  "function", "NET-001: net.isIPv6 exists");

assertEq(net.isIP("192.168.1.1"),    4,  "NET-001: isIP IPv4 returns 4");
assertEq(net.isIP("::1"),            6,  "NET-001: isIP IPv6 returns 6");
assertEq(net.isIP("not an ip"),      0,  "NET-001: isIP invalid returns 0");
assertEq(net.isIP(""),               0,  "NET-001: isIP empty returns 0");

assert(net.isIPv4("192.168.1.1"),        "NET-001: isIPv4 valid");
assert(!net.isIPv4("::1"),               "NET-001: isIPv4 IPv6 = false");
assert(!net.isIPv4("not an ip"),         "NET-001: isIPv4 invalid = false");

assert(net.isIPv6("::1"),                "NET-001: isIPv6 valid");
assert(net.isIPv6("2001:db8::1"),        "NET-001: isIPv6 full");
assert(!net.isIPv6("192.168.1.1"),       "NET-001: isIPv6 IPv4 = false");

// NET-002: createServer — verify the function exists and creates an object
assertEq(typeof net.createServer, "function", "NET-002: net.createServer exists");
var server = net.createServer(function() {});
assert(typeof server === "object" && server !== null, "NET-002: createServer returns object");
assert(typeof server.listen === "function",           "NET-002: server.listen exists");
assert(typeof server.close  === "function",           "NET-002: server.close exists");
assert(typeof server.on     === "function",           "NET-002: server.on exists");
// Close immediately without listening
server.close();

// NET-003: connect / createConnection — verify functions exist
assertEq(typeof net.connect, "function",           "NET-003: net.connect exists");
assertEq(typeof net.createConnection, "function",  "NET-003: net.createConnection exists");

// NET-004: Socket
assertEq(typeof net.Socket, "function",            "NET-004: net.Socket constructor");
var sock = new net.Socket();
assert(typeof sock === "object",                   "NET-004: Socket creates object");
assert(typeof sock.connect === "function",         "NET-004: Socket.connect");
assert(typeof sock.write   === "function",         "NET-004: Socket.write");
assert(typeof sock.on      === "function",         "NET-004: Socket.on");
assert(typeof sock.destroy === "function",         "NET-004: Socket.destroy");
sock.destroy();

// Server — listen, connection, address, close using loopback
var server2 = net.createServer();
var listenPort = 0;
var serverDone = false;

server2.listen(0, "127.0.0.1", function() {
    var addr = server2.address();
    assert(typeof addr === "object",           "NET-004: address() returns object");
    assert(typeof addr.port === "number",      "NET-004: address().port is number");
    assert(addr.port > 0,                      "NET-004: address().port > 0");
    listenPort = addr.port;
    server2.close(function() { serverDone = true; });
});

setTimeout(function() {
    assert(serverDone, "NET-004: server listen+close worked");
    __jacDone();
}, 2000);
