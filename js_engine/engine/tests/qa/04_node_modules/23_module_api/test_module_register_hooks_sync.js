// testing_plans/05_modules_resolution_loading/NODE_MODULE_API_COMPREHENSIVE_TEST_PLAN.md — G6 (NMOD-HS-*)
"use strict";

var path = require("node:path");
var url = require("node:url");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/23_module_api/test_module_register_hooks_sync.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }

var m = require("node:module");
assert(typeof m.builtinModules !== "undefined", "NMOD-AVAIL-006: node:module surface");

var registerHooks = m.registerHooks;
if (typeof registerHooks !== "function") {
  console.log("ok skipped G6 NMOD-HS-*: registerHooks not available on this Node line");
  __jacDone();
}

var order = [];
var h1 = registerHooks({
  resolve: function (specifier, context, nextResolve) {
    order.push("h1r");
    return nextResolve(specifier, context);
  },
  load: function (u, ctx, nextLoad) {
    order.push("h1l");
    return nextLoad(u, ctx);
  },
});
var h2 = registerHooks({
  resolve: function (specifier, context, nextResolve) {
    order.push("h2r");
    return nextResolve(specifier, context);
  },
  load: function (u, ctx, nextLoad) {
    order.push("h2l");
    return nextLoad(u, ctx);
  },
});

var urlTrivial = url.pathToFileURL(path.join(__dirname, "fixtures", "trivial_export.cjs")).href;
var urlMark = url.pathToFileURL(path.join(__dirname, "fixtures", "cjs_mark.fixture.js")).href;
var urlLeaf = url.pathToFileURL(path.join(__dirname, "fixtures", "leaf", "leaf.fixture.js")).href;

import(urlTrivial)
  .then(function () {
    assert(order.indexOf("h2r") < order.indexOf("h1r"), "NMOD-HS-002: LIFO resolve order (h2 before h1)");
    assert(order.indexOf("h2l") < order.indexOf("h1l"), "NMOD-HS-002: LIFO load order (h2 before h1)");
    order = [];
    return import(urlMark);
  })
  .then(function () {
    assert(order.indexOf("h2r") < order.indexOf("h1r"), "NMOD-HS-002: LIFO on second distinct module");
    h2.deregister();
    order = [];
    return import(urlLeaf);
  })
  .then(function () {
    assert(order.indexOf("h2r") === -1 && order.indexOf("h2l") === -1, "NMOD-HS-003: deregister removes h2 from chain");
    assert(order.indexOf("h1r") !== -1, "NMOD-HS-003: h1 still runs after h2 deregister");
    h1.deregister();
    console.log("ok module registerHooks sync (G6 NMOD-HS-001 NMOD-HS-002 NMOD-HS-003 NMOD-HS-101 NMOD-HS-102)");
  })
  .catch(function (e) {
    console.error("FAIL: NMOD-HS-IMPORT", e);
    __reg.bump(); __jacDone();
  });
__jacDone();
