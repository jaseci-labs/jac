// NMOD-EXT-001/002/003: require.extensions, module._compile, require.cache invalidation

"use strict";

var path = require("path");
var fs = require("fs");
var os = require("os");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/23_module_api/test_require_extensions_compile.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }

var m = require("node:module");

// NMOD-EXT-001: createRequire exposes extensions + cache
var cr = m.createRequire(__filename);
assert(typeof cr.extensions === "object" && cr.extensions !== null, "NMOD-EXT-001: require.extensions exists on createRequire");
assert(typeof cr.extensions[".js"] === "function", "NMOD-EXT-001: default .js loader present");
assert(typeof cr.extensions[".json"] === "function", "NMOD-EXT-001: default .json loader present");
assert(typeof cr.extensions[".node"] === "function", "NMOD-EXT-001: default .node loader present");
assert(typeof cr.cache === "object" && cr.cache !== null, "NMOD-EXT-001: require.cache on createRequire");

// Global require also exposes extensions (Node parity)
assert(typeof require.extensions === "object", "NMOD-EXT-001: global require.extensions");
assert(require.extensions === cr.extensions, "NMOD-EXT-001: shared extensions table");

// NMOD-EXT-002: module._compile via extensions override (Vite pattern)
var tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), "jac-ext-"));
var cfgPath = path.join(tmpDir, "vite.config.js");
fs.writeFileSync(cfgPath, "// placeholder on disk\n");

var bundled = "module.exports = { plugins: [], root: '/tmp/vite-test' };";
var loaderExt = ".js";
var defaultLoader = cr.extensions[loaderExt];
assert(typeof defaultLoader === "function", "NMOD-EXT-002: saved default loader");

cr.extensions[loaderExt] = function (mod, filename) {
    if (filename === cfgPath) {
        mod._compile(bundled, filename);
    } else {
        defaultLoader(mod, filename);
    }
};

delete cr.cache[cr.resolve(cfgPath)];
var loaded = cr(cfgPath);
assert(loaded && loaded.root === "/tmp/vite-test", "NMOD-EXT-002: bundled config via _compile");
assert(Array.isArray(loaded.plugins), "NMOD-EXT-002: exports shape preserved");

cr.extensions[loaderExt] = defaultLoader;

// NMOD-EXT-003: cache delete forces reload (fresh module object)
var markerPath = path.join(__dirname, "fixtures", "cjs_mark.fixture.js");
var first = cr(markerPath);
assert(first.nmodMark === 99, "NMOD-EXT-003: baseline fixture load");
delete cr.cache[cr.resolve(markerPath)];
var second = cr(markerPath);
assert(second.nmodMark === 99, "NMOD-EXT-003: reload after cache delete");
assert(second !== first, "NMOD-EXT-003: fresh exports after cache invalidation");

// Module surface aliases
assert(typeof m.Module._extensions === "object", "NMOD-EXT-001: Module._extensions alias");
assert(typeof m.Module.prototype._compile === "function", "NMOD-EXT-002: Module.prototype._compile exists");

try { fs.rmSync(tmpDir, { recursive: true, force: true }); } catch (e) { /* ignore */ }

console.log("ok require.extensions / module._compile / require.cache (NMOD-EXT-*)");
__jacDone();
