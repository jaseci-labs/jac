"use strict";

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/23_module_api/test_module_strip_types_and_legacy.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }

var m = require("node:module");
assert(typeof m.builtinModules !== "undefined", "NMOD-AVAIL-008: node:module surface");

assert(require("module") === m, "NMOD-LEG-001: module and node:module aliases stable");

if (typeof m.stripTypeScriptTypes === "function") {
  var out = m.stripTypeScriptTypes("const x: number = 1;", { mode: "strip" });
  assert(out.indexOf(":") === -1, "NMOD-TS-001: strip mode removes type annotation");
  var out2 = m.stripTypeScriptTypes("const x: number = 1;", { mode: "strip", sourceUrl: "a.ts" });
  assert(out2.indexOf("sourceURL") !== -1, "NMOD-TS-004: sourceUrl comment appended");
  var threw = false;
  try {
    m.stripTypeScriptTypes("const x: number = 1;", { mode: "strip", sourceMap: true });
  } catch (e) {
    threw = true;
  }
  assert(threw, "NMOD-TS-003: strip + sourceMap errors");
} else {
  console.log("skip NMOD-TS-*: stripTypeScriptTypes not on this Node line");
}

console.log("ok module strip types + legacy checks (G8 NMOD-TS-* NMOD-LEG-*)");
__jacDone();
