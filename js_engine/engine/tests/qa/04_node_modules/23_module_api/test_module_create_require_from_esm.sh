#!/usr/bin/env bash
# testing_plans/05_modules_resolution_loading/NODE_MODULE_API_COMPREHENSIVE_TEST_PLAN.md — NMOD-REQ-001 (ESM entry)
# js_engine may exit 0 on uncaught errors in .mjs; require success marker + exit code.
set -euo pipefail
: "${JAC_JS_RUNNER:=bin/js_engine}"
dir=$(dirname "${BASH_SOURCE[0]}")
# shellcheck disable=SC1091
source "$dir/../../_harness/regression_case_sh.sh"
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
set +e
"$JAC_JS_RUNNER" "$dir/test_module_create_require_from_esm.mjs" >"$tmp" 2>&1
ec=$?
set -e
cat "$tmp"
if [[ $ec -eq 0 ]] && grep -q "ok createRequire from ESM" "$tmp"; then
  regression_finish_test_case "regression/04_node_modules/23_module_api/test_module_create_require_from_esm.sh"
fi
regression_record_fail "createRequire from ESM: expected exit 0 and marker in output (ec=$ec)"
regression_finish_test_case "regression/04_node_modules/23_module_api/test_module_create_require_from_esm.sh"
