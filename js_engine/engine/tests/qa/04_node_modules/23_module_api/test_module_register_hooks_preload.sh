#!/usr/bin/env bash
# testing_plans/05_modules_resolution_loading/NODE_MODULE_API_COMPREHENSIVE_TEST_PLAN.md — NMOD-HS-004
set -euo pipefail
: "${JAC_JS_RUNNER:=bin/js_engine}"
dir=$(dirname "${BASH_SOURCE[0]}")
# shellcheck disable=SC1091
source "$dir/../../_harness/regression_case_sh.sh"

if ! command -v node >/dev/null 2>&1; then
  echo "ok skipped NMOD-HS-004: node not in PATH for capability probe" >&2
  regression_finish_test_case "regression/04_node_modules/23_module_api/test_module_register_hooks_preload.sh"
fi

if ! node -e 'process.exit(typeof require("node:module").registerHooks === "function" ? 0 : 1)'; then
  echo "ok skipped NMOD-HS-004: registerHooks not available on this Node line"
  regression_finish_test_case "regression/04_node_modules/23_module_api/test_module_register_hooks_preload.sh"
fi

set +e
"$JAC_JS_RUNNER" --require "$dir/fixtures/preload_register.cjs" "$dir/fixtures/preload_app.cjs"
ec=$?
set -e
if [[ "$ec" -ne 0 ]]; then
  regression_record_fail "NMOD-HS-004: preload app exited with code $ec"
fi
regression_finish_test_case "regression/04_node_modules/23_module_api/test_module_register_hooks_preload.sh"
