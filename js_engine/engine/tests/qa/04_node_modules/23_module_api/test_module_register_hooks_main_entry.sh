#!/usr/bin/env bash
# NMOD-HS-105: registerHooks resolve hooks registered by a --require preload
# must also observe the MAIN entry's own resolution. The engine runs the main
# script directly (no require()), so el_run fires the chain explicitly before
# executing the entry — mirrors Node, where the main module loads after the
# preloads and therefore passes through hooks registered by them.
set -euo pipefail
: "${JAC_JS_RUNNER:=bin/js_engine}"
dir=$(dirname "${BASH_SOURCE[0]}")
# shellcheck disable=SC1091
source "$dir/../../_harness/regression_case_sh.sh"

set +e
"$JAC_JS_RUNNER" --require "$dir/fixtures/preload_register_record.cjs" "$dir/fixtures/main_entry_app.cjs"
ec=$?
set -e
if [[ "$ec" -ne 0 ]]; then
  regression_record_fail "NMOD-HS-105: main-entry app exited with code $ec"
fi
regression_finish_test_case "regression/04_node_modules/23_module_api/test_module_register_hooks_main_entry.sh"
