"use strict";
var registerHooks = require("node:module").registerHooks;
if (typeof registerHooks !== "function") {
  process.exit(2);
}
globalThis.__nmodPreloadResolveCount = 0;
registerHooks({
  resolve: function (specifier, context, nextResolve) {
    globalThis.__nmodPreloadResolveCount++;
    return nextResolve(specifier, context);
  },
  load: function (url, context, nextLoad) {
    return nextLoad(url, context);
  },
});
