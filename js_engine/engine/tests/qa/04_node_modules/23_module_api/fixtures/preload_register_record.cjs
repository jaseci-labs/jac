// NMOD-HS-105: preload registers a resolve hook that records every specifier
// it observes, so tests can assert which resolutions passed through the chain.
"use strict";
var registerHooks = require("node:module").registerHooks;
if (typeof registerHooks !== "function") {
  process.exit(2);
}
globalThis.__nmodResolvedSpecs = [];
registerHooks({
  resolve: function (specifier, context, nextResolve) {
    globalThis.__nmodResolvedSpecs.push(specifier);
    return nextResolve(specifier, context);
  },
});
