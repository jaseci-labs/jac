// testing_plans/05_modules_resolution_loading/NODE_MODULE_API_COMPREHENSIVE_TEST_PLAN.md — G5 (NMOD-CC-*)
"use strict";

var fs = require("node:fs");
var os = require("node:os");
var path = require("node:path");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/23_module_api/test_module_compile_cache.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }

var m = require("node:module");
assert(typeof m.builtinModules !== "undefined", "NMOD-AVAIL-005: node:module surface");

if (
  !m.constants ||
  !m.constants.compileCacheStatus ||
  typeof m.enableCompileCache !== "function"
) {
  console.log("skip NMOD-CC-*: compile cache API not on this Node line");
  __jacDone();
}

var CCS = m.constants.compileCacheStatus;
assert(typeof CCS.ENABLED === "number", "NMOD-CC-001: ENABLED");
assert(typeof CCS.ALREADY_ENABLED === "number", "NMOD-CC-001: ALREADY_ENABLED");
assert(typeof CCS.FAILED === "number", "NMOD-CC-001: FAILED");
assert(typeof CCS.DISABLED === "number", "NMOD-CC-001: DISABLED");

var dir = fs.mkdtempSync(path.join(os.tmpdir(), "nmod-cc-"));
var r1 = m.enableCompileCache({ directory: dir });
assert(r1 && typeof r1.status === "number", "NMOD-CC-002: enableCompileCache returns status");
if (r1.status === CCS.FAILED) {
  console.log("skip NMOD-CC remainder: enableCompileCache FAILED:", r1.message || "");
  try {
    fs.rmSync(dir, { recursive: true, force: true });
  } catch (e) {
    /* ignore */
  }
  __jacDone();
}
var r2 = m.enableCompileCache(dir);
assert(r2.status === CCS.ALREADY_ENABLED || r2.status === CCS.ENABLED, "NMOD-CC-003: string directory overload");

if (typeof m.getCompileCacheDir === "function") {
  var d = m.getCompileCacheDir();
  assert(typeof d === "string" && d.length > 0, "NMOD-CC-005: getCompileCacheDir returns path when enabled");
}

if (typeof m.flushCompileCache === "function") {
  try {
    m.flushCompileCache();
  } catch (e) {
    assert(false, "NMOD-CC-005: flushCompileCache must not throw: " + e);
  }
}

try {
  fs.rmSync(dir, { recursive: true, force: true });
} catch (e) {
  /* ignore */
}

console.log("ok module compile cache (G5 NMOD-CC-*)");
__jacDone();
