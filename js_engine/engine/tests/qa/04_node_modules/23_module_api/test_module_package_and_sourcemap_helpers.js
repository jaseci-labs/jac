// testing_plans/05_modules_resolution_loading/NODE_MODULE_API_COMPREHENSIVE_TEST_PLAN.md — G4 (NMOD-PKG-*, NMOD-SMAP-*)
"use strict";

var path = require("node:path");
var url = require("node:url");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/23_module_api/test_module_package_and_sourcemap_helpers.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }

var m = require("node:module");
assert(typeof m.builtinModules !== "undefined", "NMOD-AVAIL-004: node:module surface");

if (typeof m.findPackageJSON === "function") {
  var leafJs = path.join(__dirname, "fixtures", "leaf", "leaf.fixture.js");
  var pkgPath = m.findPackageJSON(".", leafJs);
  assert(typeof pkgPath === "string", "NMOD-PKG-002: findPackageJSON relative returns string path");
  assert(path.basename(pkgPath) === "package.json", "NMOD-PKG-002: resolves to package.json");
  assert(pkgPath.indexOf("leaf") !== -1, "NMOD-PKG-002: leaf fixture package.json");

  var barePkgPath = path.join(
    __dirname,
    "_fixtures_node_modules",
    "nmod-bare-test",
    "package.json"
  );
  var barePkgJson = m.findPackageJSON(barePkgPath, leafJs);
  assert(
    typeof barePkgJson === "string" && barePkgJson.indexOf("nmod-bare-test") !== -1,
    "NMOD-PKG-001: package.json path resolves via findPackageJSON"
  );

  var missing;
  try {
    missing = m.findPackageJSON("not-a-real-package-name-zzzz", leafJs);
  } catch (e) {
    assert(
      e && e.code === "ERR_MODULE_NOT_FOUND",
      "NMOD-PKG-004: missing bare package throws ERR_MODULE_NOT_FOUND"
    );
    missing = undefined;
  }
  assert(missing === undefined, "NMOD-PKG-004: missing bare package yields undefined");
} else {
  console.log("skip NMOD-PKG-*: findPackageJSON not available on this Node line");
}

if (typeof m.getSourceMapsSupport === "function") {
  var st = m.getSourceMapsSupport();
  assert(st && typeof st.enabled === "boolean", "NMOD-SMAP-001: getSourceMapsSupport.enabled boolean");
  assert(typeof st.nodeModules === "boolean", "NMOD-SMAP-001: nodeModules boolean");
  assert(typeof st.generatedCode === "boolean", "NMOD-SMAP-001: generatedCode boolean");
  if (typeof m.setSourceMapsSupport === "function") {
    m.setSourceMapsSupport(false, { nodeModules: false, generatedCode: false });
    var st2 = m.getSourceMapsSupport();
    assert(st2.enabled === false, "NMOD-SMAP-002: setSourceMapsSupport can disable");
  }
} else {
  console.log("skip NMOD-SMAP-001/002: getSourceMapsSupport not on this Node line");
}

assert(typeof m.SourceMap === "function", "NMOD-SMAP-004: SourceMap constructor exists");
var sm = new m.SourceMap({ version: 3, sources: [], names: [], mappings: "" });
assert(sm.payload && sm.payload.version === 3, "NMOD-SMAP-004: SourceMap.payload");
assert(typeof sm.findEntry === "function" && typeof sm.findOrigin === "function", "NMOD-SMAP-004: findEntry/findOrigin");
var fe = sm.findEntry(0, 0);
var fo = sm.findOrigin(1, 1);
assert(fe && typeof fe === "object" && Object.keys(fe).length === 0, "NMOD-SMAP-004: findEntry empty mapping");
assert(fo && typeof fo === "object" && Object.keys(fo).length === 0, "NMOD-SMAP-004: findOrigin empty mapping");

var fsm = m.findSourceMap(__filename);
assert(fsm === undefined || fsm instanceof m.SourceMap, "NMOD-SMAP-003: findSourceMap undefined or SourceMap");

console.log("ok module package + sourcemap helpers (G4 NMOD-PKG-* NMOD-SMAP-*)");
__jacDone();
