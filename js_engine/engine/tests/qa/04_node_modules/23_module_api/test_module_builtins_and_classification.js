// testing_plans/05_modules_resolution_loading/NODE_MODULE_API_COMPREHENSIVE_TEST_PLAN.md — G1 (NMOD-BLT-*, NMOD-ISB-*)
"use strict";

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/23_module_api/test_module_builtins_and_classification.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }

var m = require("node:module");
assert(
  typeof m.builtinModules !== "undefined" && Array.isArray(m.builtinModules),
  "NMOD-AVAIL-001: require('node:module') must expose non-empty builtinModules (engine may stub node:module)"
);
assert(m.builtinModules.length > 0, "NMOD-BLT-001: builtinModules is a non-empty array");

var names = m.builtinModules.slice();
assert(names.indexOf("fs") !== -1, "NMOD-BLT-002: builtinModules includes fs");
assert(names.indexOf("path") !== -1, "NMOD-BLT-002: builtinModules includes path");
assert(names.indexOf("module") !== -1, "NMOD-BLT-002: builtinModules includes module");
var hasNodePrefixed = names.some(function (n) {
  return typeof n === "string" && n.indexOf("node:") === 0;
});
if (hasNodePrefixed) {
  /* Node.js v23.5+ documents node:-prefixed entries in the list */
} else {
  console.log("skip NMOD-BLT-003: builtinModules has no node:-prefixed entries on this Node line");
}

var beforeLen = m.builtinModules.length;
var pushed = false;
try {
  m.builtinModules.push("__nmod_probe_should_not_persist__");
  pushed = true;
} catch (e) {
  /* Node may freeze builtinModules; mutation is not supported */
}
if (pushed) {
  assert(typeof m.isBuiltin === "function" && m.isBuiltin("fs") === true, "NMOD-BLT-004: after push, isBuiltin('fs') still works");
  m.builtinModules.pop();
  assert(m.builtinModules.length === beforeLen, "NMOD-BLT-004: restored builtinModules length after probe push/pop");
} else {
  assert(typeof m.isBuiltin === "function" && m.isBuiltin("fs") === true, "NMOD-BLT-004: isBuiltin('fs') when builtinModules is non-mutable");
}

assert(m.isBuiltin("node:fs") === true, "NMOD-ISB-001: isBuiltin('node:fs')");
assert(m.isBuiltin("fs") === true, "NMOD-ISB-002: isBuiltin('fs')");
assert(m.isBuiltin("not-a-real-builtin-xyz") === false, "NMOD-ISB-003: isBuiltin false for unknown");
assert(m.isBuiltin("") === false, "NMOD-ISB-004: isBuiltin('') is false");
assert(m.isBuiltin(" ") === false, "NMOD-ISB-004: isBuiltin(' ') is false");

console.log("ok module builtins and classification (G1 NMOD-BLT-* NMOD-ISB-*)");
__jacDone();
