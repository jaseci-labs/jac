// testing_plans/05_modules_resolution_loading/NODE_MODULE_API_COMPREHENSIVE_TEST_PLAN.md — G2 (NMOD-MOD-*, NMOD-REQ-*)
"use strict";

var path = require("node:path");
var url = require("node:url");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/23_module_api/test_module_create_require_and_module_surface.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }

var m = require("node:module");
var bare = require("module");
assert(
  typeof m.builtinModules !== "undefined",
  "NMOD-AVAIL-002: node:module must expose builtinModules"
);

assert(typeof m.Module === "function" || typeof m.Module === "object", "NMOD-MOD-001: Module export exists");
assert(m === bare, "NMOD-MOD-002: require('module') and require('node:module') are the same object");

var stableKeys = [
  "Module",
  "builtinModules",
  "createRequire",
  "isBuiltin",
  "register",
  "syncBuiltinESMExports",
  "SourceMap",
  "findSourceMap",
];
for (var i = 0; i < stableKeys.length; i++) {
  var k = stableKeys[i];
  assert(typeof m[k] !== "undefined", "NMOD-MOD-002: expected export present: " + k);
}

if (typeof m.globalPaths !== "undefined") {
  assert(Array.isArray(m.globalPaths), "NMOD-MOD-004: globalPaths is an array when present");
}

var cr = m.createRequire(__filename);
var rel = path.join(__dirname, "fixtures", "cjs_mark.fixture.js");
assert(cr(rel).nmodMark === 99, "NMOD-REQ-002: createRequire(__filename) resolves relative fixture");
assert(typeof cr.resolve === "function", "NMOD-REQ-004: createRequire returns require.resolve");
var resolved = cr.resolve("./fixtures/cjs_mark.fixture.js");
assert(path.isAbsolute(resolved), "NMOD-REQ-004: require.resolve returns absolute path");
assert(cr(resolved).nmodMark === 99, "NMOD-REQ-004: resolve path is loadable");

var crUrl = m.createRequire(url.pathToFileURL(__filename));
assert(crUrl("./fixtures/cjs_mark.fixture.js").nmodMark === 99, "NMOD-REQ-003: createRequire accepts file URL base");

var bad = false;
try {
  m.createRequire("./not-absolute");
  bad = true;
} catch (e) {
  assert(bad === false, "NMOD-REQ-003: invalid base throws");
  assert(e && e.code === "ERR_INVALID_ARG_VALUE", "NMOD-REQ-003: expected ERR_INVALID_ARG_VALUE");
}

var twice = m.createRequire(__filename);
assert(twice(rel) === cr(rel), "NMOD-REQ-005: CJS module identity stable across createRequire calls for same file");

console.log("ok module createRequire and Module surface (G2 NMOD-MOD-* NMOD-REQ-*)");
__jacDone();
