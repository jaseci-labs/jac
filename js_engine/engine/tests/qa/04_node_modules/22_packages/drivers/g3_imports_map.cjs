// NODE_PACKAGE_RESOLUTION_COMPREHENSIVE_TEST_PLAN.md — G3 (NPKG-IMP-*, NPKG-ERR-IMP-*)

function assert(cond, msg) {
    if (!cond) {
        console.error("FAIL: " + msg);
        process.exit(1);
    }
}
function assertEq(a, e, msg) {
    if (a !== e) {
        console.error(
            "FAIL: " + msg + " | expected: " + JSON.stringify(e) + " | actual: " + JSON.stringify(a),
        );
        process.exit(1);
    }
}

async function main() {
    var ns1 = await import("npkg-imp001");
    assertEq(ns1.out, 42, "NPKG-IMP-001: #imports alias resolves inside package");

    var ns4 = await import("npkg-imp004");
    assert(typeof ns4.sep === "string" && ns4.sep.length > 0, "NPKG-IMP-004: imports may map to builtin path");

    var ns5 = await import("npkg-imp005");
    assertEq(ns5.out, "a", "NPKG-IMP-005: pattern imports #lib/* substitution");

    try {
        await import("npkg-imp002");
        assert(false, "NPKG-IMP-002: expected invalid imports target to reject load");
    } catch (e) {
        assertEq(e.code, "ERR_INVALID_PACKAGE_TARGET", "NPKG-IMP-002: invalid imports target type rejected");
    }

    try {
        await import("npkg-imp-err001");
        assert(false, "NPKG-ERR-IMP-001: expected missing # alias to fail");
    } catch (e) {
        assertEq(e.code, "ERR_PACKAGE_IMPORT_NOT_DEFINED", "NPKG-ERR-IMP-001: undefined # import specifier");
    }

    try {
        await import("npkg-imp-err002");
        assert(false, "NPKG-ERR-IMP-003: expected invalid external imports target to fail");
    } catch (e) {
        assertEq(
            e.code,
            "ERR_INVALID_PACKAGE_TARGET",
            "NPKG-ERR-IMP-003: imports target outside package rejected",
        );
    }

    try {
        require.resolve("npkg-imp001#utils");
        assert(false, "NPKG-IMP-003: expected require.resolve of # specifier to fail");
    } catch (err) {
        assertEq(
            err.code,
            "MODULE_NOT_FOUND",
            "NPKG-IMP-003: #imports not visible outside owning package (consumer)",
        );
    }
}

main().then(
    function () {
        process.exit(0);
    },
    function (e) {
        console.error("FAIL: " + e);
        process.exit(1);
    },
);
