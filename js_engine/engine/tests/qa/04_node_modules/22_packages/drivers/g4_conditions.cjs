// NODE_PACKAGE_RESOLUTION_COMPREHENSIVE_TEST_PLAN.md — G4 (NPKG-COND-*, NPKG-BROWSER-*) without CLI flags

function assert(cond, msg) {
    if (!cond) {
        console.error("FAIL: " + msg);
        process.exit(1);
    }
}
function assertEq(a, e, msg) {
    if (a !== e) {
        console.error(
            "FAIL: " + msg + " | expected: " + JSON.stringify(e) + " | actual: " + JSON.stringify(a),
        );
        process.exit(1);
    }
}

var c2 = require("npkg-cond002");
assertEq(c2.which, "node", "NPKG-COND-002: node condition selects node branch on Node.js");

var c4 = require("npkg-cond004");
assertEq(c4.ok, true, "NPKG-COND-004: unknown custom condition key ignored; default used");

var b1 = require("npkg-browser001");
assertEq(b1.via, "main-ignore-browser-field", "NPKG-BROWSER-001: top-level browser field ignored by Node resolution");

var b2r = require("npkg-browser002");
assertEq(b2r.side, "require", "NPKG-BROWSER-002: require does not select browser condition branch");

import("npkg-cond003")
    .then(function (ns) {
        assertEq(ns.nest, "node-import", "NPKG-COND-003: nested import+node conditions resolve inner node branch");
        return import("npkg-browser002");
    })
    .then(function (nsb) {
        assertEq(nsb.side, "import", "NPKG-BROWSER-002: dynamic import uses import branch, not browser");
        return import("npkg-dual001");
    })
    .then(function (d1i) {
        assertEq(d1i.side, "import", "NPKG-COND-005: import condition differs from require for same package root");
    })
    .then(
        function () {
            process.exit(0);
        },
        function (e) {
            console.error("FAIL: " + e);
            process.exit(1);
        },
    );
