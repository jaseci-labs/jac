function assert(cond, msg) {
    if (!cond) {
        console.error("FAIL: " + msg);
        process.exit(1);
    }
}
function assertEq(a, e, msg) {
    if (a !== e) {
        console.error(
            "FAIL: " + msg + " | expected: " + JSON.stringify(e) + " | actual: " + JSON.stringify(a),
        );
        process.exit(1);
    }
}
function assertThrowsCode(fn, wantCode, msg) {
    try {
        fn();
        assert(false, msg + " (expected throw)");
    } catch (err) {
        assert(
            err && err.code === wantCode,
            msg + " | expected code " + wantCode + " | got " + (err && err.code) + " | " + (err && err.message),
        );
    }
}

var m1 = require("npkg-main001");
assertEq(m1.id, "NPKG-MAIN-001", "NPKG-MAIN-001: main-only entry resolves via main");
assertEq(m1.via, "main", "NPKG-MAIN-001: value from main target");

var m2 = require("npkg-main002");
assertEq(m2.who, "new", "NPKG-MAIN-002: exports takes precedence over main");

var m3 = require("npkg-main003");
assert(m3.sugar === true, "NPKG-MAIN-003: string exports form resolves to package root");

assertThrowsCode(
    function () {
        require("npkg-main004/legacy.js");
    },
    "ERR_PACKAGE_PATH_NOT_EXPORTED",
    "NPKG-MAIN-004: undeclared subpath rejected when exports encapsulates",
);

var pj = require("npkg-main005/package.json");
assertEq(pj.name, "npkg-main005", "NPKG-MAIN-005: package.json readable without exports field");

assertThrowsCode(
    function () {
        require("npkg-main005b/package.json");
    },
    "ERR_PACKAGE_PATH_NOT_EXPORTED",
    "NPKG-MAIN-005: package.json not loadable unless explicitly exported",
);

var t2 = require("npkg-type002");
assertEq(t2.tag, "cjs", "NPKG-TYPE-002: explicit type commonjs for .js");

var t4 = require("npkg-type004");
assertEq(t4.tag, "cjs-in-module-pkg", "NPKG-TYPE-004: .cjs remains CommonJS inside type module package");

var t6 = require("npkg-type006");
assertEq(t6.tag, "invalid-type-fallback", "NPKG-TYPE-006: invalid type value falls back like CommonJS for .js");

(function npkgType003() {
    try {
        var t3 = require("npkg-type003");
        assertEq(t3.tag, "mjs-esm", "NPKG-TYPE-003: .mjs main loadable via require (Node 24+)");
    } catch (err) {
        assertThrowsCode(
            function () {
                throw err;
            },
            "ERR_REQUIRE_ESM",
            "NPKG-TYPE-003: .mjs main cannot be require()d from CJS (ERR_REQUIRE_ESM)",
        );
    }
})();

var d1 = require("npkg-dual001");
assertEq(d1.side, "require", "NPKG-CJS-ESM-001: require selects require branch");

var d2 = require("npkg-dual002");
assertEq(d2.pick, "require-first", "NPKG-CJS-ESM-002: ordered require/import/default — require wins for CJS");

var d3 = require("npkg-dual003");
assertEq(d3.via, "default-branch", "NPKG-CJS-ESM-003: unknown condition ignored; default branch used");

import("npkg-type001")
    .then(function (ns) {
        assertEq(ns.tag, "esm", "NPKG-TYPE-001: type module makes .js ESM (dynamic import)");
        return import("npkg-type003");
    })
    .then(function (ns3) {
        assertEq(ns3.tag, "mjs-esm", "NPKG-TYPE-003: .mjs stays ESM in CommonJS-type package");
        return import("npkg-dual001");
    })
    .then(function (d1i) {
        assertEq(d1i.side, "import", "NPKG-CJS-ESM-001: import selects import branch");
        return import("npkg-dual002");
    })
    .then(function (d2i) {
        assertEq(d2i.pick, "import-second", "NPKG-CJS-ESM-002: import branch for ESM loader");
    })
    .then(
        function () {
            process.exit(0);
        },
        function (e) {
            console.error("FAIL: async package tests: " + e);
            process.exit(1);
        },
    );
