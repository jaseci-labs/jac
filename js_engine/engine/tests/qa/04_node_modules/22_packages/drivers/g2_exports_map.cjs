// NODE_PACKAGE_RESOLUTION_COMPREHENSIVE_TEST_PLAN.md — G2 (NPKG-EXP-*, NPKG-ERR-EXP-*)

function assert(cond, msg) {
    if (!cond) {
        console.error("FAIL: " + msg);
        process.exit(1);
    }
}
function assertEq(a, e, msg) {
    if (a !== e) {
        console.error(
            "FAIL: " + msg + " | expected: " + JSON.stringify(e) + " | actual: " + JSON.stringify(a),
        );
        process.exit(1);
    }
}
function assertThrowsCode(fn, wantCode, msg) {
    try {
        fn();
        assert(false, msg + " (expected throw)");
    } catch (err) {
        assert(
            err && err.code === wantCode,
            msg + " | expected " + wantCode + " | got " + (err && err.code) + " | " + (err && err.message),
        );
    }
}

var e1 = require("npkg-exp001");
assertEq(e1.id, "NPKG-EXP-001", "NPKG-EXP-001: root export resolves");

var e2root = require("npkg-exp002");
assert(e2root.root === true, "NPKG-EXP-002: root subpath");
var e2f = require("npkg-exp002/feature");
assert(e2f.sub === true, "NPKG-EXP-002: explicit subpath export");

assertThrowsCode(
    function () {
        require("npkg-exp003/secret.js");
    },
    "ERR_PACKAGE_PATH_NOT_EXPORTED",
    "NPKG-EXP-003: undeclared file not exported",
);

var pj4 = require("npkg-exp004/package.json");
assertEq(pj4.name, "npkg-exp004", "NPKG-EXP-004: exporting package.json allows require");

var e5a = require("npkg-exp005/noext");
var e5b = require("npkg-exp005/ext.js");
assertEq(e5a.same, true, "NPKG-EXP-005: extensionless export key");
assertEq(e5b.same, true, "NPKG-EXP-005: extensioned export key");

var pat = require("npkg-exp101/features/x.js");
assertEq(pat.pattern, "x", "NPKG-EXP-101: pattern export resolves by substitution");

assertThrowsCode(
    function () {
        require("npkg-exp102/blocked/x.js");
    },
    "ERR_PACKAGE_PATH_NOT_EXPORTED",
    "NPKG-EXP-102: null pattern blocks matched subpath",
);
var e102extra = require("npkg-exp102/blocked/extra.js");
assertEq(e102extra.extra, true, "NPKG-EXP-102: exact export overrides null pattern for that path");

assertThrowsCode(
    function () {
        require("npkg-exp103/escape/x.js");
    },
    "ERR_INVALID_PACKAGE_TARGET",
    "NPKG-EXP-103: export target escaping package directory is rejected",
);

var e104 = require("npkg-exp104/foo.js");
assertEq(e104.which, "exact", "NPKG-EXP-104: exact export key beats overlapping pattern");

assertThrowsCode(
    function () {
        require("npkg-err-exp001");
    },
    "ERR_INVALID_PACKAGE_TARGET",
    "NPKG-ERR-EXP-001: export target must start with ./",
);

assertThrowsCode(
    function () {
        require("npkg-err-exp002");
    },
    "ERR_INVALID_PACKAGE_TARGET",
    "NPKG-ERR-EXP-002: ../ in export target rejected",
);

assertThrowsCode(
    function () {
        require("npkg-err-exp003");
    },
    "ERR_PACKAGE_PATH_NOT_EXPORTED",
    "NPKG-ERR-EXP-003: invalid nested exports mapping yields package resolution failure",
);

process.exit(0);
