function assert(cond, msg) {
    if (!cond) {
        console.error("FAIL: " + msg);
        process.exit(1);
    }
}
function assertEq(a, e, msg) {
    if (a !== e) {
        console.error(
            "FAIL: " + msg + " | expected: " + JSON.stringify(e) + " | actual: " + JSON.stringify(a),
        );
        process.exit(1);
    }
}
function assertThrowsCode(fn, wantCode, msg) {
    try {
        fn();
        assert(false, msg + " (expected throw)");
    } catch (err) {
        assert(
            err && err.code === wantCode,
            msg + " | expected " + wantCode + " | got " + (err && err.code) + " | " + (err && err.message),
        );
    }
}

var s1 = require("npkg-self001");
assertEq(s1.fromSelf, "sub-self", "NPKG-SELF-001: self-reference by package name resolves exported subpath");

assertThrowsCode(
    function () {
        require("npkg-self002/hidden.js");
    },
    "ERR_PACKAGE_PATH_NOT_EXPORTED",
    "NPKG-SELF-002: self-reference cannot load paths not listed in exports",
);

var sc = require("@npkg/self-scope/sub.cjs");
assertEq(sc.viaSelf, true, "NPKG-SELF-003: scoped package self-reference works");

var inner = require("npkg-type005/inner");
assertEq(inner.kind, "nested-cjs-boundary", "NPKG-BOUND-001: nested package.json overrides parent type for that subtree");

var b2 = require("npkg-bound002");
assertEq(b2.inner, 99, "NPKG-BOUND-002: dependency resolved via package-local node_modules");

process.exit(0);
