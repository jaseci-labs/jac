#!/usr/bin/env bash
# testing_plans/05_modules_resolution_loading/NODE_PACKAGE_RESOLUTION_COMPREHENSIVE_TEST_PLAN.md
# Symlink node_modules → _fixtures_node_modules for Node bare-specifier resolution (require + import()).
set -euo pipefail

here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
cd "$here"
# shellcheck disable=SC1091
source "$here/../../_harness/regression_case_sh.sh"

if [[ -e "$here/node_modules" && ! -L "$here/node_modules" ]]; then
    regression_record_fail "NPKG-000: $here/node_modules exists and is not a symlink; refusing to shadow it"
    regression_finish_test_case "regression/04_node_modules/22_packages/test_pkg_resolution.sh"
fi

ln -sfn "$here/_fixtures_node_modules" "$here/node_modules"
cleanup() {
    if [[ -L "$here/node_modules" ]]; then
        local t
        t=$(readlink -f "$here/node_modules" 2>/dev/null || readlink "$here/node_modules" 2>/dev/null || true)
        if [[ "$t" == "$here/_fixtures_node_modules" ]] || [[ "$(readlink "$here/node_modules")" == "_fixtures_node_modules" ]]; then
            rm -f "$here/node_modules"
        fi
    fi
}
trap cleanup EXIT

: "${JAC_JS_RUNNER:?JAC_JS_RUNNER must be set by run_reg.sh}"
PKG_RUNNER=$JAC_JS_RUNNER

run_driver() {
    local name=$1
    if ! (cd "${JAC_ENGINE_ROOT}" && "$PKG_RUNNER" "$here/drivers/$name.cjs"); then
        regression_record_fail "driver $name.cjs exited non-zero"
    fi
}

run_driver g1_entry_type
run_driver g2_exports_map
run_driver g3_imports_map
run_driver g4_conditions
run_driver g5_self_boundaries

NODE_BIN=$(command -v node || true)
if [[ -z "$NODE_BIN" ]]; then
    regression_record_fail "NPKG-CLI-000: node binary required on PATH for CLI condition tests"
else
    out=$("$NODE_BIN" -e "console.log(require('npkg-cond001').env)" 2>&1) || true
    if [[ "$out" != "production" ]]; then
        regression_record_fail "NPKG-CLI-003 / NPKG-COND-001: without --conditions expected production env, got '$out'"
    fi

    out=$("$NODE_BIN" --conditions=development -e "console.log(require('npkg-cond001').env)" 2>&1) || true
    if [[ "$out" != "development" ]]; then
        regression_record_fail "NPKG-CLI-001: --conditions=development expected development env, got '$out'"
    fi

    out=$("$NODE_BIN" --conditions=alpha --conditions=beta -e "console.log(require('npkg-cli002').which)" 2>&1) || true
    if [[ "$out" != "alpha" ]]; then
        regression_record_fail "NPKG-CLI-002: expected alpha (key order), got '$out'"
    fi

    out=$("$NODE_BIN" --conditions=browser -e "console.log(require('npkg-browser004').pick)" 2>&1) || true
    if [[ "$out" != "browser" ]]; then
        regression_record_fail "NPKG-BROWSER-004: --conditions=browser should select browser branch, got '$out'"
    fi

    set +e
    "$NODE_BIN" --conditions= -e "console.log(1)" >/dev/null 2>&1
    ec=$?
    set -e
    if [[ "$ec" -eq 0 ]]; then
        regression_record_fail "NPKG-CLI-004: expected non-zero exit for empty --conditions="
    fi
fi

regression_finish_test_case "regression/04_node_modules/22_packages/test_pkg_resolution.sh"
