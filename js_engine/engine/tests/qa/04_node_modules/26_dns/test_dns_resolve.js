"use strict";

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/26_dns/test_dns_resolve.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

var dns = require("dns");

var done = 0;
function step() {
    done = done + 1;
    if (done >= 2) {
        __jacDone();
    }
}

dns.resolve4("localhost", function (err, addresses) {
    assert(!err, "resolve4 localhost");
    assert(addresses && addresses.length > 0, "resolve4 has results");
    assertEq(addresses[0], "127.0.0.1", "resolve4 address");
    step();
});

dns.reverse("127.0.0.1", function (err2, hostnames) {
    assert(!err2, "reverse 127.0.0.1");
    assert(Array.isArray(hostnames), "reverse hostnames array");
    step();
});

setTimeout(function () {
    assert(false, "resolve timeout");
    __jacDone();
}, 8000);
