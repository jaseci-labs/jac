"use strict";

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/26_dns/test_dns_strict.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

var dns = require("dns");
var Resolver = dns.promises.Resolver;

var steps = 0;
function step() {
    steps = steps + 1;
    if (steps >= 3) {
        __jacDone();
    }
}

dns.lookup("localhost", function (err, addr, fam) {
    assert(!err, "lookup localhost");
    assertEq(addr, "127.0.0.1", "lookup address");
    assertEq(fam, 4, "lookup family");
    step();
});

dns.setServers(["8.8.8.8"]);
dns.resolve4("example.com", function (err2, addrs) {
    assert(!err2, "resolve4 example.com");
    assert(addrs && addrs.length > 0, "resolve4 results");
    step();
});

var r = new Resolver();
r.setServers(["1.1.1.1"]);
assert(r.getServers()[0] === "1.1.1.1", "resolver servers");
r.resolve4("example.com").then(function (a) {
    assert(a && a.length > 0, "resolver resolve4");
    step();
}).catch(function (e) {
    console.error(e && e.message);
    __reg.bump();
    step();
});

setTimeout(function () {
    assert(false, "strict dns timeout");
    __jacDone();
}, 12000);
