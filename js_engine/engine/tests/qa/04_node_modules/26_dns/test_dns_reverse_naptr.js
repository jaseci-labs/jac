// DNS reverse error semantics + NAPTR field shape
var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase(
  "regression/04_node_modules/26_dns/test_dns_reverse_naptr.js"
);
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

var dns = require("dns");

function assert(cond, msg) { __reg.assert(cond, msg); }

var pending = 2;

function doneOne() {
  pending = pending - 1;
  if (pending === 0) { __jacDone(); }
}

dns.reverse("203.0.113.99", function (err, hostnames) {
  assert(err !== null, "reverse: expected error for non-PTR IP");
  if (err) {
    assert(err.code === "ENOTFOUND" || err.code === "ENODATA", "reverse: error code");
  }
  assert(!hostnames || hostnames.length === 0, "reverse: no hostnames on error");
  doneOne();
});

dns.promises.reverse("203.0.113.98").then(
  function () {
    assert(false, "promises.reverse: expected rejection");
    doneOne();
  },
  function (err) {
    assert(err && (err.code === "ENOTFOUND" || err.code === "ENODATA"), "promises.reverse: code");
    doneOne();
  }
);

setTimeout(function () {
  if (pending > 0) {
    assert(false, "reverse tests timed out");
    pending = 0;
    __jacDone();
  }
}, 8000);
