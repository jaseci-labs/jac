"use strict";

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/26_dns/test_dns_lookup.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

var dns = require("dns");

assertEq(typeof dns.lookup, "function", "lookup export");
assertEq(typeof dns.getDefaultResultOrder, "function", "getDefaultResultOrder");
assertEq(typeof dns.setDefaultResultOrder, "function", "setDefaultResultOrder");
assertEq(dns.getDefaultResultOrder(), "verbatim", "default order");

var done = 0;
function step() {
    done = done + 1;
    if (done >= 2) {
        __jacDone();
    }
}

dns.lookup("localhost", function (err, address, family) {
    assert(!err, "lookup localhost no err");
    assertEq(address, "127.0.0.1", "lookup localhost address");
    assertEq(family, 4, "lookup localhost family");
    step();
});

dns.lookup("127.0.0.1", { family: 4 }, function (err2, address2, family2) {
    assert(!err2, "lookup ipv4 literal");
    assertEq(address2, "127.0.0.1", "ipv4 literal address");
    assertEq(family2, 4, "ipv4 literal family");
    step();
});

setTimeout(function () {
    assert(false, "lookup timeout");
    __jacDone();
}, 5000);
