"use strict";

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/26_dns/test_dns_promises.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

var dnsPromises = require("dns/promises");
var nodeDnsPromises = require("node:dns/promises");

assertEq(typeof dnsPromises.lookup, "function", "dns/promises lookup");
assertEq(typeof nodeDnsPromises.lookup, "function", "node:dns/promises lookup");
assertEq(typeof dnsPromises.getDefaultResultOrder, "function", "promises getDefaultResultOrder");

var done = false;
dnsPromises.lookup("localhost").then(function (r) {
    assertEq(r.address, "127.0.0.1", "promises localhost");
    assertEq(r.family, 4, "promises family");
    done = true;
    __jacDone();
});

setTimeout(function () {
    if (!done) {
        assert(false, "promises lookup timeout");
        __jacDone();
    }
}, 5000);
