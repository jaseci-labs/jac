"use strict";

// DNS-NS-001: IPv6 nameserver strings (bracketed and bare) do not break setServers
var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase(
  "regression/04_node_modules/26_dns/test_dns_nameserver_ipv6.js"
);
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

var dns = require("dns");

dns.setServers(["[2001:4860:4860::8888]"]);
assert(dns.getServers().length >= 1, "DNS-NS-001: bracketed IPv6 server stored");

dns.setServers(["2001:4860:4860::8888"]);
assert(dns.getServers()[0].indexOf("2001") !== -1, "DNS-NS-002: bare IPv6 server stored");

dns.lookup("localhost", { family: 6 }, function (err, addr, fam) {
    assert(!err, "DNS-NS-003: localhost family 6");
    assert(addr === "::1" || addr === "127.0.0.1", "DNS-NS-003: localhost v6 or fallback");
    assertEq(fam, 6, "DNS-NS-003: family");
    __jacDone();
});

setTimeout(function () {
    console.error("FAIL: test_dns_nameserver_ipv6 timeout");
    __reg.bump();
    __jacDone();
}, 5000);
