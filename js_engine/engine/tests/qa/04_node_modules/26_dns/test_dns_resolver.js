"use strict";

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/26_dns/test_dns_resolver.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }

var dns = require("dns");
var Resolver = dns.promises.Resolver;

assert(typeof Resolver === "function", "Resolver export");
var r = new Resolver();
r.setServers(["1.1.1.1"]);
assert(r.getServers()[0] === "1.1.1.1", "Resolver setServers");
assert(typeof r.cancel === "function", "Resolver cancel");

r.resolve4("example.com").then(function (addrs) {
    assert(addrs && addrs.length > 0, "Resolver resolve4");
    __jacDone();
}).catch(function (e) {
    console.error("Resolver resolve4: " + (e && e.message));
    __reg.bump();
    __jacDone();
});

setTimeout(function () {
    __reg.bump();
    __jacDone();
}, 5000);
