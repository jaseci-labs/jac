"use strict";

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/26_dns/test_dns_order_servers.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

var dns = require("dns");

dns.setDefaultResultOrder("ipv4first");
assertEq(dns.getDefaultResultOrder(), "ipv4first", "setDefaultResultOrder");

var servers = dns.getServers();
assert(Array.isArray(servers), "getServers array");

dns.setServers(["8.8.8.8", "8.8.4.4"]);
assertEq(dns.getServers().length, 2, "setServers length");

dns.setDefaultResultOrder("verbatim");

__jacDone();
