// Vite V-13: dns.promises.lookup
var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase(
    "regression/04_node_modules/26_dns/test_dns_promises_lookup.js"
);
var __jacOrigExit = process.exit.bind(process);
function __jacDone() {
    __reg.finalize(__jacOrigExit);
}

function assert(cond, msg) {
    __reg.assert(cond, msg);
}
function assertEq(actual, expected, msg) {
    __reg.assertEq(actual, expected, msg);
}

var dns = require("dns");
var nodeDns = require("node:dns");
assert(typeof dns === "object", "DNS-001: require('dns')");
assert(typeof dns.promises === "object", "DNS-001: dns.promises");
assert(typeof dns.promises.lookup === "function", "DNS-001: lookup function");
assert(typeof nodeDns.promises.lookup === "function", "DNS-001: node:dns lookup");

var done = false;
dns.promises.lookup("localhost").then(function (result) {
    assertEq(result.address, "127.0.0.1", "DNS-002: localhost address");
    assertEq(result.family, 4, "DNS-002: localhost family");
    done = true;
    __jacDone();
});

setTimeout(function () {
    if (!done) {
        assert(false, "DNS-002: lookup timed out");
        __jacDone();
    }
}, 2000);
