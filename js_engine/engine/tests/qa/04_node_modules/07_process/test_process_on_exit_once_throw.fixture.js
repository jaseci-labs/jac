// PROC-EXIT-005: process.once fires once; throwing listener stops later handlers (Node parity)
var fs = require("fs");
var sentinel = process.argv[2];
process.once("exit", function () {
    fs.appendFileSync(sentinel, "once\n");
});
process.on("exit", function () {
    throw new Error("listener throw");
});
process.on("exit", function () {
    fs.appendFileSync(sentinel, "after_throw\n");
});
process.exit(0);
