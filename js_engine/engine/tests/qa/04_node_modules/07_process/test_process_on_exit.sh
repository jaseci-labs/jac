#!/usr/bin/env bash
# PROC-EXIT-* — process.on('exit') fires on explicit process.exit() and natural drain
set -uo pipefail
: "${JAC_JS_RUNNER:=bin/js_engine}"
: "${JAC_ENGINE_ROOT:=$(cd "$(dirname "${BASH_SOURCE[0]}")/../../../.." && pwd)}"
dir=$(dirname "${BASH_SOURCE[0]}")
# shellcheck disable=SC1091
source "$dir/../../_harness/regression_case_sh.sh"

run_fixture() {
    local fixture="$1"
    local expected_rc="$2"
    local expected_content="$3"
    local sentinel
    sentinel=$(mktemp /tmp/jac_proc_exit_XXXXXX)
    local rc=0
    JAC_ENGINE_ROOT="$JAC_ENGINE_ROOT" "$JAC_JS_RUNNER" "$fixture" "$sentinel" >/dev/null 2>&1 || rc=$?
    if [[ "$rc" -ne "$expected_rc" ]]; then
        regression_record_fail "PROC-EXIT: $fixture expected rc=$expected_rc got rc=$rc"
    fi
    if [[ ! -f "$sentinel" ]]; then
        regression_record_fail "PROC-EXIT: $fixture sentinel missing ($sentinel)"
    else
        local actual
        actual=$(cat "$sentinel"; printf x)
        actual=${actual%x}
        if [[ "$actual" != "$expected_content" ]]; then
            regression_record_fail "PROC-EXIT: $fixture sentinel mismatch for $fixture"
        fi
    fi
    rm -f "$sentinel"
}

run_fixture "$dir/test_process_on_exit_explicit.fixture.js" 7 $'A:7\nB:7\n'
run_fixture "$dir/test_process_on_exit_settimeout.fixture.js" 3 "timer:3"
# Node: process.exit() inside an exit handler is the last handler to run; exit code updates.
run_fixture "$dir/test_process_on_exit_reentrant.fixture.js" 0 $'X\n'
run_fixture "$dir/test_process_on_exit_natural.fixture.js" 0 "natural:0"
# Node: a throwing exit handler prevents subsequent handlers from running.
run_fixture "$dir/test_process_on_exit_once_throw.fixture.js" 0 $'once\n'

regression_finish_test_case "regression/04_node_modules/07_process/test_process_on_exit.sh"
