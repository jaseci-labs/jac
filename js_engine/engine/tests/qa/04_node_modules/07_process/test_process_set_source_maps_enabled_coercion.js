// Vite V-03 — NPROC-SM-004/006/007: Node requires boolean (no coercion); js_engine may coerce.
var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase(
    "regression/04_node_modules/07_process/test_process_set_source_maps_enabled_coercion.js"
);
var __jacOrigExit = process.exit.bind(process);
function __jacDone() {
    __reg.finalize(__jacOrigExit);
}

function assertEq(actual, expected, msg) {
    __reg.assertEq(actual, expected, msg);
}

function assertInvalidEnabledArg(fn, msg) {
    try {
        fn();
        __reg.fail(msg + " (expected throw)");
    } catch (e) {
        __reg.assert(
            e && (e.code === "ERR_INVALID_ARG_TYPE" || e instanceof TypeError),
            msg + " | got " + (e && e.code) + " " + (e && e.message)
        );
    }
}

assertInvalidEnabledArg(function () {
    process.setSourceMapsEnabled(1);
}, "NPROC-SM-004: truthy number rejected");
assertInvalidEnabledArg(function () {
    process.setSourceMapsEnabled(0);
}, "NPROC-SM-006: falsy number rejected");
assertInvalidEnabledArg(function () {
    process.setSourceMapsEnabled("");
}, "NPROC-SM-006: empty string rejected");
assertInvalidEnabledArg(function () {
    process.setSourceMapsEnabled(null);
}, "NPROC-SM-006: null rejected");
assertInvalidEnabledArg(function () {
    process.setSourceMapsEnabled();
}, "NPROC-SM-007: no arguments rejected");

__jacDone();
