// testing_plans/06_process_os_stdio/NODE_PROCESS_COMPREHENSIVE_TEST_PLAN.md — ECG-5 (warnings + resource APIs)
var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/07_process/test_process_events_resources.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }

assert(typeof process.emitWarning === "function", "NPROC-G-001: process.emitWarning is function");
assert(typeof process.on === "function", "NPROC-G-001: process.on exists for warning events");

var saw = false;
function onWarn(w) {
    saw = w && w.message === "nproc-test-warning";
}
process.on("warning", onWarn);
process.emitWarning("nproc-test-warning", "NPROCTest");

assert(typeof process.memoryUsage === "function", "NPROC-R-001: process.memoryUsage is function");
var mu = process.memoryUsage();
assert(typeof mu === "object" && mu !== null, "NPROC-R-001: memoryUsage returns object");
assert(typeof mu.rss === "number" && mu.rss > 0, "NPROC-R-001: rss positive number");
assert(typeof mu.heapTotal === "number", "NPROC-R-001: heapTotal number");
assert(typeof mu.heapUsed === "number", "NPROC-R-001: heapUsed number");
assert(typeof mu.external === "number", "NPROC-R-001: external number");

assert(typeof process.cpuUsage === "function", "NPROC-R-002: process.cpuUsage is function");
var c1 = process.cpuUsage();
assert(typeof c1.user === "number" && typeof c1.system === "number", "NPROC-R-002: cpuUsage shape");
var c2 = process.cpuUsage(c1);
assert(typeof c2.user === "number" && typeof c2.system === "number", "NPROC-R-002: cpuUsage(previous) shape");

if (typeof process.resourceUsage === "function") {
    var ru = process.resourceUsage();
    assert(typeof ru === "object" && ru !== null, "NPROC-R-003: resourceUsage returns object");
}

assert(typeof process.umask === "function", "NPROC-R-004: process.umask is function");
var prev = process.umask();
assert(typeof prev === "number", "NPROC-R-004: umask() read returns number");
process.umask(prev);

setImmediate(function () {
    process.removeListener("warning", onWarn);
    assert(saw, "NPROC-G-002: warning listener observes emitWarning (async delivery)");
    console.log("ok process events/resources (NPROC-G-*, NPROC-R-*)");
});
__jacDone();
