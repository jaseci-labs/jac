// testing_plans/06_process_os_stdio/NODE_PROCESS_COMPREHENSIVE_TEST_PLAN.md — ECG-3 (nextTick + hrtime + uptime)
var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/07_process/test_process_timing.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }

var order = [];
process.nextTick(function () {
    order.push("a");
    process.nextTick(function () {
        order.push("c");
    });
});
process.nextTick(function () {
    order.push("b");
});

var tickBeforeTimeout = false;
process.nextTick(function () {
    tickBeforeTimeout = true;
});
setTimeout(function () {
    assert(tickBeforeTimeout, "NPROC-T-002: nextTick runs before setTimeout(0) callback");
}, 0);

assert(typeof process.hrtime.bigint === "function", "NPROC-T-007: process.hrtime.bigint is function");
var b1 = process.hrtime.bigint();
var b2 = process.hrtime.bigint();
assert(typeof b1 === "bigint", "NPROC-T-007: hrtime.bigint returns bigint");
assert(b2 >= b1, "NPROC-T-007: successive bigint hrtime samples are monotonic");

assert(typeof process.uptime === "function", "NPROC-T-008: process.uptime is function");
var u1 = process.uptime();
var u2 = process.uptime();
assert(u2 >= u1, "NPROC-T-008: uptime is non-decreasing");

var hrtimeThrew = false;
try {
    process.hrtime("not-a-valid-previous-tuple");
} catch (e) {
    hrtimeThrew = e && e.code === "ERR_INVALID_ARG_TYPE";
}
assert(hrtimeThrew, "NPROC-T-006: invalid hrtime(previous) throws ERR_INVALID_ARG_TYPE");

setImmediate(function () {
    assert(order.join("") === "abc", "NPROC-T-003: nested nextTick FIFO order");
    __jacDone();
});
