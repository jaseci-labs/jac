// Vite V-03 — NPROC-SM-005: Error.stack unaffected by setSourceMapsEnabled
var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase(
    "regression/04_node_modules/07_process/test_process_set_source_maps_enabled_stack.js"
);
var __jacOrigExit = process.exit.bind(process);
function __jacDone() {
    __reg.finalize(__jacOrigExit);
}

function assert(cond, msg) {
    __reg.assert(cond, msg);
}

process.setSourceMapsEnabled(true);
var errEnabled = new Error("with maps flag on");
assert(
    typeof errEnabled.stack === "string" && errEnabled.stack.length > 0,
    "NPROC-SM-005: stack after enable"
);

process.setSourceMapsEnabled(false);
var errDisabled = new Error("with maps flag off");
assert(
    typeof errDisabled.stack === "string" && errDisabled.stack.length > 0,
    "NPROC-SM-005: stack after disable"
);

__jacDone();
