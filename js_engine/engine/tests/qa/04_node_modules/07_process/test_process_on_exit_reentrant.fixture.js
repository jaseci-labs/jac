// PROC-EXIT-003: process.exit() inside an exit handler is the last handler (Node parity)
var fs = require("fs");
var sentinel = process.argv[2];
process.on("exit", function () {
    fs.appendFileSync(sentinel, "X\n");
    process.exit(0);
});
process.on("exit", function () {
    fs.appendFileSync(sentinel, "Y\n");
});
process.exit(1);
