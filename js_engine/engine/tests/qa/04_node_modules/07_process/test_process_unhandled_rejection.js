// Vite V-05: process.on('unhandledRejection')
var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase(
    "regression/04_node_modules/07_process/test_process_unhandled_rejection.js"
);
var __jacOrigExit = process.exit.bind(process);
function __jacDone() {
    __reg.finalize(__jacOrigExit);
}

function assert(cond, msg) {
    __reg.assert(cond, msg);
}
function assertEq(actual, expected, msg) {
    __reg.assertEq(actual, expected, msg);
}

var fired = false;
var gotReason = null;
process.on("unhandledRejection", function (reason, promise) {
    fired = true;
    gotReason = reason;
    assert(typeof promise === "object", "V-05: promise arg");
});

Promise.reject("vite-ur-test");

setImmediate(function () {
    assert(fired === true, "V-05: unhandledRejection listener fired");
    assertEq(gotReason, "vite-ur-test", "V-05: reason value");
    __jacDone();
});
