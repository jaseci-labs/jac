// testing_plans/06_process_os_stdio/NODE_PROCESS_COMPREHENSIVE_TEST_PLAN.md — baseline (ECG-1/2/3 smoke)
// PROC-* legacy IDs dual-tagged with NPROC-* for traceability
var os = require("os");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/07_process/test_process.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

// PROC-001 (NPROC-I-001): version
assertEq(typeof process.version, "string",  "PROC-001 (NPROC-I-001): process.version is string");
assert(process.version[0] === "v",           "PROC-001 (NPROC-I-001): version starts with 'v'");

// PROC-002 (NPROC-I-002, NPROC-I-003): platform / arch
assertEq(typeof process.platform, "string",  "PROC-002 (NPROC-I-002): platform is string");
assert(process.platform.length > 0,          "PROC-002 (NPROC-I-002): platform non-empty");
assertEq(process.platform, os.platform(),     "PROC-002 (NPROC-I-002): process.platform matches os.platform()");
assertEq(typeof process.arch, "string",      "PROC-002 (NPROC-I-003): arch is string");
assert(process.arch.length > 0,             "PROC-002 (NPROC-I-003): arch non-empty");
assertEq(process.arch, os.arch(),            "PROC-002 (NPROC-I-003): process.arch matches os.arch()");

// PROC-003 (NPROC-I-004): pid
assertEq(typeof process.pid, "number",       "PROC-003 (NPROC-I-004): pid is number");
assert(process.pid > 0,                      "PROC-003 (NPROC-I-004): pid > 0");
assert(Number.isInteger(process.pid),        "PROC-003 (NPROC-I-004): pid is integer");

// PROC-004 (NPROC-A-001): argv
assert(Array.isArray(process.argv),          "PROC-004 (NPROC-A-001): argv is array");
assert(process.argv.length >= 2,             "PROC-004 (NPROC-A-001): argv has exec + script entries");
assertEq(typeof process.argv[0], "string",   "PROC-004 (NPROC-A-001): argv[0] is string (executable)");
assertEq(typeof process.argv[1], "string",  "PROC-004 (NPROC-A-001): argv[1] is string (script path)");

// PROC-005 (NPROC-E-001, NPROC-E-002, NPROC-E-006): env
assertEq(typeof process.env, "object",       "PROC-005 (NPROC-E-001): env is object");
assert(process.env !== null,                 "PROC-005 (NPROC-E-001): env is not null");
// Set and read a custom env var
process.env.JS_ENGINE_TEST = "hello";
assertEq(process.env.JS_ENGINE_TEST, "hello",  "PROC-005 (NPROC-E-002): set/read custom env var");
// Common env vars
assert(typeof process.env.PATH === "string" || typeof process.env.PATH === "undefined",
    "PROC-005 (NPROC-E-006): PATH is string or undefined");

// PROC-006 (NPROC-W-001): cwd()
assertEq(typeof process.cwd(), "string",     "PROC-006 (NPROC-W-001): cwd() returns string");
assert(process.cwd().length > 0,             "PROC-006 (NPROC-W-001): cwd() non-empty");

// PROC-008 (NPROC-T-001, NPROC-T-002): nextTick
var ticked = false;
process.nextTick(function() {
    ticked = true;
});
assert(!ticked, "PROC-008 (NPROC-T-001): nextTick is asynchronous (not yet fired)");
setImmediate(function() {
    assert(ticked, "PROC-008 (NPROC-T-002): nextTick fires before setImmediate");
    __jacDone();
});

// PROC-009 (NPROC-T-004, NPROC-T-005): hrtime
if (typeof process.hrtime === "function") {
    var t1 = process.hrtime();
    assert(Array.isArray(t1),                "PROC-009 (NPROC-T-004): hrtime returns array");
    assertEq(t1.length, 2,                   "PROC-009 (NPROC-T-004): hrtime has 2 elements [sec,ns]");
    assert(typeof t1[0] === "number",        "PROC-009 (NPROC-T-004): hrtime[0] sec is number");
    assert(typeof t1[1] === "number",        "PROC-009 (NPROC-T-004): hrtime[1] ns is number");
    var t2 = process.hrtime(t1);
    assert(Array.isArray(t2),               "PROC-009 (NPROC-T-005): hrtime diff returns array");
    assert(t2[0] >= 0,                      "PROC-009 (NPROC-T-005): diff sec >= 0");
    assert(t2[1] >= 0,                      "PROC-009 (NPROC-T-005): diff ns >= 0");
}
__jacDone();
