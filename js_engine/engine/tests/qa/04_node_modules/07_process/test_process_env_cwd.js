// testing_plans/06_process_os_stdio/NODE_PROCESS_COMPREHENSIVE_TEST_PLAN.md — ECG-2 (env + cwd/chdir)
var fs = require("fs");
var path = require("path");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/07_process/test_process_env_cwd.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

assert(typeof process.env === "object" && process.env !== null, "NPROC-E-001: process.env is object");

var delKey = "JS_ENGINE_NPROC_ENV_DEL";
process.env[delKey] = "x";
assertEq(process.env[delKey], "x", "NPROC-E-003: env key set before delete");
delete process.env[delKey];
assert(typeof process.env[delKey] === "undefined", "NPROC-E-003: delete removes env key");

var numKey = "JS_ENGINE_NPROC_ENV_NUM";
process.env[numKey] = 42;
assertEq(typeof process.env[numKey], "string", "NPROC-E-004: numeric assignment coerces to string");
assertEq(process.env[numKey], "42", "NPROC-E-004: coerced env value is canonical string");
delete process.env[numKey];

assertEq(typeof process.cwd(), "string", "NPROC-W-001: cwd returns string");
assert(process.cwd().length > 0, "NPROC-W-001: cwd non-empty");

if (typeof process.chdir === "function") {
    var orig = process.cwd();
    var tmp = fs.mkdtempSync(path.join(orig, "js_engine-nproc-chdir-"));
    var nested = path.join(tmp, "nested");
    fs.mkdirSync(nested);

    process.chdir(nested);
    assertEq(process.cwd(), nested, "NPROC-W-002: chdir updates cwd");

    process.chdir(orig);
    assertEq(process.cwd(), orig, "NPROC-W-003: chdir restores prior cwd");

    var missing = path.join(tmp, "does-not-exist-9f3a2c");
    var threw = false;
    try {
        process.chdir(missing);
    } catch (e) {
        threw = e && (e.code === "ENOENT" || e.code === "ENOTDIR");
    }
    assert(threw, "NPROC-W-004: chdir missing path throws ENOENT family");

    var typeThrew = false;
    try {
        process.chdir(123);
    } catch (e) {
        typeThrew = e instanceof TypeError;
    }
    assert(typeThrew, "NPROC-W-005: chdir non-string throws TypeError");

    fs.rmdirSync(nested);
    fs.rmdirSync(tmp);
} else {
    console.log("skip NPROC-W-002..W-006: process.chdir not implemented");
}

console.log("ok process env/cwd (NPROC-E-*, NPROC-W-*)");
__jacDone();
