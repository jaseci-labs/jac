// PROC-EXIT-001: explicit process.exit(code) fires exit listeners in order
var fs = require("fs");
var sentinel = process.argv[2];
process.on("exit", function (code) {
    fs.appendFileSync(sentinel, "A:" + code + "\n");
});
process.on("exit", function (code) {
    fs.appendFileSync(sentinel, "B:" + code + "\n");
});
process.exit(7);
