#!/usr/bin/env bash
# PROC-007 / NPROC-X-002: process.exit with specific code
# PROC-010 / NPROC-S-002, NPROC-S-003: stdout/stderr.write
# NPROC-A-002: argv forwards extra CLI args after script
# NPROC-X-003: natural exit honors process.exitCode
set -uo pipefail
: "${JAC_JS_RUNNER:=bin/js_engine}"
dir=$(dirname "${BASH_SOURCE[0]}")
# shellcheck disable=SC1091
source "$dir/../../_harness/regression_case_sh.sh"
stdout=$(mktemp); stderr=$(mktemp)
trap 'rm -f "$stdout" "$stderr"' EXIT

# PROC-007 (NPROC-X-002): process.exit(42) should exit with code 42
exit_code=0
"$JAC_JS_RUNNER" "$dir/test_process_exit.fixture.js" >/dev/null 2>&1 || exit_code=$?
if [[ $exit_code -ne 42 ]]; then
    regression_record_fail "PROC-007 (NPROC-X-002): expected exit code 42, got $exit_code"
fi

# PROC-010 (NPROC-S-002, NPROC-S-003): process.stdout.write sends to stdout
exit_code=0
"$JAC_JS_RUNNER" "$dir/test_process_stdio.fixture.js" >"$stdout" 2>"$stderr" || exit_code=$?
if [[ $exit_code -ne 0 ]]; then
    regression_record_fail "PROC-010 (NPROC-S-002, NPROC-S-003): fixture exited $exit_code"
fi
if ! grep -q "stdout line" "$stdout"; then
    regression_record_fail "PROC-010 (NPROC-S-002): 'stdout line' not in stdout"
fi
if ! grep -q "stderr line" "$stderr"; then
    regression_record_fail "PROC-010 (NPROC-S-003): 'stderr line' not in stderr"
fi

# NPROC-A-002: extra args after script path appear in process.argv
exit_code=0
"$JAC_JS_RUNNER" "$dir/test_process_argv.fixture.js" first-extra second-extra >/dev/null 2>&1 || exit_code=$?
if [[ $exit_code -ne 0 ]]; then
    regression_record_fail "NPROC-A-002: argv fixture exited $exit_code"
fi

# NPROC-X-003: draining the event loop exits with process.exitCode
exit_code=0
"$JAC_JS_RUNNER" -e 'process.exitCode = 7' >/dev/null 2>&1 || exit_code=$?
if [[ $exit_code -ne 7 ]]; then
    regression_record_fail "NPROC-X-003: expected exit code 7 from process.exitCode, got $exit_code"
fi

regression_finish_test_case "regression/04_node_modules/07_process/test_process_shell.sh"
