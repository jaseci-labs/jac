// testing_plans/06_process_os_stdio/NODE_PROCESS_COMPREHENSIVE_TEST_PLAN.md — ECG-4 (stdio streams)
var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/07_process/test_process_stdio_streams.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }

assert(typeof process.stdout === "object" && process.stdout !== null, "NPROC-S-001: stdout object");
assert(typeof process.stderr === "object" && process.stderr !== null, "NPROC-S-001: stderr object");
assert(typeof process.stdout.write === "function", "NPROC-S-001: stdout.write callable");
assert(typeof process.stderr.write === "function", "NPROC-S-001: stderr.write callable");

assert(typeof process.stdin === "object" && process.stdin !== null, "NPROC-S-005: stdin object exists");

var w1 = process.stdout.write("nproc-stdio-check\n");
assert(w1 === true, "NPROC-S-002: stdout.write(string) returns true");

var w2 = process.stderr.write("nproc-stderr-check\n");
assert(w2 === true, "NPROC-S-003: stderr.write(string) returns true");

var threw = false;
try {
    process.stdout.write(undefined);
} catch (e) {
    threw = e instanceof TypeError;
}
assert(threw, "NPROC-S-004: stdout.write(undefined) throws TypeError");

console.log("ok process stdio streams (NPROC-S-*)");
__jacDone();
