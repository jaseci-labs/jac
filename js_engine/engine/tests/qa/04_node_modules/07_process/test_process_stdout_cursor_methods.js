// Regression: process.stdout / process.stderr must expose the Node
// tty.WriteStream cursor API — clearLine, cursorTo, moveCursor (plus
// getColorDepth / getWindowSize). They were absent (the streams are built as
// writable streams with `isTTY` but without these methods), so vite's build
// reporter — `if (process.stdout.isTTY) { process.stdout.clearLine(0);
// process.stdout.cursorTo(0); }` — threw "(object).clearLine is not a function"
// and aborted `vite build`. See VITE_ROADMAP.md B6 (2026-09-14).
//
// Portability: Node only attaches these methods when the stream IS a TTY, and
// this suite runs piped (isTTY false) under Node, so under Node the methods may
// be absent — that is fine. The engine attaches them to stdout/stderr
// unconditionally (they no-op internally when not a TTY). So: WHEN a method is
// present it must be callable-and-safe, and the vite reporter idiom must never
// throw on either runtime.
var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/07_process/test_process_stdout_cursor_methods.js");
var __jacOrigExit = process.exit.bind(process);
function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

function checkStream(stream, label) {
  // If the cursor API is present at all, every member must be present and each
  // call must return true without throwing (Node's contract when it IS a TTY;
  // the engine's contract always). Absent-entirely is only acceptable for a
  // non-TTY Node stream.
  var hasClear = typeof stream.clearLine === "function";
  if (!hasClear) {
    assert(!stream.isTTY, label + ": clearLine absent only allowed on a non-TTY stream");
    return;
  }
  assertEq(typeof stream.cursorTo, "function", label + ": cursorTo present alongside clearLine");
  assertEq(typeof stream.moveCursor, "function", label + ": moveCursor present alongside clearLine");
  assertEq(typeof stream.getColorDepth, "function", label + ": getColorDepth present");
  assertEq(typeof stream.getWindowSize, "function", label + ": getWindowSize present");

  assertEq(stream.clearLine(0), true, label + ": clearLine(0) returns true");
  assertEq(stream.cursorTo(0), true, label + ": cursorTo(0) returns true");
  assertEq(stream.moveCursor(0, 0), true, label + ": moveCursor(0,0) returns true");

  var cbFired = false;
  stream.clearLine(0, function () { cbFired = true; });
  assert(cbFired, label + ": clearLine callback fired");

  var ws = stream.getWindowSize();
  assert(Array.isArray(ws) && ws.length === 2 && typeof ws[0] === "number" && typeof ws[1] === "number",
    label + ": getWindowSize returns [cols, rows] numbers");
  assert(typeof stream.getColorDepth() === "number", label + ": getColorDepth returns a number");
}

// PROC-TTY-001 — cursor API present-and-callable (engine always; Node when TTY).
checkStream(process.stdout, "PROC-TTY-001 stdout");
checkStream(process.stderr, "PROC-TTY-001 stderr");

// PROC-TTY-002 — the exact vite build-reporter idiom must not throw on any
// runtime. On the engine (methods present) this actually exercises them; under
// non-TTY Node the isTTY guard short-circuits.
var reporterOk = true;
try {
  if (process.stdout.isTTY) { process.stdout.clearLine(0); process.stdout.cursorTo(0); }
} catch (e) { reporterOk = false; }
assert(reporterOk, "PROC-TTY-002: vite clearLine+cursorTo reporter idiom does not throw");

__reg.finalize(__jacOrigExit);
