// ASRT-001 through ASRT-009: assert module
var assert = require("assert");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/10_assert/test_assert.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function ok(cond, msg) { __reg.ok(cond, msg); }
function check(fn, msg) { __reg.check(fn, msg); }
function checkThrows(fn, msg) { __reg.checkThrows(fn, msg); }

// ASRT-001: assert() / ok()
check(function() { assert(true); },      "ASRT-001: assert(true) passes");
check(function() { assert.ok(1); },      "ASRT-001: ok(1) passes");
checkThrows(function() { assert(false); },"ASRT-001: assert(false) throws");
checkThrows(function() { assert.ok(0); }, "ASRT-001: ok(0) throws");

// ASRT-002: equal / notEqual (==)
check(function() { assert.equal(1, "1"); },       "ASRT-002: equal 1=='1'");
check(function() { assert.notEqual(1, 2); },      "ASRT-002: notEqual 1!=2");
checkThrows(function() { assert.equal(1, 2); },   "ASRT-002: equal 1!=2 throws");
checkThrows(function() { assert.notEqual(1, 1); },"ASRT-002: notEqual 1!=1 throws");

// ASRT-003: strictEqual / notStrictEqual (===)
check(function() { assert.strictEqual(1, 1); },         "ASRT-003: strictEqual 1===1");
check(function() { assert.notStrictEqual(1, "1"); },    "ASRT-003: notStrictEqual 1!=='1'");
checkThrows(function() { assert.strictEqual(1, "1"); }, "ASRT-003: strictEqual 1!=='1' throws");
checkThrows(function() { assert.notStrictEqual(1,1); }, "ASRT-003: notStrictEqual 1===1 throws");

// ASRT-004: deepEqual / deepStrictEqual
check(function() { assert.deepEqual({a:1}, {a:1}); },       "ASRT-004: deepEqual same");
check(function() { assert.deepStrictEqual({a:1},{a:1}); },  "ASRT-004: deepStrictEqual same");
checkThrows(function() { assert.deepStrictEqual({a:1},{a:"1"}); },
    "ASRT-004: deepStrictEqual {a:1}!={a:'1'} throws");

// ASRT-005: notDeepEqual / notDeepStrictEqual
check(function() { assert.notDeepEqual({a:1},{a:2}); },         "ASRT-005: notDeepEqual different");
check(function() { assert.notDeepStrictEqual({a:1},{a:"1"}); }, "ASRT-005: notDeepStrictEqual diff");
checkThrows(function() { assert.notDeepEqual({a:1},{a:1}); },   "ASRT-005: notDeepEqual same throws");

// ASRT-006: throws / doesNotThrow
check(function() { assert.throws(function() { throw new Error("err"); }); },
    "ASRT-006: throws passes when fn throws");
check(function() { assert.doesNotThrow(function() {}); },
    "ASRT-006: doesNotThrow passes when fn doesn't throw");
checkThrows(function() { assert.throws(function() {}); },
    "ASRT-006: throws fails when fn doesn't throw");
// throws with specific error type
check(function() { assert.throws(function() { throw new TypeError("t"); }, TypeError); },
    "ASRT-006: throws with TypeError check");

// ASRT-007: rejects / doesNotReject
var done7 = false;
Promise.all([
    assert.rejects(Promise.reject(new Error("oops"))),
    assert.doesNotReject(Promise.resolve(42))
]).then(function() {
    done7 = true;
}).catch(function(e) {
    console.error("FAIL: ASRT-007: " + e.message);
    __reg.bump(); __jacDone();
});

// ASRT-008: ifError / match / fail
check(function() { assert.ifError(null); },           "ASRT-008: ifError(null) passes");
check(function() { assert.ifError(undefined); },      "ASRT-008: ifError(undefined) passes");
checkThrows(function() { assert.ifError(new Error("e")); }, "ASRT-008: ifError(Error) throws");
checkThrows(function() { assert.fail("always fails"); },    "ASRT-008: fail() throws");
if (typeof assert.match === "function") {
    check(function() { assert.match("hello world", /world/); }, "ASRT-008: match passes");
    checkThrows(function() { assert.match("hello", /xyz/); },   "ASRT-008: match fails throws");
}

// ASRT-009: assert.strict
if (assert.strict) {
    ok(typeof assert.strict === "function" || typeof assert.strict === "object",
        "ASRT-009: assert.strict exists");
    // strict.equal uses === not ==
    var strictFn = typeof assert.strict === "function" ? assert.strict : assert.strict;
    checkThrows(function() { assert.strict.equal(1, "1"); },
        "ASRT-009: strict.equal uses ===");
}

setTimeout(function() {
    ok(done7, "ASRT-007: rejects/doesNotReject resolved");
    __jacDone();
}, 1000);
