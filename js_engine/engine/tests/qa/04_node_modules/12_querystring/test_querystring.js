// QS-001 through QS-004: querystring module
var qs = require("querystring");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/12_querystring/test_querystring.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

// QS-001: parse
var parsed = qs.parse("a=1&b=2&c=3");
assertEq(parsed.a, "1",           "QS-001: parse a=1");
assertEq(parsed.b, "2",           "QS-001: parse b=2");
assertEq(parsed.c, "3",           "QS-001: parse c=3");
// repeated keys -> array
var multi = qs.parse("x=1&x=2&x=3");
assert(Array.isArray(multi.x),    "QS-001: repeated keys become array");
assertEq(multi.x[0], "1",         "QS-001: repeated key first value");
assertEq(multi.x[2], "3",         "QS-001: repeated key third value");
// custom separator and equals
var custom = qs.parse("a;1|b;2", "|", ";");
assertEq(custom.a, "1",           "QS-001: custom sep and eq");
assertEq(custom.b, "2",           "QS-001: custom sep b");

// QS-002: stringify
var str = qs.stringify({a:"1", b:"2"});
assert(str.indexOf("a=1") >= 0,   "QS-002: stringify a=1");
assert(str.indexOf("b=2") >= 0,   "QS-002: stringify b=2");
assert(str.indexOf("&") >= 0,     "QS-002: stringify uses & separator");
// array values
var arrStr = qs.stringify({x: ["1","2","3"]});
assert(arrStr.indexOf("x=1") >= 0, "QS-002: array values");
assert(arrStr.indexOf("x=2") >= 0, "QS-002: array values 2");

// QS-003: escape / unescape
var escaped = qs.escape("hello world & foo=bar");
assertEq(typeof escaped, "string",  "QS-003: escape returns string");
assert(escaped.indexOf(" ") < 0,    "QS-003: escape removes spaces");
var unescaped = qs.unescape(escaped);
assertEq(unescaped, "hello world & foo=bar", "QS-003: unescape round-trip");

// QS-004: decode / encode aliases
assertEq(qs.decode, qs.parse,       "QS-004: decode is alias for parse");
assertEq(qs.encode, qs.stringify,   "QS-004: encode is alias for stringify");

__jacDone();
