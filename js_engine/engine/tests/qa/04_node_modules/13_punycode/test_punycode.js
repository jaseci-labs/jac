// PC-001 through PC-004: punycode module (deprecated but still available)
var punycode;
var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/13_punycode/test_punycode.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

try {
    punycode = require("punycode");
} catch(e) {
    // punycode may be removed in newer Node.js — skip gracefully
    console.log("punycode module not available — skipping");
    __jacDone();
}

function assert(cond, msg) {
    if (!cond) { console.error("FAIL: " + msg); __reg.bump(); return; }
}
function assertEq(a, e, msg) {
    if (a !== e) { console.error("FAIL: " + msg + " | expected: " + JSON.stringify(e) + " | actual: " + JSON.stringify(a)); __reg.bump(); return; }
}

// PC-001: encode / decode
var encoded = punycode.encode("München");
assertEq(typeof encoded, "string",         "PC-001: encode returns string");
assert(encoded.indexOf("nchen") >= 0,      "PC-001: encode contains ASCII part");
var decoded = punycode.decode(encoded);
assertEq(decoded, "München",               "PC-001: decode round-trip");

// PC-002: toASCII / toUnicode
var ascii = punycode.toASCII("münchen.de");
assertEq(typeof ascii, "string",           "PC-002: toASCII returns string");
assert(ascii.indexOf(".de") >= 0,          "PC-002: toASCII preserves non-punycode parts");
var unicode = punycode.toUnicode(ascii);
assertEq(typeof unicode, "string",         "PC-002: toUnicode returns string");

// PC-003: ucs2.decode / ucs2.encode
if (punycode.ucs2) {
    var codePoints = punycode.ucs2.decode("hello");
    assert(Array.isArray(codePoints),      "PC-003: ucs2.decode returns array");
    assertEq(codePoints[0], 104,           "PC-003: ucs2.decode first char");
    var str = punycode.ucs2.encode([104, 101, 108, 108, 111]);
    assertEq(str, "hello",                 "PC-003: ucs2.encode");
}

// PC-004: version
assertEq(typeof punycode.version, "string","PC-004: version is string");
assert(punycode.version.length > 0,        "PC-004: version non-empty");

__jacDone();
