// SD-001 through SD-003: string_decoder module
var StringDecoder = require("string_decoder").StringDecoder;
var Buffer = require("buffer").Buffer;

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/14_string_decoder/test_string_decoder.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

// SD-001: new StringDecoder
var decoder = new StringDecoder("utf8");
assertEq(typeof decoder, "object",                    "SD-001: StringDecoder creates object");
assert(typeof decoder.write === "function",           "SD-001: decoder.write exists");
assert(typeof decoder.end === "function",             "SD-001: decoder.end exists");

// SD-002: write — complete buffer
var buf = Buffer.from("hello world", "utf8");
var result = decoder.write(buf);
assertEq(result, "hello world",                       "SD-002: write complete buffer");

// SD-002: write — incomplete multi-byte sequence
// UTF-8 encoding of "é" (U+00E9) is 0xC3 0xA9 (2 bytes)
var dec2 = new StringDecoder("utf8");
var partial1 = Buffer.from([0xC3]);         // first byte of "é"
var partial2 = Buffer.from([0xA9]);         // second byte of "é"
var out1 = dec2.write(partial1);
// incomplete: should either be empty or buffer the byte
assert(typeof out1 === "string",                      "SD-002: write partial returns string");
var out2 = dec2.write(partial2);
// complete: the two bytes together form "é"
var combined = out1 + out2;
assertEq(combined, "é",                               "SD-002: incomplete multi-byte written in parts");

// SD-003: end — flush remaining bytes
var dec3 = new StringDecoder("utf8");
dec3.write(Buffer.from([0xC3])); // buffered incomplete byte
var flushed = dec3.end();
assertEq(typeof flushed, "string",                    "SD-003: end returns string");
// The incomplete byte should be flushed (as replacement char or empty)
// Don't assert the exact char — engines vary on replacement character handling

__jacDone();
