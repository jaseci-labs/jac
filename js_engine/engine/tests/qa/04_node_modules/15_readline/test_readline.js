// RL-001 through RL-003: readline module (constructor and interface only; no interactive input)
var readline = require("readline");
var stream   = require("stream");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/15_readline/test_readline.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

// RL-001: createInterface
assert(typeof readline.createInterface === "function", "RL-001: createInterface exists");
// Create an interface with a PassThrough stream as input (so it won't block)
var PassThrough = stream.PassThrough;
var inputStream = new PassThrough();
var rl = readline.createInterface({input: inputStream});
assert(typeof rl === "object" && rl !== null,          "RL-001: createInterface returns object");
assert(typeof rl.close === "function",                  "RL-001: rl.close exists");
assert(typeof rl.question === "function" || true,       "RL-001: rl.question may exist");
assert(typeof rl.on === "function",                     "RL-001: rl.on exists");
assert(typeof rl.prompt === "function" || true,        "RL-001: rl.prompt may exist");

// RL-002: question / close
// Test that close fires the "close" event
var closeFired = false;
rl.on("close", function() { closeFired = true; });

// RL-003: promises.createInterface — may be absent
if (readline.promises && typeof readline.promises.createInterface === "function") {
    var inputStream2 = new PassThrough();
    var rl2 = readline.promises.createInterface({input: inputStream2});
    assert(typeof rl2 === "object",                    "RL-003: promises.createInterface returns object");
    if (rl2 && typeof rl2.close === "function") {
        rl2.close();
    }
}

// Close and verify
rl.close();
setTimeout(function() {
    assert(closeFired, "RL-002: close event fires after rl.close()");
    __jacDone();
}, 200);
