// PHK-024: markResourceTiming + buffer size
var ph = require("node:perf_hooks");
var performance = ph.performance;

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase(
    "regression/04_node_modules/24_perf_hooks/test_perf_hooks_resource_buffer.js"
);
var __jacOrigExit = process.exit.bind(process);
function __jacDone() {
    __reg.finalize(__jacOrigExit);
}

function assert(cond, msg) {
    __reg.assert(cond, msg);
}

performance.setResourceTimingBufferSize(2);
performance.markResourceTiming(
    { fetchStart: performance.now(), responseEnd: performance.now() + 1 },
    "https://example.com/x",
    "fetch",
    {},
    "",
    {},
    200
);
performance.markResourceTiming(
    { fetchStart: performance.now() },
    "https://example.com/y",
    "fetch",
    {},
    "",
    {},
    200
);
var res = performance.getEntriesByType("resource");
assert(res.length === 2, "PHK-024: resource entries");
performance.clearResourceTimings();
assert(performance.getEntriesByType("resource").length === 0, "PHK-024: cleared");

__jacDone();
