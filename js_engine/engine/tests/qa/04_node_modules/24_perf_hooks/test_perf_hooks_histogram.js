// PHK-022: createHistogram + monitorEventLoopDelay
var ph = require("node:perf_hooks");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase(
    "regression/04_node_modules/24_perf_hooks/test_perf_hooks_histogram.js"
);
var __jacOrigExit = process.exit.bind(process);
function __jacDone() {
    __reg.finalize(__jacOrigExit);
}

function assert(cond, msg) {
    __reg.assert(cond, msg);
}

var h = ph.createHistogram({ lowest: 1, highest: 1000, figures: 3 });
h.record(10);
h.record(20);
h.record(30);
assert(h.count === 3, "PHK-022: histogram count");
assert(h.min <= h.max, "PHK-022: min <= max");
assert(typeof h.percentile(50) === "number", "PHK-022: percentile");
h.reset();
assert(h.count === 0, "PHK-022: reset");

var el = ph.monitorEventLoopDelay({ resolution: 20 });
assert(el.enable() === true, "PHK-022: enable");
assert(el.enable() === false, "PHK-022: enable idempotent");
setTimeout(function () {
    assert(el.disable() === true, "PHK-022: disable");
    __jacDone();
}, 50);
