// PHK-003: API identity — module.performance is the global performance object
var perfHooks = require("perf_hooks");
var nodePerfHooks = require("node:perf_hooks");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase(
    "regression/04_node_modules/24_perf_hooks/test_perf_hooks_global_identity.js"
);
var __jacOrigExit = process.exit.bind(process);
function __jacDone() {
    __reg.finalize(__jacOrigExit);
}

function assertEq(actual, expected, msg) {
    __reg.assertEq(actual, expected, msg);
}

assertEq(
    perfHooks.performance,
    performance,
    "PHK-003: perf_hooks.performance === global performance"
);
assertEq(
    nodePerfHooks.performance,
    performance,
    "PHK-003: node:perf_hooks.performance === global performance"
);

__jacDone();
