// PHK-023: eventLoopUtilization + timerify
var ph = require("node:perf_hooks");
var performance = ph.performance;

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase(
    "regression/04_node_modules/24_perf_hooks/test_perf_hooks_elu_timerify.js"
);
var __jacOrigExit = process.exit.bind(process);
function __jacDone() {
    __reg.finalize(__jacOrigExit);
}

function assert(cond, msg) {
    __reg.assert(cond, msg);
}

var u0 = performance.eventLoopUtilization();
assert(typeof u0.idle === "number", "PHK-023: elu idle");
assert(typeof u0.active === "number", "PHK-023: elu active");
assert(typeof u0.utilization === "number", "PHK-023: elu utilization");

var fnObserved = false;
var obs = new ph.PerformanceObserver(function (list) {
    var fnEntries = list.getEntriesByType("function");
    if (fnEntries.length >= 1) {
        fnObserved = true;
    }
    obs.disconnect();
});
obs.observe({ entryTypes: ["function"] });

function work() {
    return 42;
}
var wrapped = performance.timerify(work);
var got = wrapped();
assert(got === 42, "PHK-023: timerify return value");

setImmediate(function () {
    assert(fnObserved, "PHK-023: function entry recorded via observer");
    __jacDone();
});
