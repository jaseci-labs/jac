// PHK-021: PerformanceObserver observe / disconnect / takeRecords
var ph = require("node:perf_hooks");
var performance = ph.performance;
var PerformanceObserver = ph.PerformanceObserver;

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase(
    "regression/04_node_modules/24_perf_hooks/test_perf_hooks_observer.js"
);
var __jacOrigExit = process.exit.bind(process);
function __jacDone() {
    __reg.finalize(__jacOrigExit);
}

function assert(cond, msg) {
    __reg.assert(cond, msg);
}

performance.mark("pre");
var obs = new PerformanceObserver(function (list, observer) {
    var all = list.getEntries();
    assert(all.length >= 1, "PHK-021: observer got entries");
    var taken = observer.takeRecords();
    assert(Array.isArray(taken), "PHK-021: takeRecords array");
    observer.disconnect();
});
obs.observe({ entryTypes: ["mark"], buffered: true });
performance.mark("post");

setImmediate(function () {
    __jacDone();
});
