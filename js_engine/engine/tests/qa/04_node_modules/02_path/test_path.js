// PATH-001..PATH-008 + NPATH-* aliases — see testing_plans/06_process_os_stdio/NODE_PATH_COMPREHENSIVE_TEST_PLAN.md
var path = require("path");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/02_path/test_path.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

// PATH-001 (NPATH-J-*): join
assertEq(path.join("a", "b", "c"),      "a/b/c",        "PATH-001 (NPATH-J-001): join segments");
assertEq(path.join("a", "..", "b"),      "b",            "PATH-001 (NPATH-J-004): join with ..");
assertEq(path.join("a", ".", "b"),       "a/b",          "PATH-001 (NPATH-J-003): join with .");
assertEq(path.join("/a", "b"),           "/a/b",         "PATH-001 (NPATH-J-007): join absolute");
assertEq(path.join(""),                  ".",            "PATH-001 (NPATH-J-006): join empty segment");

// PATH-002 (NPATH-R-*): resolve
var resolved = path.resolve("foo", "bar");
assert(path.isAbsolute(resolved),                         "PATH-002 (NPATH-R-001): resolve returns absolute");
assertEq(path.resolve("/a", "b", "c"),  "/a/b/c",        "PATH-002 (NPATH-R-001): resolve absolute base");
assertEq(path.resolve("/a", "/b"),      "/b",            "PATH-002 (NPATH-R-002): resolve second absolute overrides");

// PATH-003 (NPATH-N-*): normalize
assertEq(path.normalize("/a//b///c"),   "/a/b/c",        "PATH-003 (NPATH-N-001): redundant slashes");
assertEq(path.normalize("a/b/../c"),    "a/c",           "PATH-003 (NPATH-N-002): .. navigation");
assertEq(path.normalize("a/./b"),       "a/b",           "PATH-003 (NPATH-N-002): . removal");
assertEq(path.normalize(""),            ".",             "PATH-003 (NPATH-N-003): empty = '.'");
// A trailing separator survives normalize/join, as in Node (Vite's build report
// slices file names by path.join(assetsDir, "/").length).
assertEq(path.normalize("a/b/"),        "a/b/",          "PATH-003 (NPATH-N-004): trailing separator kept");
assertEq(path.normalize("./"),          "./",            "PATH-003 (NPATH-N-004): './' stays './'");
assertEq(path.normalize("/a/b/../"),    "/a/",           "PATH-003 (NPATH-N-004): trailing separator after ..");
assertEq(path.join("assets", "/"),      "assets/",       "PATH-001 (NPATH-J-008): join keeps a trailing separator");
assertEq(path.resolve("/a/b/"),         "/a/b",          "PATH-001 (NPATH-J-008): resolve still drops it");

// PATH-004 (NPATH-D/B/E-*): dirname / basename / extname
assertEq(path.dirname("/a/b/c.txt"),    "/a/b",          "PATH-004 (NPATH-D-001): dirname");
assertEq(path.dirname("/a/b/"),         "/a",            "PATH-004 (NPATH-D-002): dirname trailing slash");
assertEq(path.dirname("file.txt"),      ".",             "PATH-004 (NPATH-D-004): dirname no dir");
assertEq(path.basename("/a/b/c.txt"),   "c.txt",         "PATH-004 (NPATH-B-001): basename");
assertEq(path.basename("/a/b/c.txt", ".txt"), "c",       "PATH-004 (NPATH-B-002): basename strip ext");
assertEq(path.basename(""),             "",              "PATH-004 (NPATH-B-004): basename empty");
assertEq(path.extname("c.txt"),         ".txt",          "PATH-004 (NPATH-E-001): extname");
assertEq(path.extname("c.tar.gz"),      ".gz",           "PATH-004 (NPATH-E-002): extname last dot");
assertEq(path.extname("noext"),         "",              "PATH-004 (NPATH-E-001): extname no ext");
assertEq(path.extname(".hidden"),        "",              "PATH-004 (NPATH-E-004): extname dotfile");

// PATH-005 (NPATH-L-*): relative
assertEq(path.relative("/a/b/c", "/a/b/d"), "../d",     "PATH-005 (NPATH-L-002): relative same-parent sibling");
assertEq(path.relative("/a/b", "/a/c"),     "../c",      "PATH-005 (NPATH-L-002): relative same parent");
assertEq(path.relative("/a/b", "/a/b/c"),   "c",         "PATH-005 (NPATH-L-003): relative child");
assertEq(path.relative("/a/b/c", "/a/b"),   "..",        "PATH-005 (NPATH-L-004): relative parent");
assertEq(path.relative("/a", "/a"),         "",          "PATH-005 (NPATH-L-001): relative same = empty");

// PATH-006 (NPATH-A-*): isAbsolute
assert(path.isAbsolute("/a/b"),             "PATH-006 (NPATH-A-001): absolute path");
assert(path.isAbsolute("/"),                "PATH-006 (NPATH-A-001): root is absolute");
assert(!path.isAbsolute("a/b"),             "PATH-006 (NPATH-A-002): relative is not absolute");
assert(!path.isAbsolute("./a"),             "PATH-006 (NPATH-A-002): ./ is relative");

// PATH-007 (NPATH-P/F-*): parse / format
var parsed = path.parse("/home/user/file.txt");
assertEq(parsed.root,  "/",                "PATH-007 (NPATH-P-001): parse root");
assertEq(parsed.dir,   "/home/user",       "PATH-007 (NPATH-P-001): parse dir");
assertEq(parsed.base,  "file.txt",         "PATH-007 (NPATH-P-001): parse base");
assertEq(parsed.ext,   ".txt",             "PATH-007 (NPATH-P-001): parse ext");
assertEq(parsed.name,  "file",             "PATH-007 (NPATH-P-001): parse name");
var formatted = path.format(parsed);
assertEq(formatted, "/home/user/file.txt", "PATH-007 (NPATH-F-005): format round-trip");

// PATH-008 (NPATH-C/M-*): sep / delimiter / posix
assertEq(path.sep,           "/",  "PATH-008 (NPATH-C-001): sep on POSIX");
assertEq(path.delimiter,     ":",  "PATH-008 (NPATH-C-002): delimiter on POSIX");
assert(typeof path.posix === "object" || typeof path.posix === "undefined",
    "PATH-008 (NPATH-M-004): path.posix is object or absent");

__jacDone();
