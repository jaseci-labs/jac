// URL-001 through URL-006: url module
var urlModule = require("url");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/11_url/test_url.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

// URL-001: new URL(input, base)
var u1 = new URL("https://example.com/path?q=1#hash");
assertEq(u1.protocol,    "https:",           "URL-001: protocol");
assertEq(u1.host,        "example.com",      "URL-001: host");
assertEq(u1.pathname,    "/path",            "URL-001: pathname");
assertEq(u1.search,      "?q=1",            "URL-001: search");
assertEq(u1.hash,        "#hash",            "URL-001: hash");
// relative URL with base
var u2 = new URL("/other", "https://example.com");
assertEq(u2.pathname,    "/other",           "URL-001: relative pathname");
assertEq(u2.host,        "example.com",      "URL-001: relative host from base");

// URL-002: URL properties
var u3 = new URL("https://user:pass@example.com:8080/p?a=1#h");
assertEq(u3.username,    "user",             "URL-002: username");
assertEq(u3.password,    "pass",             "URL-002: password");
assertEq(u3.port,        "8080",             "URL-002: port");
assertEq(u3.hostname,    "example.com",      "URL-002: hostname");
assertEq(u3.origin,      "https://example.com:8080", "URL-002: origin");
assertEq(typeof u3.href, "string",           "URL-002: href is string");

// URL-003: URL setters
var u4 = new URL("http://example.com/old");
u4.pathname = "/new";
assertEq(u4.pathname, "/new",                "URL-003: pathname setter");
u4.search = "?x=2";
assertEq(u4.search,   "?x=2",               "URL-003: search setter");
u4.hash = "#section";
assertEq(u4.hash,     "#section",            "URL-003: hash setter");

// URL-004: toString / toJSON
var u5 = new URL("https://example.com/path");
assertEq(typeof u5.toString(), "string",     "URL-004: toString returns string");
assertEq(u5.toString(), u5.href,             "URL-004: toString = href");
assertEq(typeof u5.toJSON(), "string",       "URL-004: toJSON returns string");
assertEq(u5.toJSON(), u5.href,               "URL-004: toJSON = href");

// URL-005: URLSearchParams
var sp = new URLSearchParams("a=1&b=2&c=3");
assertEq(sp.get("a"),  "1",                  "URL-005: get");
assertEq(sp.get("b"),  "2",                  "URL-005: get b");
assert(sp.has("c"),                          "URL-005: has");
assert(!sp.has("d"),                         "URL-005: has missing = false");
sp.set("a", "99");
assertEq(sp.get("a"),  "99",                 "URL-005: set");
sp.append("b", "22");
var allB = sp.getAll("b");
assert(allB.length === 2,                    "URL-005: append creates second value");
sp.delete("c");
assert(!sp.has("c"),                         "URL-005: delete");
sp.sort();
assertEq(typeof sp.toString(), "string",     "URL-005: toString");
// iteration
var keys = [], vals = [], ents = [];
for (var k of sp.keys())    keys.push(k);
for (var v of sp.values())  vals.push(v);
for (var e of sp.entries()) ents.push(e[0]);
assert(keys.length > 0,                      "URL-005: keys() iterable");
assert(vals.length > 0,                      "URL-005: values() iterable");

// URL-006: Legacy parse / format / resolve (may be deprecated but should exist)
if (typeof urlModule.parse === "function") {
    var parsed = urlModule.parse("https://example.com/path?q=1");
    assertEq(typeof parsed, "object",        "URL-006: parse returns object");
    assertEq(parsed.protocol, "https:",      "URL-006: parsed.protocol");
    assertEq(parsed.pathname, "/path",       "URL-006: parsed.pathname");
}
if (typeof urlModule.format === "function") {
    var formatted = urlModule.format({
        protocol: "https:",
        host: "example.com",
        pathname: "/path"
    });
    assertEq(typeof formatted, "string",     "URL-006: format returns string");
    assert(formatted.indexOf("example.com") >= 0, "URL-006: format contains host");
}
if (typeof urlModule.resolve === "function") {
    var resolved = urlModule.resolve("https://example.com/a/b", "../c");
    assertEq(typeof resolved, "string",      "URL-006: resolve returns string");
    assert(resolved.indexOf("example.com") >= 0, "URL-006: resolve contains host");
}

__jacDone();
