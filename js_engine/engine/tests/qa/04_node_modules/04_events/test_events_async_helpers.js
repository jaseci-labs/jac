// NODE_EVENTS_COMPREHENSIVE_TEST_PLAN.md — ECG-4: events.once / events.on (NEVT-A-*, NEVT-M-004)

var events = require("events");
var EventEmitter = events.EventEmitter || events;
var onceStatic = events.once;

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/04_events/test_events_async_helpers.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }
function assertDeep(actual, expected, msg) { __reg.assertDeep(actual, expected, msg); }

async function main() {
    // NEVT-M-004 (ESM dynamic import) is covered by a dedicated module harness when needed;
    // require('events') === require('node:events') is asserted in test_events_module_and_core.js (NEVT-M-002).

    // --- NEVT-A-001: events.once resolves with array of emitted arguments ---
    var ee1 = new EventEmitter();
    setImmediate(function () {
        ee1.emit("e", 1, 2);
    });
    assertDeep(await onceStatic(ee1, "e"), [1, 2], "NEVT-A-001: once resolves with multi-arg array");

    var ee2 = new EventEmitter();
    setImmediate(function () {
        ee2.emit("e2", 99);
    });
    assertDeep(await onceStatic(ee2, "e2"), [99], "NEVT-A-001: once resolves with single-arg as one-element array");

    var ee3 = new EventEmitter();
    setImmediate(function () {
        ee3.emit("e3");
    });
    assertDeep(await onceStatic(ee3, "e3"), [], "NEVT-A-001: once resolves with empty array when no args");

    // --- NEVT-A-002: waiting for non-error event rejects on error ---
    var ee4 = new EventEmitter();
    setImmediate(function () {
        ee4.emit("error", new Error("fail-first"));
    });
    var rejected = false;
    await onceStatic(ee4, "foo").catch(function () {
        rejected = true;
    });
    assert(rejected, "NEVT-A-002: once(emitter, non-error) rejects when error emits first");

    // --- NEVT-A-003: once(emitter, 'error') resolves like a normal event ---
    var ee5 = new EventEmitter();
    var err5 = new Error("boom");
    setImmediate(function () {
        ee5.emit("error", err5);
    });
    var res5 = await onceStatic(ee5, "error");
    assertDeep(res5, [err5], "NEVT-A-003: once for error event resolves with emitted arguments array");

    // --- NEVT-A-004: AbortSignal cancels once ---
    if (typeof AbortController === "function") {
        var ee6 = new EventEmitter();
        var ac = new AbortController();
        setImmediate(function () {
            ac.abort();
        });
        var aborted = false;
        await onceStatic(ee6, "never", { signal: ac.signal }).catch(function (e) {
            aborted = e && e.name === "AbortError";
        });
        assert(aborted, "NEVT-A-004: once with aborted signal rejects with AbortError");
    }

    // --- NEVT-A-005: sequential await once can miss events; Promise.all pattern works ---
    var eeMiss = new EventEmitter();
    setImmediate(function () {
        eeMiss.emit("foo");
        eeMiss.emit("bar");
    });
    var rMiss = await Promise.race([
        onceStatic(eeMiss, "foo").then(function () {
            return "foo";
        }),
        onceStatic(eeMiss, "bar").then(function () {
            return "bar";
        })
    ]);
    assert(rMiss === "foo" || rMiss === "bar", "NEVT-A-005: race shows first delivered once resolves");

    var eeBoth = new EventEmitter();
    setImmediate(function () {
        eeBoth.emit("foo");
        eeBoth.emit("bar");
    });
    var pair = await Promise.all([onceStatic(eeBoth, "foo"), onceStatic(eeBoth, "bar")]);
    assertDeep(pair, [[], []], "NEVT-A-005: Promise.all(once, once) catches both events same tick");

    __jacDone();
}

main().catch(function (e) {
    console.error("FAIL: NEVT-A async helpers: " + e);
    __reg.bump(); __jacDone();
});
__jacDone();
