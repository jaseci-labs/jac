// NODE_EVENTS_COMPREHENSIVE_TEST_PLAN.md — NEVT-M-004 (dynamic `import('node:events')` vs CJS)

import { createRequire } from "node:module";

const require = createRequire(import.meta.url);

function assert(cond, msg) {
    if (!cond) {
        console.error("FAIL: " + msg);
        process.exit(1);
    }
}
function assertEq(a, e, msg) {
    if (a !== e) {
        console.error(
            "FAIL: " +
                msg +
                " | expected: " +
                JSON.stringify(e) +
                " | actual: " +
                JSON.stringify(a)
        );
        process.exit(1);
    }
}

const cjsEvents = require("events");
const cjsNodeEvents = require("node:events");

assert(cjsEvents === cjsNodeEvents, "NEVT-M-004: require('events') aliases require('node:events')");

const ns = await import("node:events");

assertEq(typeof ns.EventEmitter, "function", "NEVT-M-004: dynamic import namespace exposes EventEmitter");
assertEq(typeof ns.default, "function", "NEVT-M-004: dynamic import default is EventEmitter constructor");
assertEq(typeof ns.once, "function", "NEVT-M-004: dynamic import exposes once");
assertEq(typeof ns.listenerCount, "function", "NEVT-M-004: dynamic import exposes listenerCount");

assert(ns.EventEmitter === cjsEvents, "NEVT-M-004: import namespace EventEmitter matches CJS export");
assert(ns.default === cjsEvents, "NEVT-M-004: import default matches CJS require('events')");

console.log("ok NEVT-M-004 dynamic import node:events");
