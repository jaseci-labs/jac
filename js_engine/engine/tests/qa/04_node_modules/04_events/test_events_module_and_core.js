// --- NEVT-C-* core semantics ---
var EventEmitter = events.EventEmitter || events;
var ee = new EventEmitter();
var calls = [];
function listener1(a, b) {
    calls.push(["l1", a, b]);
}
function listener2(a) {
    calls.push(["l2", a]);
}
ee.on("test", listener1);
ee.addListener("test", listener2);
ee.emit("test", "arg1", "arg2");
assertDeep(
    calls,
    [
        ["l1", "arg1", "arg2"],
        ["l2", "arg1"]
    ],
    "NEVT-C-001: on preserves registration order; NEVT-C-002: addListener is alias of on"
);
assertEq(ee.emit("test", "x"), true, "NEVT-C-003: emit returns true when listeners exist");
assertEq(ee.emit("nolistener"), false, "NEVT-C-003: emit returns false when no listeners");

var dupCalls = 0;
function dupFn() {
    dupCalls++;
}
ee.on("dup", dupFn);
ee.on("dup", dupFn);
ee.emit("dup");
assertEq(dupCalls, 2, "NEVT-C-006: duplicate (event, listener) registrations both run");

var eeThis = new EventEmitter();
eeThis.on(
    "t",
    function () {
        assertEq(this, eeThis, "NEVT-C-005: non-arrow listener receives emitter as this");
    }
);
eeThis.emit("t");

var sym = Symbol("nevt-c-009");
var eeSym = new EventEmitter();
eeSym.on(sym, function () {});
assertEq(typeof eeSym.listenerCount(sym), "number", "NEVT-C-009: symbol event names are supported");
eeSym.emit(sym);

var eeType = new EventEmitter();
var threwType = false;
try {
    eeType.on("x", 1);
} catch (e) {
    threwType = e instanceof TypeError;
}
assert(threwType, "NEVT-C-010: non-function listener throws TypeError");

var orderPre = [];
var eePre = new EventEmitter();
eePre.on("evt", function () {
    orderPre.push("normal");
});
eePre.prependListener("evt", function () {
    orderPre.push("prepended");
});
eePre.prependOnceListener("evt", function () {
    orderPre.push("oncePrep");
});
eePre.emit("evt");
assertEq(orderPre[0], "oncePrep", "NEVT-C-008: prependOnceListener runs before prependListener");
assertEq(orderPre[1], "prepended", "NEVT-C-008: prependListener runs before on listener");
assertEq(orderPre[2], "normal", "NEVT-C-008: on listener runs last on first emit");
orderPre.length = 0;
eePre.emit("evt");
assertDeep(orderPre, ["prepended", "normal"], "NEVT-C-008: prependOnceListener fires only once");

var eeOnceCombo = new EventEmitter();
var onceCombo = 0;
eeOnceCombo.on("once_evt", function () {
    onceCombo++;
});
eeOnceCombo.once("once_evt", function () {
    onceCombo++;
});
eeOnceCombo.emit("once_evt");
eeOnceCombo.emit("once_evt");
assertEq(onceCombo, 3, "NEVT-C-007: first emit runs on+once; second emit runs on only (total three invocations)");
var eeOnceOnly = new EventEmitter();
var oc = 0;
eeOnceOnly.once("o", function () {
    oc++;
});
eeOnceOnly.emit("o");
eeOnceOnly.emit("o");
assertEq(oc, 1, "NEVT-C-007: once listener runs at most once when it is the only registration");

var eeChain = new EventEmitter();
function chainFn() {}
assertEq(eeChain.on("a", chainFn).off("a", chainFn), eeChain, "NEVT-L-007: on/off return emitter for chaining");

__jacDone();
