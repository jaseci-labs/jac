// NODE_EVENTS_COMPREHENSIVE_TEST_PLAN.md — ECG-3: error semantics + max listeners (NEVT-E-*, NEVT-X-*)

var events = require("events");
var EventEmitter = events.EventEmitter || events;

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/04_events/test_events_errors_and_limits.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

// --- NEVT-E-001 / E-002 ---
var eeErr = new EventEmitter();
var threwUnhandled = false;
try {
    eeErr.emit("error", new Error("test error"));
} catch (e) {
    threwUnhandled = true;
}
assert(threwUnhandled, "NEVT-E-001: emit('error') without listener throws");

var eeHandled = new EventEmitter();
var caught = false;
eeHandled.on("error", function () {
    caught = true;
});
eeHandled.emit("error", new Error("handled"));
assert(caught, "NEVT-E-002: emit('error') with listener does not throw to caller");

// --- NEVT-E-003: errorMonitor observes without consuming ---
if (typeof events.errorMonitor !== "undefined") {
    var eeMon = new EventEmitter();
    var monRan = false;
    eeMon.on(events.errorMonitor, function () {
        monRan = true;
    });
    var monThrew = false;
    try {
        eeMon.emit("error", new Error("mon"));
    } catch (e) {
        monThrew = true;
    }
    assert(monRan, "NEVT-E-003: errorMonitor listener runs on error emission");
    assert(monThrew, "NEVT-E-003: error still throws when no ordinary error listener");
}

async function runAsyncEandX() {
    // --- NEVT-E-004: captureRejections routes async rejection to error ---
    var eeCap = new EventEmitter({ captureRejections: true });
    var gotCapErr = null;
    eeCap.on("kaboom", async function () {
        throw new Error("async-kaboom");
    });
    eeCap.on("error", function (err) {
        gotCapErr = err;
    });
    eeCap.emit("kaboom");
    await new Promise(function (r) {
        return setImmediate(r);
    });
    assert(gotCapErr && gotCapErr.message === "async-kaboom", "NEVT-E-004: captureRejections delivers async throw to error event");

    // --- NEVT-E-005: global EventEmitter.captureRejections affects new instances ---
    var prev = EventEmitter.captureRejections;
    EventEmitter.captureRejections = true;
    var eeG = new EventEmitter();
    var gErr = null;
    eeG.on("z", async function () {
        throw new Error("global-cap");
    });
    eeG.on("error", function (e) {
        gErr = e;
    });
    eeG.emit("z");
    await new Promise(function (r2) {
        return setImmediate(r2);
    });
    EventEmitter.captureRejections = prev;
    assert(gErr && gErr.message === "global-cap", "NEVT-E-005: global captureRejections applies to new emitters");

    // --- NEVT-X-005: MaxListenersExceededWarning ---
    var eeWarn = new EventEmitter();
    var warned = false;
    function onWarn(w) {
        if (w && w.name === "MaxListenersExceededWarning" && w.emitter === eeWarn) {
            warned = true;
        }
    }
    process.on("warning", onWarn);
    var j = 0;
    while (j < 11) {
        eeWarn.on("x", function () {});
        j = j + 1;
    }
    await new Promise(function (r3) {
        return setImmediate(r3);
    });
    process.off("warning", onWarn);
    assert(warned, "NEVT-X-005: exceeding defaultMaxListeners emits MaxListenersExceededWarning");
}

// --- NEVT-X-001 / X-002 / X-003 / X-004 ---
assertEq(EventEmitter.defaultMaxListeners, 10, "NEVT-X-001: default max listeners is 10");

var eeMax = new EventEmitter();
assertEq(eeMax.getMaxListeners(), 10, "NEVT-X-001: new emitter inherits default max listeners");
eeMax.setMaxListeners(7);
assertEq(eeMax.getMaxListeners(), 7, "NEVT-X-002: setMaxListeners updates getMaxListeners");
assertEq(eeMax.setMaxListeners(3), eeMax, "NEVT-X-002: setMaxListeners returns emitter");

var eeInf = new EventEmitter();
eeInf.setMaxListeners(Infinity);
assertEq(eeInf.getMaxListeners(), Infinity, "NEVT-X-003: Infinity disables finite cap for getMaxListeners");

var savedDef = events.defaultMaxListeners;
var descDef = Object.getOwnPropertyDescriptor(events, "defaultMaxListeners");
var sawThrow = false;
var threwRange = false;
try {
    events.defaultMaxListeners = -1;
} catch (e) {
    sawThrow = true;
    threwRange = e instanceof RangeError;
}
events.defaultMaxListeners = savedDef;
if (descDef && typeof descDef.set === "function" && sawThrow) {
    assert(threwRange, "NEVT-X-004: invalid defaultMaxListeners throws RangeError");
}

var eeRange = new EventEmitter();
var threwSet = false;
try {
    eeRange.setMaxListeners(-1);
} catch (e2) {
    threwSet = e2 instanceof RangeError;
}
assert(threwSet, "NEVT-X-004: setMaxListeners with invalid n throws RangeError");

runAsyncEandX()
    .then(function () {
        __jacDone();
    })
    .catch(function (e) {
        console.error("FAIL: NEVT-E/X async: " + e);
        __reg.bump(); __jacDone();
    });
