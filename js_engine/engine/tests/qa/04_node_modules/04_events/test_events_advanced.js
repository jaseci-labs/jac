// NODE_EVENTS_COMPREHENSIVE_TEST_PLAN.md — ECG-5: events.on, addAbortListener, EventTarget helpers, EventEmitterAsyncResource (NEVT-A-006..008, NEVT-B-*, NEVT-R-*)

var events = require("events");
var EventEmitter = events.EventEmitter || events;

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/04_events/test_events_advanced.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }
function assertDeep(actual, expected, msg) { __reg.assertDeep(actual, expected, msg); }

async function main() {
    // --- NEVT-A-006 / A-007: events.on async iterator ---
    if (typeof events.on === "function") {
        var eeOn = new EventEmitter();
        setImmediate(function () {
            eeOn.emit("foo", "bar");
            eeOn.emit("foo", 42);
        });
        var out = [];
        var asyncIt = events.on(eeOn, "foo")[Symbol.asyncIterator]();
        var n1 = await asyncIt.next();
        var n2 = await asyncIt.next();
        out.push(n1.value, n2.value);
        assertEq(n1.done, false, "NEVT-A-006: first async iteration not done");
        assertDeep(out, [["bar"], [42]], "NEVT-A-006: on() yields arrays of emitted arguments per event");

        var eeErrOn = new EventEmitter();
        setImmediate(function () {
            eeErrOn.emit("error", new Error("iter-err"));
        });
        var threwIter = false;
        try {
            var it2 = events.on(eeErrOn, "ok")[Symbol.asyncIterator]();
            await it2.next();
        } catch (e) {
            threwIter = e instanceof Error;
        }
        assert(threwIter, "NEVT-A-007: events.on iterator propagates error emissions");
    }

    // --- NEVT-B-001 / B-002: addAbortListener ---
    if (typeof events.addAbortListener === "function" && typeof AbortController === "function") {
        var acB = new AbortController();
        var ran = false;
        var disp = events.addAbortListener(acB.signal, function () {
            ran = true;
        });
        acB.abort();
        assert(ran, "NEVT-B-001: addAbortListener runs on abort");
        assertEq(typeof disp[Symbol.dispose], "function", "NEVT-B-002: addAbortListener returns disposable");
    }

    // --- NEVT-B-003: getEventListeners on EventTarget (listenerCount(et) is Node-version-dependent) ---
    if (typeof EventTarget !== "undefined" && typeof events.getEventListeners === "function") {
        var et = new EventTarget();
        function h() {}
        et.addEventListener("ev", h);
        var gl = events.getEventListeners(et, "ev");
        assertEq(gl.length, 1, "NEVT-B-003: getEventListeners returns EventTarget handlers");
    }

    // --- NEVT-R-* EventEmitterAsyncResource ---
    if (typeof events.EventEmitterAsyncResource === "function") {
        var EEAR = events.EventEmitterAsyncResource;
        var ear = new EEAR({ name: "NEVT-R-test" });
        assert(ear instanceof EventEmitter, "NEVT-R-001: EventEmitterAsyncResource is instanceof EventEmitter");
        assertEq(typeof ear.asyncId, "number", "NEVT-R-002: asyncId is number");
        assertEq(typeof ear.triggerAsyncId, "number", "NEVT-R-002: triggerAsyncId is number");
        assert(ear.asyncResource, "NEVT-R-002: asyncResource object exists");
        assertEq(typeof ear.emitDestroy, "function", "NEVT-R-002: emitDestroy exists");
        ear.emitDestroy();
    }

    __jacDone();
}

main().catch(function (e) {
    console.error("FAIL: NEVT advanced events: " + e);
    __reg.bump(); __jacDone();
});
__jacDone();
