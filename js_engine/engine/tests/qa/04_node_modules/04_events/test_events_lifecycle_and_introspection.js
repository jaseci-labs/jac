// NODE_EVENTS_COMPREHENSIVE_TEST_PLAN.md — ECG-2: lifecycle meta-events + introspection (NEVT-L-*, NEVT-I-*)

var events = require("events");
var EventEmitter = events.EventEmitter || events;

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase("regression/04_node_modules/04_events/test_events_lifecycle_and_introspection.js");
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }

function assert(cond, msg) { __reg.assert(cond, msg); }
function assertEq(actual, expected, msg) { __reg.assertEq(actual, expected, msg); }

// --- NEVT-L-001: newListener runs before insertion and can prepend ---
// (Use a guard + on('newListener'), not once('newListener'), so nested newListener
// emissions do not recurse infinitely on minimal EventEmitter shims.)
var eeNl = new EventEmitter();
var orderNl = [];
var nlInserted = false;
eeNl.on("newListener", function (eventName, listener) {
    if (eventName === "event" && !nlInserted) {
        nlInserted = true;
        eeNl.on("event", function () {
            orderNl.push("B");
        });
    }
});
eeNl.on("event", function () {
    orderNl.push("A");
});
eeNl.emit("event");
assertEq(orderNl.join(","), "B,A", "NEVT-L-001: newListener can register listeners that run before the pending one");

// --- NEVT-L-002: removeListener fires after removal with original function for once ---
var eeRmMeta = new EventEmitter();
var sawRemove = null;
function origOnce() {}
eeRmMeta.on("removeListener", function (ev, fn) {
    if (ev === "z") {
        sawRemove = fn;
    }
});
eeRmMeta.once("z", origOnce);
eeRmMeta.off("z", origOnce);
assertEq(sawRemove, origOnce, "NEVT-L-002: removeListener receives original listener for once()");

// --- NEVT-L-003 / L-004 / L-005 / L-006 / L-008 ---
var eeOff = new EventEmitter();
var offCalls = 0;
function offFn() {
    offCalls++;
}
eeOff.on("off_evt", offFn);
eeOff.emit("off_evt");
eeOff.off("off_evt", offFn);
eeOff.emit("off_evt");
assertEq(offCalls, 1, "NEVT-L-003: off removes listener like removeListener");

function pong() {}
var eeDup = new EventEmitter();
eeDup.on("ping", pong);
eeDup.once("ping", pong);
eeDup.removeListener("ping", pong);
var pingCalls = 0;
eeDup.on("ping", function () {
    pingCalls++;
});
eeDup.emit("ping");
eeDup.emit("ping");
assertEq(pingCalls, 2, "NEVT-L-004: removeListener removes most recently added duplicate instance");

var eeEmit = new EventEmitter();
var logEmit = [];
function cbA() {
    logEmit.push("A");
    eeEmit.removeListener("event", cbB);
}
function cbB() {
    logEmit.push("B");
}
eeEmit.on("event", cbA);
eeEmit.on("event", cbB);
eeEmit.emit("event");
assertEq(logEmit.join(","), "A,B", "NEVT-L-005: removeListener during emit does not skip snapshot listeners");
logEmit.length = 0;
eeEmit.emit("event");
assertEq(logEmit.join(","), "A", "NEVT-L-005: listener removed after emit takes effect on next emit");

var eeAll = new EventEmitter();
eeAll.on("a", function () {});
eeAll.on("a", function () {});
eeAll.on("b", function () {});
eeAll.removeAllListeners("a");
assertEq(eeAll.listenerCount("a"), 0, "NEVT-L-006: removeAllListeners(event) clears that event");
assertEq(eeAll.listenerCount("b"), 1, "NEVT-L-006: removeAllListeners leaves other events");
eeAll.removeAllListeners();
assertEq(eeAll.listenerCount("b"), 0, "NEVT-L-006: removeAllListeners() clears remaining events");

var eeNoop = new EventEmitter();
eeNoop.off("missing", function () {});
assertEq(eeNoop.listenerCount("missing"), 0, "NEVT-L-008: off on unknown event is no-op");

// --- NEVT-I-* introspection ---
var sym = Symbol("nevt-i-001");
var eeI = new EventEmitter();
eeI.on("foo", function () {});
eeI.on("bar", function () {});
eeI.on(sym, function () {});
var names = eeI.eventNames();
assert(names.indexOf("foo") >= 0 && names.indexOf("bar") >= 0, "NEVT-I-001: eventNames includes string events");
if (typeof Object.getOwnPropertySymbols === "function") {
    var hasSym = false;
    var si = 0;
    while (si < names.length) {
        if (names[si] === sym) {
            hasSym = true;
        }
        si = si + 1;
    }
    assert(hasSym, "NEVT-I-001: eventNames includes symbol keys when getOwnPropertySymbols exists");
}

var eeCopy = new EventEmitter();
function fCopy() {}
eeCopy.on("e", fCopy);
var ls = eeCopy.listeners("e");
ls.push(function () {});
assertEq(eeCopy.listenerCount("e"), 1, "NEVT-I-002: listeners() returns a copy mutating it does not affect emitter");

var eeRaw = new EventEmitter();
function origRaw() {}
eeRaw.once("log", origRaw);
var raw = eeRaw.rawListeners("log");
assertEq(raw.length, 1, "NEVT-I-003: rawListeners includes once wrapper");
assert(raw[0] !== origRaw, "NEVT-I-003: rawListeners once entry is not identical to original function");
assertEq(raw[0].listener, origRaw, "NEVT-I-003: once wrapper exposes .listener to original");

assertEq(eeRaw.listeners("log")[0], origRaw, "NEVT-I-002: listeners() returns underlying function for once");

assertEq(events.listenerCount(eeCopy, "e"), 1, "NEVT-I-006: events.listenerCount matches instance.listenerCount");

if (typeof eeCopy.listenerCount === "function" && eeCopy.listenerCount.length >= 2) {
    var eeLc = new EventEmitter();
    function fTwice() {}
    eeLc.on("e2", fTwice);
    eeLc.on("e2", fTwice);
    assertEq(eeLc.listenerCount("e2", fTwice), 2, "NEVT-I-005: listenerCount(event, fn) counts matching registrations");
}

if (typeof events.getEventListeners === "function") {
    var eeG = new EventEmitter();
    function gFn() {}
    eeG.on("foo", gFn);
    var gl = events.getEventListeners(eeG, "foo");
    assert(Array.isArray(gl), "NEVT-I-007: getEventListeners returns array");
    assertEq(gl.length, 1, "NEVT-I-007: getEventListeners length matches listeners");
    assertEq(gl[0], gFn, "NEVT-I-007: getEventListeners matches listener identity");
}

__jacDone();
