// CHP-001..CHP-012: spawnSync / execFileSync
var cp = require("child_process");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase(
    "regression/04_node_modules/26_child_process/test_child_process_spawn_sync.js"
);
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }
function assert(cond, msg) { __reg.assert(cond, msg); }

var r = cp.spawnSync("/bin/echo", ["hello"]);
assert(r.status === 0, "CHP-001: spawnSync status 0");
assert(String(r.stdout).trim() === "hello", "CHP-002: spawnSync stdout");

var r2 = cp.spawnSync("/bin/sh", ["-c", "echo one && echo two >&2"]);
assert(r2.status === 0, "CHP-003: shell spawnSync status");
assert(String(r2.stdout).indexOf("one") >= 0, "CHP-004: shell stdout");
assert(String(r2.stderr).indexOf("two") >= 0, "CHP-005: shell stderr");

var r3 = cp.spawnSync("/bin/echo", ["stdin-test"], { input: "ignored\n" });
assert(r3.status === 0, "CHP-006: spawnSync with input option");
assert(String(r3.stdout).trim() === "stdin-test", "CHP-007: spawnSync input ignored by echo");

var bad = cp.spawnSync("/no/such/binary", []);
assert(bad.status === 127 || bad.status === null, "CHP-008: missing binary status");

var ef = cp.execFileSync("/bin/echo", ["file-arg"]);
assert(String(ef).trim() === "file-arg", "CHP-009: execFileSync");

var pidOk = typeof r.pid === "number" && r.pid > 0;
assert(pidOk, "CHP-010: spawnSync pid");

assert(Array.isArray(r.output) || r.output === null || r.output.length >= 0,
    "CHP-011: spawnSync output array shape");

__jacDone();
