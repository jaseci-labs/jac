// CHP-030..CHP-039: async spawn events
var cp = require("child_process");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase(
    "regression/04_node_modules/26_child_process/test_child_process_spawn_async.js"
);
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }
function assert(cond, msg) { __reg.assert(cond, msg); }

var done = false;
var stdout = "";
var stderr = "";
var spawned = false;
var timeoutId = null;

var child = cp.spawn("/bin/sh", ["-c", "echo async-out; echo async-err >&2"]);
assert(typeof child.pid === "number" && child.pid > 0, "CHP-030: spawn pid");

child.on("spawn", function () {
    spawned = true;
});

child.stdout.on("data", function (chunk) {
    stdout = stdout + String(chunk);
});

child.stderr.on("data", function (chunk) {
    stderr = stderr + String(chunk);
});

child.on("exit", function (code) {
    assert(code === 0, "CHP-031: exit code 0");
});

child.on("close", function (code) {
    assert(spawned, "CHP-032: spawn event fired");
    assert(stdout.indexOf("async-out") >= 0, "CHP-033: async stdout");
    assert(stderr.indexOf("async-err") >= 0, "CHP-034: async stderr");
    assert(code === 0, "CHP-035: close code 0");
    done = true;
    if (timeoutId !== null) {
        clearTimeout(timeoutId);
    }
    __jacDone();
});

timeoutId = setTimeout(function () {
    if (!done) {
        assert(false, "CHP-036: async spawn timeout");
        __jacDone();
    }
}, 2000);
