// CHP-020..CHP-028: exec / execSync (shell)
var cp = require("child_process");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase(
    "regression/04_node_modules/26_child_process/test_child_process_exec_sync.js"
);
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }
function assert(cond, msg) { __reg.assert(cond, msg); }

var out = cp.execSync("echo exec-sync");
assert(String(out).trim() === "exec-sync", "CHP-020: execSync stdout");

var threw = false;
try {
    cp.execSync("exit 9");
} catch (e) {
    threw = true;
    assert(e.status === 9 || e.code === 9, "CHP-021: execSync error status");
}
assert(threw, "CHP-022: execSync throws on failure");

var done = false;
cp.exec("echo exec-cb", function (err, stdout, stderr) {
    assert(!err, "CHP-023: exec callback no err");
    assert(String(stdout).trim() === "exec-cb", "CHP-024: exec callback stdout");
    assert(String(stderr) === "", "CHP-025: exec callback stderr empty");
    done = true;
    __jacDone();
});

setTimeout(function () {
    if (!done) {
        assert(false, "CHP-026: exec callback timeout");
        __jacDone();
    }
}, 5000);
