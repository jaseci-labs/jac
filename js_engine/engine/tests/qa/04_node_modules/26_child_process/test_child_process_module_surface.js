// CHP-050..CHP-055: module export surface
var cp = require("node:child_process");
var cpBare = require("child_process");
var mod = require("module");

var __jacHarness = require("../../_harness/regression_case.cjs");
var __reg = __jacHarness.createTestCase(
    "regression/04_node_modules/26_child_process/test_child_process_module_surface.js"
);
var __jacOrigExit = process.exit.bind(process);
function __jacDone() { __reg.finalize(__jacOrigExit); }
function assert(cond, msg) { __reg.assert(cond, msg); }

var names = [
    "spawn", "spawnSync", "exec", "execSync", "execFile", "execFileSync",
    "fork", "ChildProcess"
];
var i;
for (i = 0; i < names.length; i++) {
    assert(typeof cp[names[i]] !== "undefined", "CHP-050: export " + names[i]);
    assert(typeof cpBare[names[i]] !== "undefined", "CHP-051: bare " + names[i]);
}

assert(mod.isBuiltin("child_process"), "CHP-052: module.isBuiltin('child_process')");
assert(mod.builtinModules.indexOf("child_process") >= 0, "CHP-053: builtinModules");
assert(typeof cp.ChildProcess === "function", "CHP-054: ChildProcess constructor");

__jacDone();
